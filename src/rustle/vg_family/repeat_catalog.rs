//! Node-multiplicity REPEAT CATALOG -- faithful Rust port of the catalog-production
//! core of `bench/vg_repeat_catalog.py` (the O1 over-merge-gate migration,
//! `docs/RETIREMENT_AND_MIGRATION.md` Tier-2 #7, full-port path).
//!
//! This is the piece the repeat-bridge GATE consumes at runtime: per canonical
//! (k,w)-minimizer NODE it produces `multiplicity` (# distinct genes carrying the
//! node), the `cyclic`/`is_repeat` flags, `n_transcripts`, and `softmask_frac`.
//! The gate's keep/cut decision uses the fixed `M_OP = 5` threshold on the node
//! multiplicities (a family edge is CUT iff every shared node has multiplicity
//! `>= M_OP`); this module builds exactly those multiplicities.
//!
//! PORTED (the Python is ground truth; line refs are `bench/vg_repeat_catalog.py`):
//!   * `load_skeletons`  (:80)  -> `parse_skeletons` / `load_skeletons`;
//!   * `dn_exons`        (:90)  -> `dn_exons` (intron -> exon COMPLEMENT + coord convention);
//!   * the VG build loop (:245-289) + node-section output (:598-604) -> `NodeCatalog`.
//!   * `minimizers` is REUSED from `super::minimizers` (already byte-exact, commit 18adb6e).
//!
//! DEFERRED (NOT gate-runtime -- calibration/evaluation, see the report):
//!   * the `M_GRID` masking-oracle sweep (:397), the `KFOLDS` component CV (:431-478),
//!     and the "# SECTION edges (eval population)" block (:605-618). Those select /
//!     report `M_OP` and compute AUC / tp_recall / genuine_cut_rate against the DNA
//!     truth population; the gate consumes the FIXED `M_OP = 5` + these node
//!     multiplicities, not the CV.
//!
//! GENOME ACCESS: `GenomeIndex` (`genome.rs`) UPPERCASES bases, which would destroy
//! the soft-mask (lowercase) that `minimizers` reads for `softmask_frac`; so this
//! module carries a minimal CASE-CARRYING indexed-FASTA reader (`IndexedFasta`) that
//! returns the reference bytes verbatim, exactly like `pysam.FastaFile.fetch`.
//!
//! Verified byte-identical to the shipped Python against a golden fixture
//! (`testdata/repeat_catalog_fixture.json`, generated by
//! `bench/gen_repeat_catalog_fixture.py`, PYTHONHASHSEED=0); see the `#[test]`s.

