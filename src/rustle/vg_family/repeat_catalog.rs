    // ------------------------------------------------------------ unit corners

    #[test]
    fn dn_exons_branches() {
        let mut meta: HashMap<String, (String, i64, i64)> = HashMap::new();
        let mut skel: HashMap<(String, i64, i64), String> = HashMap::new();
        meta.insert("m".into(), ("c".into(), 100, 300));

        // (1) meta miss -> None
        assert_eq!(dn_exons("absent", &meta, &skel), None);

        // (2) skel key absent -> single exon [(start,end)]
        assert_eq!(
            dn_exons("m", &meta, &skel),
            Some(("c".to_string(), vec![(100, 300)]))
        );

        // (3) blank introns -> single exon via the OTHER branch
        skel.insert(("c".into(), 100, 300), "".into());
        assert_eq!(
            dn_exons("m", &meta, &skel),
            Some(("c".to_string(), vec![(100, 300)]))
        );

        // (4) unsorted introns -> sorted complement
        skel.insert(("c".into(), 100, 300), "250-280;120-150".into());
        assert_eq!(
            dn_exons("m", &meta, &skel),
            Some(("c".to_string(), vec![(100, 120), (150, 250), (280, 300)]))
        );

        // (5) leading intron a == start (no leading exon)
        skel.insert(("c".into(), 100, 300), "100-150".into());
        assert_eq!(
            dn_exons("m", &meta, &skel),
            Some(("c".to_string(), vec![(150, 300)]))
        );

        // (6) whole span is intron -> empty exon list
        skel.insert(("c".into(), 100, 300), "100-300".into());
        assert_eq!(dn_exons("m", &meta, &skel), Some(("c".to_string(), vec![])));
    }

