/// Reconstruct a de-novo locus's `(chrom, exons)` from its meta coords + skeleton
/// introns (exons = the COMPLEMENT of the introns within `[start, end)`).
///
/// Faithful port of `dn_exons`:
///   * `meta.get(dn)` miss  -> `None` (Python `(None, None)`);
///   * skeleton key absent  -> `Some((chrom, [(start, end)]))` (single exon);
///   * else parse `"a-b;c-d;..."` into intervals, SORT them, and walk the complement:
///     `cur = start`; for each `(a, b)` push `(cur, a)` iff `a > cur`, then `cur = b`;
///     finally push `(cur, end)` iff `end > cur`.
///
/// The blank-introns skeleton (`introns == ""`) and the missing-skeleton case both
/// yield a single `[(start, end)]` exon but via the two distinct Python branches.
pub fn dn_exons(
    dn: &str,
    meta: &HashMap<String, (String, i64, i64)>,
    skel: &HashMap<(String, i64, i64), String>,
) -> Option<(String, Vec<(i64, i64)>)> {
    let (chrom, start, end) = match meta.get(dn) {
        None => return None,
        Some(t) => (t.0.clone(), t.1, t.2),
    };
    let introns = match skel.get(&(chrom.clone(), start, end)) {
        None => return Some((chrom, vec![(start, end)])),
        Some(s) => s,
    };
    let mut iv: Vec<(i64, i64)> = Vec::new();
    if !introns.trim().is_empty() {
        for tok in introns.split(';') {
            // Python: a, b = tok.split("-")
            let mut it = tok.split('-');
            let a: i64 = it
                .next()
                .expect("intron token has a left field")
                .parse()
                .expect("intron start parses");
            let b: i64 = it
                .next()
                .expect("intron token has a right field")
                .parse()
                .expect("intron end parses");
            iv.push((a, b));
        }
    }
    iv.sort();
    let mut exons: Vec<(i64, i64)> = Vec::new();
    let mut cur = start;
    for (a, b) in iv {
        if a > cur {
            exons.push((cur, a));
        }
        cur = b;
    }
    if end > cur {
        exons.push((cur, end));
    }
    Some((chrom, exons))
}

