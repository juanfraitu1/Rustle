/// One "# SECTION nodes (mult>=2)" output row.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct NodeRow {
    /// canonical (k,w)-minimizer value (`node_id`)
    pub node_id: u64,
    /// `multiplicity` = # DISTINCT GENES whose node set contains this node
    pub multiplicity: usize,
    /// `n_genes` -- the Python writes `mult[c]` a second time in this column
    pub n_genes: usize,
    /// `cyclic` -- the node recurs (>= 2 runs) within a single transcript
    pub cyclic: bool,
    /// `is_repeat_m{M_OP}` = `multiplicity >= M_OP` OR `cyclic`
    pub is_repeat: bool,
    /// `n_transcripts` = # transcripts (loci) carrying the node
    pub n_transcripts: usize,
    /// masked-run occurrences (numerator of `softmask_frac`)
    pub softmask_num: u64,
    /// total-run occurrences (denominator of `softmask_frac`)
    pub softmask_den: u64,
}

impl NodeRow {
    /// `softmask_frac` as the raw ratio (unrounded).
    pub fn softmask_frac(&self) -> f64 {
        if self.softmask_den == 0 {
            0.0
        } else {
            self.softmask_num as f64 / self.softmask_den as f64
        }
    }

    /// The exact TSV line Python writes (fields `\t`-joined, no trailing newline).
    pub fn to_tsv(&self) -> String {
        format!(
            "{}\t{}\t{}\t{}\t{}\t{}\t{}",
            self.node_id,
            self.multiplicity,
            self.n_genes,
            self.cyclic as u8,
            self.is_repeat as u8,
            self.n_transcripts,
            format_softmask(self.softmask_num, self.softmask_den),
        )
    }
}

/// `round(num/den, 4)` formatted exactly as Python `str(float)` (drops trailing
/// zeros, always keeps `".0"`). Rounds the actual `f64` (NOT the rational a/b): for
/// these dyadic doubles no exact 4-decimal tie exists, so Rust's correctly-rounded
/// `{:.4}` matches Python's `format(x, ".4f")`, which equals `str(round(x, 4))`
/// after stripping (verified over all num/den <= 1200). `den == 0` -> `"0.0"`
/// (Python `node_sm.get(c, 0.0)`).
fn format_softmask(num: u64, den: u64) -> String {
    if den == 0 {
        return "0.0".to_string();
    }
    let x = num as f64 / den as f64;
    let s = format!("{:.4}", x); // correctly-rounded 4-decimal, e.g. "0.0063","0.5000","1.0000"
    let trimmed = s.trim_end_matches('0');
    if trimmed.ends_with('.') {
        format!("{}0", trimmed)
    } else {
        trimmed.to_string()
    }
}

/// The canonical-minimizer node-multiplicity catalog over a universe of loci.
///
/// Faithful port of the VG build loop (`:245-289`): each locus contributes its GENE
/// label and its case-carrying spliced sequence; per node (canonical minimizer value)
/// we accumulate the DISTINCT gene set (=> `multiplicity`), the max within-transcript
/// run count (=> `cyclic`), the masked / total run occurrences (=> `softmask_frac`),
/// and the transcript count (=> `n_transcripts`). All accumulators are commutative,
/// so the catalog is independent of locus order.
#[derive(Default, Debug)]
pub struct NodeCatalog {
    /// node -> # distinct genes (multiplicity)
    mult: HashMap<u64, usize>,
    /// node -> max #runs within a single transcript (cyclic iff >= 2)
    cyc_max: HashMap<u64, usize>,
    /// node -> masked-run occurrences
    lc_occ: HashMap<u64, u64>,
    /// node -> total run occurrences
    tot_occ: HashMap<u64, u64>,
    /// node -> # transcripts carrying it
    n_tx: HashMap<u64, usize>,
}

impl NodeCatalog {
    /// Build the catalog from `(gene, case_carrying_sequence)` items -- one per
    /// gene-assigned family-universe locus. Loci with `seq.len() < k` are skipped
    /// (Python `if len(s) < K: continue`, redundant with `minimizers` but preserved).
    pub fn build<'a>(loci: impl IntoIterator<Item = (&'a str, &'a [u8])>) -> Self {
        let mut node_genes: HashMap<u64, HashSet<&'a str>> = HashMap::new();
        let mut cat = NodeCatalog::default();
        for (g, s) in loci {
            if s.len() < MINIMIZER_K {
                continue;
            }
            let runs = minimizers(s, MINIMIZER_K, MINIMIZER_W);
            // per-transcript run counts (for the cyclic flag) + the distinct-node set
            let mut loc_runcount: HashMap<u64, usize> = HashMap::new();
            let mut seen: HashSet<u64> = HashSet::new();
            for (val, mk) in &runs {
                node_genes.entry(*val).or_default().insert(g);
                seen.insert(*val);
                *loc_runcount.entry(*val).or_default() += 1;
                *cat.tot_occ.entry(*val).or_default() += 1;
                if *mk {
                    *cat.lc_occ.entry(*val).or_default() += 1;
                }
            }
            for val in &seen {
                *cat.n_tx.entry(*val).or_default() += 1;
                let rc = loc_runcount[val];
                let cm = cat.cyc_max.entry(*val).or_default();
                if rc > *cm {
                    *cm = rc;
                }
            }
        }
        // mult[c] = len(node_genes[c])
        cat.mult = node_genes.into_iter().map(|(c, gs)| (c, gs.len())).collect();
        cat
    }

    /// `multiplicity` of a node (# distinct genes), or 0 if absent. Gate input.
    pub fn multiplicity(&self, node_id: u64) -> usize {
        self.mult.get(&node_id).copied().unwrap_or(0)
    }

    /// Whether a node is a library-free REPEAT at `M_OP` (`multiplicity >= M_OP`
    /// OR cyclic). The gate CUTS a family edge iff every shared node is a repeat.
    pub fn is_repeat(&self, node_id: u64) -> bool {
        self.multiplicity(node_id) >= M_OP || self.cyclic(node_id)
    }

    /// Whether a node recurs (>= 2 runs) within a single transcript (tandem/cyclic).
    pub fn cyclic(&self, node_id: u64) -> bool {
        self.cyc_max.get(&node_id).copied().unwrap_or(0) >= 2
    }

    /// Total number of nodes in the catalog (all multiplicities).
    pub fn n_nodes(&self) -> usize {
        self.mult.len()
    }

    fn row(&self, c: u64) -> NodeRow {
        let m = self.mult[&c];
        let cyc = self.cyclic(c);
        NodeRow {
            node_id: c,
            multiplicity: m,
            n_genes: m,
            cyclic: cyc,
            is_repeat: m >= M_OP || cyc,
            n_transcripts: self.n_tx.get(&c).copied().unwrap_or(0),
            softmask_num: self.lc_occ.get(&c).copied().unwrap_or(0),
            softmask_den: self.tot_occ.get(&c).copied().unwrap_or(0),
        }
    }

    /// The "# SECTION nodes (mult>=2)" rows, sorted by `(-multiplicity, node_id)`
    /// (descending multiplicity, then ascending node id) exactly as the Python writer.
    pub fn node_rows(&self) -> Vec<NodeRow> {
        let mut codes: Vec<u64> = self
            .mult
            .iter()
            .filter(|(_, &m)| m >= 2)
            .map(|(&c, _)| c)
            .collect();
        codes.sort_by(|&a, &b| {
            let (ma, mb) = (self.mult[&a], self.mult[&b]);
            mb.cmp(&ma).then(a.cmp(&b))
        });
        codes.into_iter().map(|c| self.row(c)).collect()
    }

    /// The full "# SECTION nodes (mult>=2)" text (the two Python header lines + one
    /// line per `node_rows()` row, each terminated by `\n`) -- byte-identical to the
    /// section `bench/vg_repeat_catalog.py` writes at lines 599-604.
    pub fn node_section_text(&self) -> String {
        let mut out = String::new();
        out.push_str("# SECTION nodes (mult>=2)\n");
        out.push_str(&format!(
            "node_id\tmultiplicity\tn_genes\tcyclic\tis_repeat_m{}\tn_transcripts\tsoftmask_frac\n",
            M_OP
        ));
        for row in self.node_rows() {
            out.push_str(&row.to_tsv());
            out.push('\n');
        }
        out
    }
}

/// Runtime gate DRIVER: build the node catalog from the genome + loaders' outputs,
/// mirroring `bench/vg_repeat_catalog.py:243-289`. Iterates `sorted(gene_of_dn.keys())`,
/// projects each locus to `(chrom, exons)` via `dn_exons`, fetches the case-carrying
/// spliced sequence, and accumulates into a `NodeCatalog`. (Order-independent, so the
/// sort only mirrors Python; skipped loci: no gene, no exons, fetch failure, `len < k`.)
pub fn build_catalog_from_genome(
    fa: &IndexedFasta,
    meta: &HashMap<String, (String, i64, i64)>,
    skel: &HashMap<(String, i64, i64), String>,
    gene_of_dn: &HashMap<String, String>,
) -> NodeCatalog {
    let mut loci: Vec<&String> = gene_of_dn.keys().collect();
    loci.sort();
    let mut items: Vec<(String, Vec<u8>)> = Vec::new();
    for dn in loci {
        let g = match gene_of_dn.get(dn) {
            Some(g) if !g.is_empty() => g.clone(),
            _ => continue,
        };
        let (chrom, exons) = match dn_exons(dn, meta, skel) {
            Some(x) => x,
            None => continue,
        };
        let s = match locus_exon_sequence(fa, &chrom, &exons) {
            Some(s) => s,
            None => continue,
        };
        if s.len() < MINIMIZER_K {
            continue;
        }
        items.push((g, s));
    }
    NodeCatalog::build(items.iter().map(|(g, s)| (g.as_str(), s.as_slice())))
}

