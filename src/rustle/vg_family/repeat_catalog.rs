/// Parse the denovo-skeletons TSV text into `{(chrom, start, end) -> introns_string}`.
///
/// Faithful port of `load_skeletons`: skips the header row (`next(fh)`), keys on the
/// first three tab fields `(f[0], int(f[1]), int(f[2]))`, value = the `introns` field
/// `f[5]` (empty string for single-exon skeletons). Columns:
/// `chrom  start  end  n_exon  n_reads  introns`.
pub fn parse_skeletons(text: &str) -> HashMap<(String, i64, i64), String> {
    let mut skel = HashMap::new();
    let mut lines = text.lines();
    lines.next(); // header
    for ln in lines {
        // Python: f = ln.rstrip("\n").split("\t"); skel[(f0,int f1,int f2)] = f5
        let f: Vec<&str> = ln.split('\t').collect();
        if f.len() < 6 {
            continue; // well-formed rows always carry 6 cols (introns may be empty)
        }
        let start: i64 = match f[1].parse() {
            Ok(v) => v,
            Err(_) => continue,
        };
        let end: i64 = match f[2].parse() {
            Ok(v) => v,
            Err(_) => continue,
        };
        skel.insert((f[0].to_string(), start, end), f[5].to_string());
    }
    skel
}

/// Read + parse the denovo-skeletons TSV file (see `parse_skeletons`).
pub fn load_skeletons(path: &str) -> io::Result<HashMap<(String, i64, i64), String>> {
    Ok(parse_skeletons(&std::fs::read_to_string(path)?))
}

