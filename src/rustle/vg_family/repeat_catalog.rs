/// Headline operating multiplicity threshold. `bench/vg_repeat_catalog.py:72  M_OP = 5`.
/// A node is a library-free REPEAT iff `multiplicity >= M_OP` OR it is `cyclic`; the
/// repeat-bridge gate CUTS a family edge iff every shared node is a repeat at `M_OP`.
pub const M_OP: usize = 5;

