// ===========================================================================

/// The copy-vs-allele DEMOTE DECISION for a single gene.
///
/// Faithful port of the nested `demote_gene` in the APPLY stage:
/// ```python
/// def demote_gene(g):
///     a = allele.get(g)
///     return a is not None and a["balanced_frac"] >= 0.90 and a["copy_like"] <= 0.10
/// ```
/// A gene absent from `allele` returns `false` (Python `a is None`). The
/// comparison operators are load-bearing and preserved EXACTLY: `balanced_frac`
/// is `>=` (inclusive) `DEMOTE_BAL_MIN`, `copy_like` is `<=` (inclusive)
/// `DEMOTE_COPY_MAX`. It closes over ONLY the `load_allele` dict + the two scalar
/// thresholds -- no catalog / DNA / genome input -- so the port is self-contained.
pub fn demote_gene(allele: &HashMap<String, AlleleSignal>, gene: &str) -> bool {
    match allele.get(gene) {
        Some(a) => a.balanced_frac >= DEMOTE_BAL_MIN && a.copy_like <= DEMOTE_COPY_MAX,
        None => false,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    // ---------------------------------------------------------------- unit tests

    fn sig(bal: f64, het: f64, cop: f64, maf: f64) -> AlleleSignal {
        AlleleSignal { balanced_frac: bal, het_risk: het, copy_like: cop, med_maf: maf }
    }

    #[test]
    fn demote_gene_boundaries_and_missing() {
        let mut a: HashMap<String, AlleleSignal> = HashMap::new();
        a.insert("HIT".into(), sig(0.95, 1.0, 0.05, 0.46)); // clear demote
        a.insert("EXACT".into(), sig(0.90, 1.0, 0.10, 0.5)); // both boundaries inclusive
        a.insert("BAL_LOW".into(), sig(0.8999, 1.0, 0.05, 0.5)); // bal just below
        a.insert("COPY_HIGH".into(), sig(0.95, 1.0, 0.1001, 0.5)); // copy just above
        assert!(demote_gene(&a, "HIT"));
        assert!(demote_gene(&a, "EXACT")); // >= and <= are inclusive
        assert!(!demote_gene(&a, "BAL_LOW"));
        assert!(!demote_gene(&a, "COPY_HIGH"));
        assert!(!demote_gene(&a, "ABSENT")); // a is None -> false
    }

    #[test]
    fn pair_core_max_aggregation_and_skips() {
        // gene map: two genes A/B via DN1/DN2; DN3 same-gene as DN1 (A); DN9 unmapped.
        let mut god: HashMap<String, String> = HashMap::new();
        god.insert("DN1".into(), "A".into());
        god.insert("DN2".into(), "B".into());
        god.insert("DN3".into(), "A".into()); // A--A (ga==gb) skip
        // DN9 deliberately absent -> missing skip
        let text = "\
a\tb\tcore_recip
DN1\tDN2\t0.20
DN2\tDN1\t0.50
DN1\tDN2\t0.31
DN1\tDN3\t0.99
DN1\tDN9\t0.77";
        let pc = load_pair_core_str(&god, text);
        // A/B present with MAX = 0.50 (order-invariant); A/A and A/<missing> absent.
        assert_eq!(pc.len(), 1);
        let k = gene_pair_key("A", "B");
        assert!((pc[&k] - 0.50).abs() < 1e-12);
        assert!(!pc.contains_key(&gene_pair_key("A", "A")));
    }

    #[test]
    fn universal_aln_empty_is_none() {
        let text = "\
gene_a\tgene_b\tdn_a\tdn_b\tcls\tin_ep\tcore\taln_len\taln_frac
GB\tGA\tx\ty\ttruthbar\t1\t0.3\t0\t0.1234
GC\tGD\tx\ty\ttruthbar\t0\t0.2\t0\t";
        let d = load_universal_aln_str(text);
        assert_eq!(d[&gene_pair_key("GA", "GB")], Some(0.1234)); // key is sorted
        assert_eq!(d[&gene_pair_key("GC", "GD")], None); // empty -> None
    }

    // ---------------------------------------------------------------- parity test

    /// Byte-parity against the golden fixture emitted by
    /// `bench/gen_edge_oracle_fixture.py` from the shipped Python loaders +
    /// `demote_gene`. Reports the first mismatch it finds.
    #[test]
    fn edge_oracle_parity() {
        let raw = include_str!("testdata/edge_oracle_fixture.json");
        let fx: serde_json::Value = serde_json::from_str(raw).expect("parse fixture json");

        // thresholds must match the Python constants.
        let th = &fx["thresholds"];
        assert!(
            (th["demote_bal_min"].as_f64().unwrap() - DEMOTE_BAL_MIN).abs() < 1e-12,
            "DEMOTE_BAL_MIN drift"
        );
        assert!(
            (th["demote_copy_max"].as_f64().unwrap() - DEMOTE_COPY_MAX).abs() < 1e-12,
            "DEMOTE_COPY_MAX drift"
        );

        // ---- (a) load_pair_core parity (incl. MAX-aggregation + both skip paths) ----
        let pcx = &fx["pair_core"];
        let god: HashMap<String, String> = pcx["gene_of_dn"]
            .as_object()
            .unwrap()
            .iter()
            .map(|(k, v)| (k.clone(), v.as_str().unwrap().to_string()))
            .collect();
        let pc = load_pair_core_str(&god, pcx["edges_tsv"].as_str().unwrap());
        let golden_pc: HashMap<(String, String), f64> = pcx["golden"]
            .as_array()
            .unwrap()
            .iter()
            .map(|e| {
                let a = e.as_array().unwrap();
                (
                    (a[0].as_str().unwrap().to_string(), a[1].as_str().unwrap().to_string()),
                    a[2].as_f64().unwrap(),
                )
            })
            .collect();
        assert_eq!(
            pc.len(),
            golden_pc.len(),
            "PAIR_CORE size mismatch: rust {} vs python {}",
            pc.len(),
            golden_pc.len()
        );
        for (k, gv) in &golden_pc {
            let got = pc.get(k).unwrap_or_else(|| {
                panic!("PAIR_CORE missing pair {k:?} (python core {gv})")
            });
            assert!(
                (got - gv).abs() <= 1e-12,
                "PAIR_CORE MISMATCH {k:?}: rust {got} != python {gv}"
            );
        }
        // diversity guards (fixture stays representative of the aggregation/skip paths)
        let div = &pcx["diversity"];
        assert!(div["n_pairs"].as_u64().unwrap() >= 8, "too few pair_core pairs");
        assert!(div["multi_edge_pairs"].as_u64().unwrap() >= 3, "too few multi-edge (MAX) pairs");
        assert!(div["max_not_first"].as_u64().unwrap() >= 1, "no order-sensitive MAX pair");
        assert!(div["skipped_missing"].as_u64().unwrap() >= 1, "no gene_of_dn-missing skip");
        assert!(div["skipped_same_gene"].as_u64().unwrap() >= 1, "no ga==gb skip");

        // ---- (b) load_universal_aln parity (incl. empty -> None) ----
        let ux = &fx["universal_aln"];
        let ua = load_universal_aln_str(ux["tsv"].as_str().unwrap());
        let mut n_empty = 0usize;
        let mut golden_ua: HashMap<(String, String), Option<f64>> = HashMap::new();
        for e in ux["golden"].as_array().unwrap() {
            let a = e.as_array().unwrap();
            let k = (a[0].as_str().unwrap().to_string(), a[1].as_str().unwrap().to_string());
            let v = if a[2].is_null() {
                n_empty += 1;
                None
            } else {
                Some(a[2].as_f64().unwrap())
            };
            golden_ua.insert(k, v);
        }
        assert_eq!(ua.len(), golden_ua.len(), "UNIVERSAL_ALN size mismatch");
        for (k, gv) in &golden_ua {
            let got = ua
                .get(k)
                .unwrap_or_else(|| panic!("UNIVERSAL_ALN missing pair {k:?}"));
            match (got, gv) {
                (None, None) => {}
                (Some(x), Some(y)) => assert!(
                    (x - y).abs() <= 1e-12,
                    "UNIVERSAL_ALN MISMATCH {k:?}: rust {x} != python {y}"
                ),
                _ => panic!("UNIVERSAL_ALN None/Some MISMATCH {k:?}: rust {got:?} != python {gv:?}"),
            }
        }
        assert!(n_empty >= 1, "fixture has no empty(None) universal_aln row");

        // ---- (c) load_allele parity (per-field) ----
        let ax = &fx["allele"];
        let al = load_allele_str(ax["tsv"].as_str().unwrap());
        let golden_al = ax["golden"].as_object().unwrap();
        assert_eq!(al.len(), golden_al.len(), "ALLELE size mismatch");
        for (g, gv) in golden_al {
            let got = al.get(g).unwrap_or_else(|| panic!("ALLELE missing gene {g}"));
            let want = AlleleSignal {
                balanced_frac: gv["balanced_frac"].as_f64().unwrap(),
                het_risk: gv["het_risk"].as_f64().unwrap(),
                copy_like: gv["copy_like"].as_f64().unwrap(),
                med_maf: gv["med_maf"].as_f64().unwrap(),
            };
            assert!(
                (got.balanced_frac - want.balanced_frac).abs() <= 1e-12
                    && (got.het_risk - want.het_risk).abs() <= 1e-12
                    && (got.copy_like - want.copy_like).abs() <= 1e-12
                    && (got.med_maf - want.med_maf).abs() <= 1e-12,
                "ALLELE MISMATCH {g}: rust {got:?} != python {want:?}"
            );
        }

        // ---- (d) demote_gene parity (diverse; boundary cases at each threshold) ----
        let dx = &fx["demote"];
        let allele: HashMap<String, AlleleSignal> = dx["allele"]
            .as_object()
            .unwrap()
            .iter()
            .map(|(g, v)| {
                (
                    g.clone(),
                    AlleleSignal {
                        balanced_frac: v["balanced_frac"].as_f64().unwrap(),
                        het_risk: v["het_risk"].as_f64().unwrap(),
                        copy_like: v["copy_like"].as_f64().unwrap(),
                        med_maf: v["med_maf"].as_f64().unwrap(),
                    },
                )
            })
            .collect();
        let mut n_demote = 0usize;
        let mut n_true = 0usize;
        for case in dx["cases"].as_array().unwrap() {
            let gene = case["gene"].as_str().unwrap();
            let expect = case["expect"].as_bool().unwrap();
            let got = demote_gene(&allele, gene);
            assert_eq!(
                got, expect,
                "DEMOTE MISMATCH gene '{gene}': rust {got} != python {expect}"
            );
            n_demote += 1;
            if expect {
                n_true += 1;
            }
        }
        assert!(n_demote >= 8, "too few demote cases: {n_demote}");
        assert!(n_true >= 1, "no positive demote case");
        assert!(n_demote - n_true >= 1, "no negative demote case");

        eprintln!(
            "edge_oracle parity: pair_core {} pairs OK (multi-edge {}, max-not-first {}, skip-missing {}, skip-same {}); \
             universal_aln {} rows OK ({} None); allele {} genes OK; demote {} cases OK ({} demoted)",
            golden_pc.len(),
            div["multi_edge_pairs"], div["max_not_first"], div["skipped_missing"], div["skipped_same_gene"],
            golden_ua.len(), n_empty, golden_al.len(), n_demote, n_true
        );
    }
}
