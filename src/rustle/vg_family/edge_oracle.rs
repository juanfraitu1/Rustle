//! O1 RNA-only EDGE-ORACLE loaders + the allele-demote decision (Rust port).
//!
//! Faithful Rust port of the pieces of the `E_r` RNA-homology edge oracle that
//! the family-definition DRIVER consumes, the next increment of the Python->Rust
//! migration (`docs/RETIREMENT_AND_MIGRATION.md` Tier-1 #4). Sits on top of the
//! already-ported loaders (`family_loaders.rs`, which supplies `gene_of_dn` via
//! `build_genes_dict`) and the `distinct_loci`/`refine_families` operators in
//! `family_definition.rs`.
//!
//! Ported functions (the Python source is the SPEC; line refs are the shipped
//! file `bench/rna_only_edge_oracle.py`):
//!   * `load_pair_core`     (:103)  -- EDGES_TSV -> gene-pair -> MAX `core_recip`
//!     over the DN-graph edges of that pair (the whole-transcript reciprocal
//!     homology weight the gamma operator sees). Preserves EXACTLY the max-
//!     aggregation, the `ga != gb` skip, and the `gene_of_dn`-missing skip.
//!   * `load_universal_aln` (:548)  -- SHAREDLEN_UNIV_TSV -> gene-pair ->
//!     `aln_frac` (`""` -> `None`), the leakage-free universal shared-exon cache.
//!   * `load_allele`        (:182)  -- A1_TSV -> gene -> the family-level RNA
//!     allele signal (`balanced_frac` / `het_risk` / `copy_like` / `med_maf`).
//!   * `demote_gene`        (:1235) -- the copy-vs-allele DEMOTE DECISION: a gene
//!     whose every variant position is a balanced ~50/50 het (`balanced_frac >=
//!     0.90` AND `copy_like <= 0.10`) is declared ALLELIC, not multi-copy. It
//!     pulls in ONLY the `load_allele` dict + the two scalar thresholds (nothing
//!     from the catalog / DNA), so the port is self-contained.
//!
//! FILE-PATH CONSTANTS (Python `rna_only_edge_oracle.py`, joined onto `BENCH =`
//! the `bench/` dir):
//!   * EDGES_TSV          = `bench/denovo_family_edges.tsv`   (:81)
//!   * SHAREDLEN_UNIV_TSV = `bench/ri_sharedlen_universal.tsv` (:540)
//!   * A1_TSV             = `bench/a1_read_consensus_o1.tsv`  (:86)
//!
//! Verified byte-identical to the shipped Python loaders + `demote_gene` against
//! a golden fixture (`testdata/edge_oracle_fixture.json`, generated by
//! `bench/gen_edge_oracle_fixture.py`); see the `#[test]`s at the bottom.

use std::collections::HashMap;

/// `balanced_frac >= DEMOTE_BAL_MIN` is one of the two DEMOTE conjuncts: a minor-
/// allele fraction ~0.5 (balanced) is a diploid het, i.e. an allele-as-copy risk.
/// Hard-coded from `rna_only_edge_oracle.py:1237` (`a["balanced_frac"] >= 0.90`);
/// the same constant is mirrored at `family_rna_refine.py:181  DEMOTE_BAL_MIN`.
pub const DEMOTE_BAL_MIN: f64 = 0.90;

/// `copy_like <= DEMOTE_COPY_MAX` is the second DEMOTE conjunct: a `copy_like`
/// near 0 means NOT a ~1/K real copy. Hard-coded from
/// `rna_only_edge_oracle.py:1237` (`a["copy_like"] <= 0.10`); mirrored at
/// `family_rna_refine.py:182  DEMOTE_COPY_MAX`.
pub const DEMOTE_COPY_MAX: f64 = 0.10;

/// Canonical UNORDERED gene-pair key = the Python `frozenset((a, b))`.
///
/// A sorted `(String, String)` tuple: `frozenset({a, b})` is order-independent,
/// and the loaders only ever build/look up a key with this same function, so the
/// sorted tuple is a faithful stand-in. (Python `frozenset((a, a)) == {a}` has a
/// single element; the sorted tuple `(a, a)` is a distinct-but-consistent
/// representation. `load_pair_core` never emits a self-pair (its `ga != gb`
/// guard); `load_universal_aln` has no such guard, but the shipped
/// `ri_sharedlen_universal.tsv` carries no same-gene rows, and a `(a, a)` key can
/// never collide with a cross-pair `(min, max)` where the two genes differ.)
pub fn gene_pair_key(a: &str, b: &str) -> (String, String) {
    if a <= b {
        (a.to_string(), b.to_string())
    } else {
        (b.to_string(), a.to_string())
    }
}

