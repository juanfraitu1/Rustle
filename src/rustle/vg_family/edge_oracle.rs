/// gene-pair -> `aln_frac` from the UNIVERSAL (leakage-free) cache; `""` -> `None`.
///
/// Faithful port of `load_universal_aln`: the header line builds the column-index
/// map (`I = {c: i for i, c in enumerate(h)}`); columns `gene_a`, `gene_b`,
/// `aln_frac`. An empty `aln_frac` string maps to `None`, otherwise `float(af)`.
/// (Last-write-wins on a duplicate gene-pair, matching the Python dict
/// assignment; the shipped cache carries no duplicates.)
pub fn load_universal_aln_str(text: &str) -> HashMap<(String, String), Option<f64>> {
    let mut lines = text.lines();
    let header: Vec<&str> = lines.next().expect("universal header").split('\t').collect();
    let idx: HashMap<&str, usize> = header.iter().enumerate().map(|(i, &c)| (c, i)).collect();
    let (ia, ib, iaf) = (idx["gene_a"], idx["gene_b"], idx["aln_frac"]);
    let mut d: HashMap<(String, String), Option<f64>> = HashMap::new();
    for line in lines {
        let f: Vec<&str> = line.split('\t').collect();
        let k = gene_pair_key(f[ia], f[ib]);
        let af = f[iaf];
        let v = if af.is_empty() {
            None
        } else {
            Some(af.parse::<f64>().expect("aln_frac float"))
        };
        d.insert(k, v);
    }
    d
}

/// Read the SHAREDLEN_UNIV_TSV file and parse it (see `load_universal_aln_str`).
pub fn load_universal_aln(path: &str) -> std::io::Result<HashMap<(String, String), Option<f64>>> {
    Ok(load_universal_aln_str(&std::fs::read_to_string(path)?))
}

