/// The family-level RNA allele signal for one gene (`load_allele` value dict).
/// Minor-allele-fraction ~0.5 => diploid het (allele-as-copy risk); ~1/K => real
/// copy. Consumed by `demote_gene`.
#[derive(Clone, Debug, PartialEq)]
pub struct AlleleSignal {
    pub balanced_frac: f64,
    pub het_risk: f64,
    pub copy_like: f64,
    pub med_maf: f64,
}

/// gene -> `AlleleSignal`. Faithful port of `load_allele`: the header builds the
/// column-index map; columns `gene`, `balanced_frac`, `het_risk`, `copy_like`,
/// `med_maf` (all parsed as `f64`). Last-write-wins per gene (Python dict).
pub fn load_allele_str(text: &str) -> HashMap<String, AlleleSignal> {
    let mut lines = text.lines();
    let header: Vec<&str> = lines.next().expect("allele header").split('\t').collect();
    let idx: HashMap<&str, usize> = header.iter().enumerate().map(|(i, &c)| (c, i)).collect();
    let (ig, ibal, ihet, icop, imaf) = (
        idx["gene"],
        idx["balanced_frac"],
        idx["het_risk"],
        idx["copy_like"],
        idx["med_maf"],
    );
    let mut d: HashMap<String, AlleleSignal> = HashMap::new();
    for line in lines {
        let f: Vec<&str> = line.split('\t').collect();
        d.insert(
            f[ig].to_string(),
            AlleleSignal {
                balanced_frac: f[ibal].parse().expect("balanced_frac float"),
                het_risk: f[ihet].parse().expect("het_risk float"),
                copy_like: f[icop].parse().expect("copy_like float"),
                med_maf: f[imaf].parse().expect("med_maf float"),
            },
        );
    }
    d
}

/// Read the A1_TSV file and parse it (see `load_allele_str`).
pub fn load_allele(path: &str) -> std::io::Result<HashMap<String, AlleleSignal>> {
    Ok(load_allele_str(&std::fs::read_to_string(path)?))
}

