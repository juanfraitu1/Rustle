/// gene-pair -> MAX `core_recip` over the DN-graph edges of that pair.
///
/// Faithful port of `load_pair_core` operating on the raw EDGES_TSV text (the
/// file version reads the file and delegates here). The header line is skipped;
/// every subsequent line is `a\tb\tcore_recip` (POSITIONAL 3-column split, as in
/// the Python `a, b, c = ln.rstrip("\n").split("\t")`). For each edge:
///   * `ga = gene_of_dn.get(a)`, `gb = gene_of_dn.get(b)`;
///   * SKIP unless BOTH are present AND `ga != gb` (the Python
///     `if ga and gb and ga != gb`);
///   * keep the STRICTLY-greatest `float(c)` per gene-pair, exactly as the Python
///     `if cv > pc.get(k, -1.0): pc[k] = cv` (default -1.0; order-invariant MAX).
pub fn load_pair_core_str(
    gene_of_dn: &HashMap<String, String>,
    text: &str,
) -> HashMap<(String, String), f64> {
    let mut pc: HashMap<(String, String), f64> = HashMap::new();
    for line in text.lines().skip(1) {
        // Python: a, b, c = ln.rstrip("\n").split("\t")  (exactly 3 columns)
        let f: Vec<&str> = line.split('\t').collect();
        let (a, b, c) = (f[0], f[1], f[2]);
        if let (Some(ga), Some(gb)) = (gene_of_dn.get(a), gene_of_dn.get(b)) {
            if ga != gb {
                let cv: f64 = c.parse().expect("core_recip float");
                let k = gene_pair_key(ga, gb);
                // Python: if cv > pc.get(k, -1.0): pc[k] = cv
                let cur = pc.get(&k).copied().unwrap_or(-1.0);
                if cv > cur {
                    pc.insert(k, cv);
                }
            }
        }
    }
    pc
}

/// Read the EDGES_TSV file and parse it (see `load_pair_core_str`).
pub fn load_pair_core(
    gene_of_dn: &HashMap<String, String>,
    path: &str,
) -> std::io::Result<HashMap<(String, String), f64>> {
    Ok(load_pair_core_str(gene_of_dn, &std::fs::read_to_string(path)?))
}

