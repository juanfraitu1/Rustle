pub fn load_gene_labels_str(text: &str) -> BTreeMap<(String, i64), String> {
    let mut g: BTreeMap<(String, i64), String> = BTreeMap::new();
    for line in text.lines().skip(1) {
        let p: Vec<&str> = line.split('\t').collect();
        let start: i64 = p[3].parse().expect("gene-label start int");
        g.insert((p[2].to_string(), start), p[5].to_string());
    }
    g
}

