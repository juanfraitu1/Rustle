/// Read the minimap2 `de` (gap-compressed per-base divergence) aux tag as an `f64`.
///
/// The BAM stores `de` as a 4-byte IEEE-754 single (`Value::Float`); pysam widens it
/// to a Python `float` (a C double) losslessly, so `f32 as f64` reproduces pysam's
/// value bit-for-bit — the comparison `de < best[qname][1]` and the emitted raw f64
/// bits therefore match Python exactly. A missing (or non-float) `de` yields `None`,
/// matching Python's `dict(r.get_tags()).get("de")` returning `None`.
fn read_de_tag(rb: &RecordBuf) -> Option<f64> {
    match rb.data().get(&Tag::new(b'd', b'e'))? {
        BufValue::Float(f) => Some(*f as f64),
        _ => None,
    }
}

/// The multimapper read-fetch of `materialize_family` (Python ~lines 139-161): sweep the
/// copy `regions` IN THE GIVEN ORDER (already sorted by `-length` upstream), and for each
/// region `.bai`-indexed-query the genome BAM over `[max(0, s-pad),
/// min(contig_len[c], e+pad))` on contig `c`, building two structures:
///
///  * `best`: `qname -> (region_index, de)` keeping the LOWEST `de` for each read, with
///    the FIRST-SEEN region winning ties (Python's strict `de < best[qname][1]`). This is
///    the "best-mapping copy" (lowest minimap2 divergence) per read — the multimapper
///    evidence pool.
///  * `seqs`: `[(qname, query_sequence)]` in INSERTION ORDER (fetch order across regions),
///    added for a read the FIRST time it is seen as a NON-secondary alignment with a
///    non-empty SEQ. Insertion order is load-bearing: it drives the [`READ_CAP`]
///    truncation (keep the first `read_cap`). Returned as a `Vec` (NOT a map) precisely to
///    preserve that order.
///
/// ## Filter (verbatim pysam semantics, Python lines 145-151)
///  1. skip `is_unmapped` (0x4) or `is_supplementary` (0x800);
///  2. skip if `reference_end is None` OR `reference_end < s` OR `reference_start > e`
///     — where `s`/`e` are the ORIGINAL (un-padded) region bounds, `reference_start` is
///     the 0-based leftmost aligned position (`alignment_start-1`) and `reference_end` is
///     the 0-based exclusive end (`reference_start + cigar reference-span`, i.e. the same
///     `reference_start + sum(M/D/N/=/X)` pysam reports; `None` when the read has no
///     reference-consuming alignment);
///  3. skip if the `de` tag is absent (so a seq-bearing read WITHOUT `de` never enters
///     `seqs` either — the `de` gate precedes the `seqs` update, exactly as in Python).
///
/// ## Query ↔ pysam intersection equivalence
/// pysam `fetch(c, s2, stop)` (0-based half-open) returns a read iff
/// `reference_start < stop AND reference_end > s2`. The noodles indexed query filters on
/// the 1-based-inclusive interval `[s2+1, stop]` (built via the crate's established
/// `"{chrom}:{a}-{b}"` region string) intersecting the read's 1-based `[start, end]`,
/// which reduces to the SAME predicate. Both return records in coordinate (BGZF file)
/// order, so re-applying the exact Python post-filter yields an identical set AND the
/// identical insertion order for `seqs`.
///
/// Requires a `{bam_path}.bai` index; errors (rather than scanning) if it is missing, so
/// the byte-parity test can skip cleanly when the multi-GB BAM is unavailable.
pub fn fetch_reads<P: AsRef<Path>>(
    bam_path: P,
    regions: &[(String, i64, i64, i64)],
    contig_len: &BTreeMap<String, i64>,
    pad: i64,
    read_cap: usize,
) -> Result<(BTreeMap<String, (usize, f64)>, Vec<(String, String)>)> {
    let bam_path = bam_path.as_ref();
    let bai_path = {
        let mut s = bam_path.as_os_str().to_os_string();
        s.push(".bai");
        std::path::PathBuf::from(s)
    };
    anyhow::ensure!(
        bai_path.exists(),
        "fetch_reads needs a .bai index next to {} (expected {})",
        bam_path.display(),
        bai_path.display()
    );

    let mut reader = noodles_bam::io::reader::Builder::default().build_from_path(bam_path)?;
    let header = reader.read_header()?;
    let index = noodles_bam::bai::read(&bai_path)?;

    // `best` is a MAP (qname -> (region_idx, de)); BTreeMap gives deterministic ascending
    // key order (Python later does `for r in sorted(best)`). `seqs`/`seen` preserve the
    // load-bearing first-seen INSERTION order for the cap.
    let mut best: BTreeMap<String, (usize, f64)> = BTreeMap::new();
    let mut seqs: Vec<(String, String)> = Vec::new();
    let mut seen: HashSet<String> = HashSet::new();

    for (i, (c, s, e, _)) in regions.iter().enumerate() {
        // s2, e2 = max(0, s - PAD), e + PAD ; stop = min(contig_len.get(c, e2), e2)
        let s2 = (s - pad).max(0);
        let e2 = e + pad;
        let stop = contig_len.get(c).copied().unwrap_or(e2).min(e2);
        if stop <= s2 {
            continue; // degenerate/empty region -> pysam.fetch returns nothing
        }
        // 1-based inclusive [s2+1, stop] == pysam 0-based half-open [s2, stop).
        let region: noodles_core::Region = format!("{c}:{}-{}", s2 + 1, stop).parse()?;
        let query = reader.query(&header, &index, &region)?;

        for result in query {
            let record = result?;
            let rb = RecordBuf::try_from_alignment_record(&header, &record)?;

            let flags = rb.flags();
            if flags.is_unmapped() || flags.is_supplementary() {
                continue;
            }

            // reference_start (0-based) and reference_end (0-based exclusive).
            // `reference_end is None` <=> no reference-consuming alignment.
            let Some(start) = rb.alignment_start() else {
                continue;
            };
            let ref_start_0 = start.get() as i64 - 1;
            let span = rb.cigar().alignment_span() as i64;
            if span == 0 {
                continue; // pysam reference_end is None here
            }
            let ref_end_0_excl = ref_start_0 + span;
            if ref_end_0_excl < *s || ref_start_0 > *e {
                continue;
            }

            let Some(de) = read_de_tag(&rb) else {
                continue;
            };

            let name = match rb.name() {
                Some(n) => n.to_string(),
                None => continue,
            };

            // best[qname] = (i, de) if new OR strictly-lower de (first-seen wins ties).
            match best.get(&name) {
                None => {
                    best.insert(name.clone(), (i, de));
                }
                Some(&(_, cur_de)) => {
                    if de < cur_de {
                        best.insert(name.clone(), (i, de));
                    }
                }
            }

            // seqs[qname] = query_sequence, first non-secondary seq-bearing sighting.
            if !flags.is_secondary() && !seen.contains(&name) {
                let seq_bytes: &[u8] = rb.sequence().as_ref();
                if !seq_bytes.is_empty() {
                    let seq: String = seq_bytes.iter().map(|&b| b as char).collect();
                    seen.insert(name.clone());
                    seqs.push((name, seq));
                }
            }
        }
    }

    if seqs.len() > read_cap {
        seqs.truncate(read_cap);
    }
    Ok((best, seqs))
}

