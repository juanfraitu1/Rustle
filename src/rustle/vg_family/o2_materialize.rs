/// Collapse de-novo loci that are the same genomic copy (isoforms) into one
/// copy-region — same chrom + reciprocal overlap `>` [`OVERLAP_MERGE`] of the shorter
/// locus. Distinct tandem copies stay separate. Faithful port of
/// `bench/psv_graph_genomewide.py::dedup_copies`.
///
/// Input `loci` is a slice of `(lid, chrom, start, end, nreads)` (the `lid` is unused
/// by the algorithm, exactly as in Python where only `(c, s, e, nr)` are read).
/// Output is `(chrom, start, end, nreads)` per merged region.
///
/// ## Order fidelity (load-bearing — see the module note)
/// The Python groups by chrom with a `collections.defaultdict(list)`, whose iteration
/// is INSERTION order (first-seen chrom order across `loci`). The returned `regions`
/// list is emitted chrom-group by chrom-group in that first-seen order, and within a
/// group in sweep order (which follows the `items.sort()` ascending `(s, e, nr)`
/// order). We reproduce this EXACTLY with a first-seen `Vec<chrom>` + a `HashMap`
/// index (NOT a `BTreeMap`, which would reorder chroms alphabetically). The downstream
/// `materialize_family` re-sorts the regions by length-desc, but reproducing this
/// return order verbatim keeps the port byte-faithful for every consumer.
///
/// ## The merge test (reproduced verbatim, incl. the strict `>` and the min-of-lengths)
/// Sweeping the sorted items with a running `cur = (start, end, nreads)`: the next
/// item `(s, e, nr)` merges into `cur` iff `s < cur.end` AND
/// `ov > OVERLAP_MERGE * min(cur.end - cur.start, e - s)` where
/// `ov = min(cur.end, e) - s`. On a merge, `cur = (cur.start, max(cur.end, e),
/// cur.nreads + nr)` (note the `max` end and the `nreads` accumulation) and the next
/// item is consumed WITHOUT flushing (`continue`). Otherwise `cur` is flushed to
/// `regions` and a fresh `cur` starts at `(s, e, nr)`. The comparison is done in `f64`
/// (an `int` `ov` against the `float` `OVERLAP_MERGE * int`), matching Python; with
/// `OVERLAP_MERGE == 0.5` the products are exact for these coordinate magnitudes.
pub fn dedup_copies(loci: &[(String, String, i64, i64, i64)]) -> Vec<(String, i64, i64, i64)> {
    // Group by chrom preserving FIRST-SEEN chrom order (Python defaultdict(list)).
    let mut chrom_order: Vec<String> = Vec::new();
    let mut idx: HashMap<&str, usize> = HashMap::new();
    let mut groups: Vec<Vec<(i64, i64, i64)>> = Vec::new();
    for (_lid, c, s, e, nr) in loci {
        let gi = match idx.get(c.as_str()) {
            Some(&i) => i,
            None => {
                let i = groups.len();
                idx.insert(c.as_str(), i);
                chrom_order.push(c.clone());
                groups.push(Vec::new());
                i
            }
        };
        groups[gi].push((*s, *e, *nr));
    }

    let mut regions: Vec<(String, i64, i64, i64)> = Vec::new();
    for (gi, c) in chrom_order.iter().enumerate() {
        let mut items = std::mem::take(&mut groups[gi]);
        // Python items.sort() -> lexicographic ascending (s, e, nr).
        items.sort();
        let mut cur: Option<(i64, i64, i64)> = None;
        for (s, e, nr) in items {
            if let Some((cs, ce, cnr)) = cur {
                if s < ce {
                    let ov = ce.min(e) - s;
                    let minlen = (ce - cs).min(e - s);
                    if (ov as f64) > OVERLAP_MERGE * (minlen as f64) {
                        // merge (grow end via max, accumulate nreads) and continue
                        cur = Some((cs, ce.max(e), cnr + nr));
                        continue;
                    }
                }
                // no merge: flush the running region before starting a fresh one
                regions.push((c.clone(), cs, ce, cnr));
            }
            cur = Some((s, e, nr));
        }
        if let Some((cs, ce, cnr)) = cur {
            regions.push((c.clone(), cs, ce, cnr));
        }
    }
    regions
}

