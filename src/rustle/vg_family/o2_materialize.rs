/// Parse the SUN identifiability TSV text into `(chrom, start) -> gene`. Faithful port
/// of `bench/o2_vg_visualization.py::load_gene_labels` operating on the raw text.
///
/// Header line skipped. Columns (Python `p = line.split("\t"); g[(p[2], int(p[3]))] =
