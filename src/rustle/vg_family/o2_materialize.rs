    #[test]
    fn dedup_copies_byte_parity() {
        let fx = load_fixture();

        // OVERLAP_MERGE value agreement.
        assert_eq!(
            OVERLAP_MERGE,
            fx["overlap_merge"].as_f64().unwrap(),
            "OVERLAP_MERGE constant disagrees with Python"
        );

        let cases = fx["dedup_cases"].as_array().expect("dedup_cases array");
        assert!(
            cases.len() >= 100,
            "expected >=100 dedup cases, got {}",
            cases.len()
        );

        let mut n_merge = 0usize;
        let mut n_multichrom = 0usize;
        let mut n_single = 0usize;
        let mut n_tandem_sep = 0usize;

        for case in cases {
            let id = case["id"].as_str().unwrap();
            let loci: Vec<FamLocus> = case["loci"]
                .as_array()
                .unwrap()
                .iter()
                .map(|r| {
                    let a = r.as_array().unwrap();
                    (
                        a[0].as_str().unwrap().to_string(),
                        a[1].as_str().unwrap().to_string(),
                        a[2].as_i64().unwrap(),
                        a[3].as_i64().unwrap(),
                        a[4].as_i64().unwrap(),
                    )
                })
                .collect();
            let expect: Vec<(String, i64, i64, i64)> = case["expect"]
                .as_array()
                .unwrap()
                .iter()
                .map(|r| {
                    let a = r.as_array().unwrap();
                    (
                        a[0].as_str().unwrap().to_string(),
                        a[1].as_i64().unwrap(),
                        a[2].as_i64().unwrap(),
                        a[3].as_i64().unwrap(),
                    )
                })
                .collect();

            let got = dedup_copies(&loci);

            // First-mismatch localization (position + field), then whole-vec equality.
            let n = got.len().max(expect.len());
            for i in 0..n {
                match (got.get(i), expect.get(i)) {
                    (Some(g), Some(e)) if g == e => {}
                    (g, e) => panic!(
                        "dedup case {id}: region[{i}] rust={:?} python={:?}\n  \
                         rust n_regions={}, python n_regions={}",
                        g,
                        e,
                        got.len(),
                        expect.len()
                    ),
                }
            }
            assert_eq!(got, expect, "dedup case {id}: whole-vec inequality");

            // Class accounting (for the fixture-composition sanity checks below).
            let n_loci = loci.len();
            let n_chrom = {
                let mut cs: Vec<&str> = loci.iter().map(|l| l.1.as_str()).collect();
                cs.sort();
                cs.dedup();
                cs.len()
            };
            if n_loci == 1 {
                n_single += 1;
            }
            if n_chrom >= 2 {
                n_multichrom += 1;
            }
            if got.len() < n_loci {
                n_merge += 1;
            }
            // same-chrom loci that stayed as multiple regions => a tandem separation
            if n_chrom == 1 && got.len() >= 2 {
                n_tandem_sep += 1;
            }
        }

        assert!(n_merge >= 1, "no case exercised an isoform merge");
        assert!(n_single >= 1, "no single-locus case");
        assert!(n_multichrom >= 1, "no multi-chrom case");
        assert!(n_tandem_sep >= 1, "no tandem-stays-separate case");

        eprintln!(
            "o2_materialize dedup_copies byte-parity: {} cases all match incl order \
             ({} with merges, {} single-locus, {} multi-chrom, {} tandem-separate)",
            cases.len(),
            n_merge,
            n_single,
            n_multichrom,
            n_tandem_sep
        );
    }

