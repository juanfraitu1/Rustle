/// Parse the SUN identifiability TSV text into `(chrom, start) -> gene`. Faithful port
/// of `bench/o2_vg_visualization.py::load_gene_labels` operating on the raw text.
///
/// Header line skipped. Columns (Python `p = line.split("\t"); g[(p[2], int(p[3]))] =
/// p[5]`): `p[2]=chrom  p[3]=start  p[5]=gene`. A repeated `(chrom, start)` key keeps
/// the LAST value (dict assignment / `BTreeMap::insert` both overwrite).
pub fn load_gene_labels_str(text: &str) -> BTreeMap<(String, i64), String> {
    let mut g: BTreeMap<(String, i64), String> = BTreeMap::new();
    for line in text.lines().skip(1) {
        let p: Vec<&str> = line.split('\t').collect();
        let start: i64 = p[3].parse().expect("gene-label start int");
        g.insert((p[2].to_string(), start), p[5].to_string());
    }
    g
}

/// Read the SUN identifiability TSV and parse it (see [`load_gene_labels_str`]). A
/// MISSING file yields an empty map, matching the Python
/// `if os.path.exists(SUN_TSV): ... else return {}`.
pub fn load_gene_labels<P: AsRef<Path>>(path: P) -> std::io::Result<BTreeMap<(String, i64), String>> {
    let path = path.as_ref();
    if !path.exists() {
        return Ok(BTreeMap::new());
    }
    Ok(load_gene_labels_str(&std::fs::read_to_string(path)?))
}

