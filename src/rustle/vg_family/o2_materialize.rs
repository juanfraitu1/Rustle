    fn parse_regions(v: &Value) -> Vec<(String, i64, i64, i64)> {
        v.as_array()
            .unwrap()
            .iter()
            .map(|r| {
                let a = r.as_array().unwrap();
                (
                    a[0].as_str().unwrap().to_string(),
                    a[1].as_i64().unwrap(),
                    a[2].as_i64().unwrap(),
                    a[3].as_i64().unwrap(),
                )
            })
            .collect()
    }

    fn qname_list(v: &Value) -> Vec<String> {
        v.as_array()
            .unwrap()
            .iter()
            .map(|q| q.as_str().unwrap().to_string())
            .collect()
    }

    /// fetch_reads == the Python read-fetch EXACTLY on every fixture family:
    ///   * `best` map: qname -> (region_idx, de) with de compared as raw f64 BITS;
    ///   * `seqs` qname ORDER (insertion order, drives the cap);
    ///   * the READ_CAP truncation (via lowered-cap cases, since no family hits 6000).
    /// Skips-with-message (does NOT fail) if the multi-GB genome BAM / its `.bai` is
    /// absent, so CI without the BAM is green; it IS present in dev so this runs+passes.
    #[test]
    fn fetch_reads_byte_parity() {
        let fx = load_readfetch_fixture();
        let bam_path = fx["bam_path"].as_str().expect("bam_path");
        let bai = format!("{bam_path}.bai");
        if !Path::new(bam_path).exists() || !Path::new(&bai).exists() {
            eprintln!(
                "o2_materialize fetch_reads byte-parity SKIPPED: genome BAM or .bai absent \
                 ({bam_path} / {bai}). Present in dev; run there to exercise this test."
            );
            return;
        }

        // Constant agreement with the Python (pg.PAD / pg.READ_CAP).
        let pad = fx["pad"].as_i64().expect("pad");
        let read_cap = fx["read_cap"].as_u64().expect("read_cap") as usize;
        assert_eq!(PAD, pad, "PAD constant disagrees with Python pg.PAD");
        assert_eq!(READ_CAP, read_cap, "READ_CAP disagrees with Python pg.READ_CAP");

        // contig_len (all genome contigs, as the Python passed).
        let mut contig_len: BTreeMap<String, i64> = BTreeMap::new();
        for (k, v) in fx["contig_len"].as_object().expect("contig_len obj") {
            contig_len.insert(k.clone(), v.as_i64().unwrap());
        }

        // Keep each family's regions for the lowered-cap truncation cases below.
        let mut regions_by_fam: BTreeMap<i64, Vec<(String, i64, i64, i64)>> = BTreeMap::new();
        let mut total_best = 0usize;
        let mut total_seqs = 0usize;

        let families = fx["families"].as_array().expect("families array");
        assert!(families.len() >= 4, "expected >=4 fixture families");

        for fam in families {
            let fam_id = fam["fam_id"].as_i64().unwrap();
            let regions = parse_regions(&fam["regions"]);
            regions_by_fam.insert(fam_id, regions.clone());

            let (best, seqs) = fetch_reads(bam_path, &regions, &contig_len, pad, read_cap)
                .unwrap_or_else(|e| panic!("fetch_reads(fam {fam_id}) failed: {e}"));

            // ---- best map: qname -> (region_idx, de-as-f64-bits) ----
            let exp_best = fam["best"].as_object().expect("best obj");
            // localize first divergence over the union of keys (ascending).
            let mut names: Vec<&String> = best.keys().collect();
            for k in exp_best.keys() {
                if !best.contains_key(k) {
                    names.push(k);
                }
            }
            names.sort();
            names.dedup();
            for name in names {
                let got = best.get(name);
                let exp = exp_best.get(name);
                match (got, exp) {
                    (Some(&(gi, gde)), Some(ev)) => {
                        let ea = ev.as_array().unwrap();
                        let ei = ea[0].as_i64().unwrap() as usize;
                        let ebits: u64 = ea[1].as_str().unwrap().parse().unwrap();
                        assert_eq!(
                            gi, ei,
                            "fam {fam_id} best[{name}] region_idx rust={gi} python={ei}"
                        );
                        assert_eq!(
                            gde.to_bits(),
                            ebits,
                            "fam {fam_id} best[{name}] de-bits rust={} python={} (rust de={gde})",
                            gde.to_bits(),
                            ebits
                        );
                    }
                    (Some(g), None) => {
                        panic!("fam {fam_id} best[{name}] present in rust ({g:?}), MISSING in python")
                    }
                    (None, Some(e)) => {
                        panic!("fam {fam_id} best[{name}] MISSING in rust, python={e:?}")
                    }
                    (None, None) => unreachable!(),
                }
            }
            assert_eq!(
                best.len(),
                exp_best.len(),
                "fam {fam_id} best cardinality rust={} python={}",
                best.len(),
                exp_best.len()
            );
            assert_eq!(
                best.len(),
                fam["n_best"].as_u64().unwrap() as usize,
                "fam {fam_id} n_best disagrees"
            );

            // ---- seqs qname ORDER (no family hits READ_CAP, so precap == postcap) ----
            let got_order: Vec<String> = seqs.iter().map(|(n, _)| n.clone()).collect();
            let exp_precap = qname_list(&fam["seqs_order_precap"]);
            let exp_postcap = qname_list(&fam["seqs_order_postcap"]);
            assert!(
                !fam["hit_read_cap"].as_bool().unwrap(),
                "fixture fam {fam_id} unexpectedly hit READ_CAP; test assumes precap==postcap here"
            );
            assert_eq!(exp_precap, exp_postcap, "fam {fam_id} fixture precap!=postcap");
            // first-divergence localization on the ordered qname list.
            let n = got_order.len().max(exp_precap.len());
            for k in 0..n {
                assert_eq!(
                    got_order.get(k),
                    exp_precap.get(k),
                    "fam {fam_id} seqs order[{k}] rust={:?} python={:?} (rust len={}, python len={})",
                    got_order.get(k),
                    exp_precap.get(k),
                    got_order.len(),
                    exp_precap.len()
                );
            }
            assert_eq!(
                got_order.len(),
                fam["n_seqs_precap"].as_u64().unwrap() as usize,
                "fam {fam_id} n_seqs disagrees"
            );

            total_best += best.len();
            total_seqs += got_order.len();
        }

        // ---- lowered-cap cases: exercise the READ_CAP truncation path ----
        let lowered = fx["lowered_cap"].as_array().expect("lowered_cap array");
        assert!(!lowered.is_empty(), "expected lowered-cap truncation cases");
        let mut n_truncated = 0usize;
        for lc in lowered {
            let fam_id = lc["fam_id"].as_i64().unwrap();
            let cap = lc["read_cap"].as_u64().unwrap() as usize;
            let regions = regions_by_fam
                .get(&fam_id)
                .unwrap_or_else(|| panic!("lowered-cap fam {fam_id} not among fixture families"));
            let (_best, seqs) = fetch_reads(bam_path, regions, &contig_len, pad, cap)
                .unwrap_or_else(|e| panic!("fetch_reads(fam {fam_id}, cap {cap}) failed: {e}"));
            let got_order: Vec<String> = seqs.iter().map(|(n, _)| n.clone()).collect();
            let exp_postcap = qname_list(&lc["seqs_order_postcap"]);
            assert!(
                lc["truncated"].as_bool().unwrap(),
                "lowered fam {fam_id} cap {cap} should truncate"
            );
            assert_eq!(
                got_order.len(),
                cap,
                "lowered fam {fam_id}: truncated len rust={} expected cap={cap}",
                got_order.len()
            );
            for k in 0..got_order.len().max(exp_postcap.len()) {
                assert_eq!(
                    got_order.get(k),
                    exp_postcap.get(k),
                    "lowered fam {fam_id} cap {cap} postcap order[{k}] rust={:?} python={:?}",
                    got_order.get(k),
                    exp_postcap.get(k)
                );
            }
            n_truncated += 1;
        }

        eprintln!(
            "o2_materialize fetch_reads byte-parity: {} families ({} best entries, {} seqs) \
             all match python incl de-bits + seqs order; {} lowered-cap truncation cases match",
            families.len(),
            total_best,
            total_seqs,
            n_truncated
        );
    }
