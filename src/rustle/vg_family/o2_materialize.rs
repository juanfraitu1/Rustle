//! O2 VG-materialization step 3: the LOADERS + copy-dedup that
//! `bench/o2_vg_visualization.py::materialize_family` runs BEFORE it aligns copies
//! and threads reads.
//!
//! This module will grow to hold the full `materialize_family`; it starts with the
//! four pieces that run first, ported byte-faithfully from the Python ground truth:
//!
//!   * [`dedup_copies`] — collapse de-novo loci that are the same genomic copy
//!     (isoforms) into one copy-region (Python `psv_graph_genomewide.dedup_copies`,
//!     ~line 62);
//!   * [`load_families`] / [`load_families_str`] — parse the validated-families TSV
//!     into `fam_id -> [(lid, chrom, start, end, nreads)]` (Python
//!     `o2_vg_visualization.load_families`, ~line 84);
//!   * [`load_gene_labels`] / [`load_gene_labels_str`] — parse the SUN identifiability
//!     TSV into `(chrom, start) -> gene` (Python `o2_vg_visualization.load_gene_labels`,
//!     ~line 71);
//!   * [`FLAGSHIP`] — the flagship-family roster constant (Python
//!     `o2_vg_visualization.FLAGSHIP`, ~line 63).
//!
//! Byte-parity is enforced against a golden fixture
//! (`testdata/o2_materialize_fixture.json`, generated by
//! `bench/gen_o2_materialize_fixture.py`, PYTHONHASHSEED=0) by the `#[test]`s below.

