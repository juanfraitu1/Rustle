/// One family's loci as parsed from the validated-families TSV.
pub type FamLocus = (String, String, i64, i64, i64);

/// Parse the validated-families TSV text into `fam_id -> [(lid, chrom, start, end,
/// nreads)]`. Faithful port of `bench/o2_vg_visualization.py::load_families` operating
/// on the raw text (`load_families` reads the file and delegates here).
///
/// Header line skipped. Columns (Python `fi, lid, c, s, e, nr = line.split("\t")`):
/// `f[0]=family  f[1]=locus  f[2]=chrom  f[3]=start  f[4]=end  f[5]=nreads`. The
/// per-family `Vec` preserves FILE order (Python `defaultdict(list).append`), which is
/// what feeds [`dedup_copies`]' first-seen-chrom ordering — so the order must be kept.
/// The `BTreeMap` key order is irrelevant to callers (they index `fams[fam_id]`) but is
/// deterministic.
pub fn load_families_str(text: &str) -> BTreeMap<i64, Vec<FamLocus>> {
    let mut fams: BTreeMap<i64, Vec<FamLocus>> = BTreeMap::new();
    for line in text.lines().skip(1) {
        let f: Vec<&str> = line.split('\t').collect();
        let fi: i64 = f[0].parse().expect("family int");
        let s: i64 = f[3].parse().expect("start int");
        let e: i64 = f[4].parse().expect("end int");
        let nr: i64 = f[5].parse().expect("nreads int");
        fams.entry(fi)
            .or_default()
            .push((f[1].to_string(), f[2].to_string(), s, e, nr));
    }
    fams
}

/// Read the validated-families TSV file and parse it (see [`load_families_str`]).
pub fn load_families<P: AsRef<Path>>(path: P) -> std::io::Result<BTreeMap<i64, Vec<FamLocus>>> {
    Ok(load_families_str(&std::fs::read_to_string(path)?))
}

