    /// PROVES `split_block` == the shipped Python EXACTLY (as sets of sorted DN-blocks)
    /// for every fixture block. Reports the first mismatch + root-cause hints.
    #[test]
    fn split_block_parity() {
        let fx = load_fixture();
        let blocks = fx["blocks"].as_array().expect("blocks array");
        assert!(blocks.len() >= 20, "need >= 20 blocks, got {}", blocks.len());

        let mut n_split = 0;
        let mut n_unchanged = 0;
        let mut seen_flagship = false;
        let mut seen_colocated = false;
        let mut seen_na = false;
        let mut seen_multi_art = false;
        let mut seen_gt_maxloci = false;
        let mut seen_lt3 = false;
        let mut seen_graph = false;

        for b in blocks {
            let label = b["label"].as_str().unwrap();
            let cls = b["cls"].as_str().unwrap();
            let n_art = b["n_art"].as_u64().unwrap();
            let (block, genes, gene_of_dn, skel, strand, fa) = block_inputs(b);

            let want: Vec<Vec<String>> = b["result"]
                .as_array()
                .unwrap()
                .iter()
                .map(|p| p.as_array().unwrap().iter().map(|v| v.as_str().unwrap().to_string()).collect())
                .collect();
            let got = split_block(&block, &genes, &gene_of_dn, &skel, &strand, &fa);

            assert_eq!(
                as_set(&got),
                as_set(&want),
                "split_block MISMATCH block '{label}' (cls={cls}): rust {} parts {:?} != python {} parts {:?}",
                got.len(),
                got,
                want.len(),
                want
            );

            if want.len() > 1 {
                n_split += 1;
            } else {
                n_unchanged += 1;
            }
            match cls {
                "split" => {
                    if label == "flagship_210" {
                        seen_flagship = true;
                        // fid 210: LOC115935264 bridges LOC101126070 | GALNT17 -> 3 singleton parts;
                        // GALNT17 + LOC101126070 must NOT be co-membered after the split.
                        assert!(got.len() >= 2, "flagship 210 did not split");
                        let galnt17: Vec<&String> =
                            gene_of_dn.iter().filter(|(_, g)| g.as_str() == "GALNT17").map(|(d, _)| d).collect();
                        let loc: Vec<&String> = gene_of_dn
                            .iter()
                            .filter(|(_, g)| g.as_str() == "LOC101126070")
                            .map(|(d, _)| d)
                            .collect();
                        assert!(!galnt17.is_empty() && !loc.is_empty(), "flagship missing GALNT17/LOC101126070");
                        for part in &got {
                            let has_g = galnt17.iter().any(|d| part.contains(d));
                            let has_l = loc.iter().any(|d| part.contains(d));
                            assert!(!(has_g && has_l), "flagship 210: GALNT17 + LOC101126070 still co-membered");
                        }
                    }
                }
                "colocated_skip" => seen_colocated = true,
                "na_dominant_skip" => seen_na = true,
                "multi_articulation" => seen_multi_art = true,
                "skip_gt_maxloci" => seen_gt_maxloci = true,
                "skip_block_lt3" => seen_lt3 = true,
                "nonsplit_graph" => seen_graph = true,
                _ => {}
            }
            if n_art >= 2 {
                seen_multi_art = true;
            }
        }

        assert!(n_split >= 1, "fixture must exercise >= 1 SPLIT block");
        assert!(seen_flagship, "fixture must include the flagship fid-210 GALNT17|LOC101126070 split");
        assert!(seen_colocated, "fixture must include a colocated-chimera skip");
        assert!(seen_na, "fixture must include an NA-dominant skip");
        assert!(seen_multi_art, "fixture must include a multi-articulation-point family");
        assert!(seen_gt_maxloci, "fixture must include a >MAX_LOCI skip");
        assert!(seen_lt3, "fixture must include a <3-loci skip");
        assert!(seen_graph, "fixture must include non-split blocks that reach the exon graph");
        eprintln!(
            "split_block parity: {} blocks byte-identical to Python ({n_split} split, {n_unchanged} unchanged)",
            blocks.len()
        );
    }
