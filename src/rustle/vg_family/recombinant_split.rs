// ===========================================================================
// articulation_points  -- iterative Tarjan cut-vertices (== nx.articulation_points SET)
// ===========================================================================

/// The set of articulation points (cut vertices) of the undirected graph given by
/// `adj` (node `u`'s neighbours = `adj[u]`, symmetric, no self-loops). Node universe
/// is `0..adj.len()`.
///
/// Standard iterative (non-recursive) Tarjan DFS: a non-root node `u` is a cut vertex
/// iff it has a child `v` in the DFS tree with `low[v] >= disc[u]`; the DFS root is a
/// cut vertex iff it has `> 1` tree children. The cut-vertex SET is a graph invariant
/// (independent of neighbour iteration order), so this equals
/// `set(nx.articulation_points(G))` exactly (networkx 3.6.1 deduplicates its own DFS
/// generator via a `seen` set). Multi-component graphs = union over the DFS forest;
/// a single node / edgeless graph has none.
pub fn articulation_points(adj: &[BTreeSet<usize>]) -> BTreeSet<usize> {
    let n = adj.len();
    // Indexed neighbour snapshots (sorted order from the BTreeSet; order is irrelevant
    // to the resulting SET -- see the doc).
    let neigh: Vec<Vec<usize>> = adj.iter().map(|s| s.iter().copied().collect()).collect();
    let mut disc = vec![0usize; n];
    let mut low = vec![0usize; n];
    let mut visited = vec![false; n];
    let mut ap: BTreeSet<usize> = BTreeSet::new();
    let mut timer = 0usize;

    for s in 0..n {
        if visited[s] {
            continue;
        }
        timer += 1;
        disc[s] = timer;
        low[s] = timer;
        visited[s] = true;
        let mut root_children = 0usize;
        // Frame: (node, parent(-1 for root), next-neighbour index).
        let mut stack: Vec<(usize, isize, usize)> = vec![(s, -1, 0)];
        while !stack.is_empty() {
            let top = stack.len() - 1;
            let (u, parent) = (stack[top].0, stack[top].1);
            if stack[top].2 < neigh[u].len() {
                let v = neigh[u][stack[top].2];
                stack[top].2 += 1;
                if v as isize == parent {
                    continue; // skip the single tree edge back to the DFS parent
                }
                if visited[v] {
                    if disc[v] < low[u] {
                        low[u] = disc[v]; // back edge
                    }
                } else {
                    visited[v] = true;
                    timer += 1;
                    disc[v] = timer;
                    low[v] = timer;
                    if parent == -1 {
                        root_children += 1;
                    }
                    stack.push((v, u as isize, 0));
                }
            } else {
                // u fully explored: propagate low to the DFS parent + test cut-vertex.
                stack.pop();
                if let Some(&(pu, pp, _)) = stack.last() {
                    if low[u] < low[pu] {
                        low[pu] = low[u];
                    }
                    if pp != -1 && low[u] >= disc[pu] {
                        ap.insert(pu);
                    }
                }
            }
        }
        if root_children > 1 {
            ap.insert(s);
        }
    }
    ap
}

// ===========================================================================
// components_excluding  -- connected components with a node set removed
// ===========================================================================

/// Connected components of the graph `adj` over the nodes NOT in `removed`, each
/// component sorted ascending, the list sorted by first element. Matches the Python
/// `sorted((sorted(c) for c in nx.connected_components(Gb)), key=lambda c: c[0])`
/// where `Gb` is `G` with `removed` deleted -- INCLUDING singleton components for
/// nodes whose only edges went to removed nodes. Deterministic DFS in ascending order.
pub fn components_excluding(adj: &[BTreeSet<usize>], removed: &BTreeSet<usize>) -> Vec<Vec<usize>> {
    let n = adj.len();
    let mut seen = vec![false; n];
    for &r in removed {
        if r < n {
            seen[r] = true; // treat removed nodes as already-visited => skipped
        }
    }
    let mut comps: Vec<Vec<usize>> = Vec::new();
    for s in 0..n {
        if seen[s] {
            continue;
        }
        let mut stack = vec![s];
        seen[s] = true;
        let mut comp = Vec::new();
        while let Some(u) = stack.pop() {
            comp.push(u);
            for &v in &adj[u] {
                if !seen[v] {
                    seen[v] = true;
                    stack.push(v);
                }
            }
        }
        comp.sort_unstable();
        comps.push(comp);
    }
    comps.sort_by(|a, b| a[0].cmp(&b[0]));
    comps
}

