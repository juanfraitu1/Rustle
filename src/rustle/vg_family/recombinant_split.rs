//! O1 recombinant-SPLIT gate -- faithful Rust port of `bench/recombinant_split.py`
//! (the O1 over-merge-gate migration, `docs/RETIREMENT_AND_MIGRATION.md` Tier-2 #6,
//! full byte-parity path).
//!
//! A RECOMBINANT bridge is a locus whose exon-chain splits COLINEARLY into >=2
//! DIFFERENT sub-families' exons AND is an articulation point whose best single-
//! neighbour colinear coverage `< COLINEAR_COV`. The shipped pairwise-edge family
//! definition transitively merges `G1-G3-G2` through such a bridge (a density-2/3
//! barbell survives the gamma-quasi-clique); this gate SPLITS the family along the
//! bridge into its colinear sub-families. The HIGH-confidence DISTRIBUTED-MOSAIC
//! subset only (both bridged sub-families annotated, minor block >= 2 exons, NOT
//! genomically colocated) is recall-safe to split (flagship: fid 210
//! `LOC115935264` bridging `LOC101126070 | GALNT17`).
//!
//! REUSES the already-ported shared exon-graph LIBRARY in `super::bridge_detector`
//! (`family_exons` / `exon_match_tensor` / `build_graph` / `colinear_cov` /
//! `subfams_colocated` / `subfam_dom_gene` + `ID_THRESH` / `COLINEAR_COV`) and the
//! `GeneMeta` shape from `super::family_loaders` -- nothing re-derived. Only the
//! SPLIT-gate driver (`_members`, `_recombinant_bridges`, `split_block`) + the two
//! deterministic graph algorithms it needs (`articulation_points`,
//! `components_excluding`) are ported here.
//!
//! PORTED (the Python is ground truth; line refs are `bench/recombinant_split.py`):
//!   * constants `COLINEAR_COV=0.60` (:39, reused from bridge_detector),
//!     `ID_THRESH=0.70` (:40, reused), `MAX_LOCI=60` (:41);
//!   * `_members` (:72), `_recombinant_bridges` (:83), `split_block` (:132).
//!
//! NEW graph algorithms (deterministic):
//!   * `articulation_points` -- iterative Tarjan cut-vertices. The Python does
//!     `sorted(nx.articulation_points(G))`; networkx 3.6.1 `articulation_points`
//!     DEDUPLICATES its DFS generator (`seen` set), so the yielded value is exactly
//!     the graph-invariant cut-vertex SET -- which a standard Tarjan implementation
//!     reproduces regardless of neighbour order. Verified SET-equal to networkx on
//!     the `articulation_graphs` fixture (chains, cycles, trees, star, shared-vertex
//!     triangles, barbell, K4, multi-component, single node, bridges).
//!   * `components_excluding` -- connected components over the nodes NOT in a removed
//!     set (matching `nx.connected_components(G.copy(); remove_nodes_from(...))`,
//!     INCLUDING singleton components for now-isolated nodes), each sorted, sorted by
//!     first element (the Python `sorted((sorted(c) ...), key=lambda c: c[0])`).
//!
//! Verified byte-identical to the shipped Python against a golden fixture
//! (`testdata/recombinant_split_fixture.json`, generated by
//! `bench/gen_recombinant_split_fixture.py`, PYTHONHASHSEED=0); see the `#[test]`s.
//!
//! **STATUS:** OTHER-BINARY — family_define only; DEFAULT-ON there, opt out with --no-split-recombinants or RUSTLE_NO_SPLIT_RECOMBINANTS=1 (src/bin/family_define.rs:44-46 clap arg   (docs/MODULE_STATUS.md; assigned by reachability, not by this header)

