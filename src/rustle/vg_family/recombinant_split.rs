/// Indices of vg-split RECOMBINANT articulation bridges. Faithful port of
/// `_recombinant_bridges` (:83): for each articulation point `b` (ascending), the
/// components of `G\b` that touch `b`'s neighbours (sorted by min-member) are the
/// bridged sub-families; require `>= 2`. For each exon `i` of `b`, the sub-families it
/// SOLELY hits (`idv >= ID_THRESH`, single component) are counted; require `>= 2`
/// singly-hit sub-families (different exons -> different sub-families). Skip if any
/// neighbour colinearly covers `>= COLINEAR_COV` (a shared domain, not a mosaic); skip
/// if the sub-families are genomically colocated (readthrough chimera); require BOTH
/// involved sub-families annotated AND the minor block `>= 2` exons. Emit `b`.
fn recombinant_bridges(recs: &[Rec], best: &Tensor, graph: &LocusGraph) -> Vec<usize> {
    if graph.num_edges() == 0 {
        return Vec::new();
    }
    let adj = &graph.adj;
    let mut out: Vec<usize> = Vec::new();
    // sorted(nx.articulation_points(G)): BTreeSet iterates ascending == sorted.
    for b in articulation_points(adj) {
        let nbrs = &adj[b];
        let removed: BTreeSet<usize> = std::iter::once(b).collect();
        // components of G\b that intersect b's neighbours, sorted by min-member.
        let bridged: Vec<Vec<usize>> = components_excluding(adj, &removed)
            .into_iter()
            .filter(|c| c.iter().any(|m| nbrs.contains(m)))
            .collect();
        if bridged.len() < 2 {
            continue;
        }
        // comp id of each member
        let mut cid_of: HashMap<usize, usize> = HashMap::new();
        for (ci, comp) in bridged.iter().enumerate() {
            for &m in comp {
                cid_of.insert(m, ci);
            }
        }
        // per exon of b: which single sub-family it solely hits
        let mut single: HashMap<usize, usize> = HashMap::new();
        for i in 0..recs[b].exons.len() {
            let mut hit: BTreeSet<usize> = BTreeSet::new();
            for &m in nbrs {
                let (idv, _) = best.get(b, i, m);
                if idv >= ID_THRESH {
                    if let Some(&c) = cid_of.get(&m) {
                        hit.insert(c);
                    }
                }
            }
            if hit.len() == 1 {
                let c = *hit.iter().next().expect("hit has exactly one element");
                *single.entry(c).or_insert(0) += 1;
            }
        }
        if single.len() < 2 {
            continue; // NOT recombinant (needs different exons -> different subfams)
        }
        // best single-neighbour colinear cover (default 0.0; all covers are >= 0).
        let best_single = nbrs
            .iter()
            .map(|&m| colinear_cov(recs, best, b, m))
            .fold(0.0f64, f64::max);
        if best_single >= COLINEAR_COV {
            continue; // a neighbour colinearly covers the bridge -> not a mosaic
        }
        if subfams_colocated(recs, &bridged) {
            continue; // readthrough chimera (assembly artifact), not distributed
        }
        // HIGH-confidence: BOTH involved sub-families annotated + minor block >= 2 exons.
        let mut involved: Vec<usize> = single.keys().copied().collect();
        involved.sort_unstable();
        let minor = involved
            .iter()
            .map(|c| single[c])
            .min()
            .expect("involved is non-empty (single.len() >= 2)");
        let both_annotated = involved.iter().all(|&c| {
            let g = subfam_dom_gene(recs, &bridged[c]);
            g != "NA" && !g.is_empty()
        });
        if !(both_annotated && minor >= 2) {
            continue; // LOW confidence (NA-dominant sub-family / 1-exon minor block)
        }
        out.push(b);
    }
    out
}

