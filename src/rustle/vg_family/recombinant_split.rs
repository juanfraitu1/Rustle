/// Return a PARTITION of `block` (list of sorted DN-blocks): split along vg-split
/// recombinant bridges, or `[sorted(block)]` unchanged if none. Never loses a locus;
/// deterministic. Faithful port of `split_block` (:132) -- see the inline comments for
/// the bridge-assignment, skeleton-less attachment, and same-gene recall-safety guard.
pub fn split_block<F: ExonFetcher>(
    block: &[String],
    genes: &HashMap<String, GeneMeta>,
    gene_of_dn: &HashMap<String, String>,
    skel: &HashMap<(String, i64, i64), Vec<(i64, i64)>>,
    strand: &HashMap<String, String>,
    fa: &F,
) -> Vec<Vec<String>> {
    if block.len() < 3 {
        return vec![sorted_block(block)];
    }
    let members = members_of(block, genes, gene_of_dn);
    if members.len() < 3 || members.len() > MAX_LOCI {
        return vec![sorted_block(block)];
    }
    let recs = family_exons(&members, skel, strand, fa);
    if recs.len() < 3 {
        return vec![sorted_block(block)];
    }
    let best = exon_match_tensor(&recs);
    let graph = build_graph(&recs, &best);
    let bridge_idx = recombinant_bridges(&recs, &best, &graph);
    if bridge_idx.is_empty() {
        return vec![sorted_block(block)];
    }

    let dn_of: Vec<String> = recs.iter().map(|r| r.dn.clone()).collect();
    let bset: BTreeSet<usize> = bridge_idx.iter().copied().collect();
    // sub-families = connected components after removing ALL vg-split bridges.
    let subfams = components_excluding(&graph.adj, &bset);
    let mut subfam_dns: Vec<BTreeSet<String>> = subfams
        .iter()
        .map(|sf| sf.iter().map(|&i| dn_of[i].clone()).collect())
        .collect();

    // assign each bridge to its best-colinear sub-family (>= COLINEAR_COV to a member)
    // else its own singleton.
    for &b in &bridge_idx {
        let mut bestc = 0.0f64;
        let mut bestsf: isize = -1;
        for (si, sf) in subfams.iter().enumerate() {
            let c = sf
                .iter()
                .map(|&m| colinear_cov(&recs, &best, b, m))
                .fold(0.0f64, f64::max);
            if c > bestc {
                bestc = c;
                bestsf = si as isize;
            }
        }
        if bestsf >= 0 && bestc >= COLINEAR_COV {
            subfam_dns[bestsf as usize].insert(dn_of[b].clone());
        } else {
            subfam_dns.push(std::iter::once(dn_of[b].clone()).collect());
        }
    }

    // skeleton-less DNs (not in recs): attach to the FIRST sub-family sharing a
    // chromosome, else own singleton.
    let mut placed: BTreeSet<String> = BTreeSet::new();
    for s in &subfam_dns {
        for x in s {
            placed.insert(x.clone());
        }
    }
    for dn in sorted_block(block) {
        if placed.contains(&dn) {
            continue;
        }
        let mut tgt: isize = -1;
        if let Some(g) = genes.get(&dn) {
            let gchrom = g.chrom.as_str();
            for si in 0..subfam_dns.len() {
                let found = subfam_dns[si].iter().any(|x| {
                    genes.get(x).map(|gx| gx.chrom.as_str()) == Some(gchrom)
                });
                if found {
                    tgt = si as isize;
                    break;
                }
            }
        }
        if tgt >= 0 {
            subfam_dns[tgt as usize].insert(dn.clone());
        } else {
            subfam_dns.push(std::iter::once(dn.clone()).collect());
        }
        placed.insert(dn);
    }

    // result = sorted((sorted(s) for s in subfam_dns if s), key=first)
    let mut result: Vec<Vec<String>> = subfam_dns
        .iter()
        .filter(|s| !s.is_empty())
        .map(|s| s.iter().cloned().collect::<Vec<String>>())
        .collect();
    result.sort_by(|a, b| a[0].cmp(&b[0]));

    // RECALL-SAFETY GUARD: if the partition separates loci of the SAME gene into
    // different sub-families, REJECT the whole split (keep merged).
    if result.len() > 1 {
        let mut gene_parts: HashMap<String, BTreeSet<usize>> = HashMap::new();
        for (pi, part) in result.iter().enumerate() {
            for dn in part {
                if let Some(g) = gene_of_dn.get(dn) {
                    if g != "NA" {
                        gene_parts.entry(g.clone()).or_default().insert(pi);
                    }
                }
            }
        }
        if gene_parts.values().any(|pis| pis.len() >= 2) {
            return vec![sorted_block(block)];
        }
    }
    result
}

