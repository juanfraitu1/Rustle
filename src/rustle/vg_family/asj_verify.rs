    /// Little-endian IEEE-754 hex (`struct.pack("<d", x).hex()`) -> the f64 bit pattern.
    fn hex_le_to_bits(s: &str) -> u64 {
        assert_eq!(s.len(), 16, "expected 16 hex chars, got {s:?}");
        let mut b = [0u8; 8];
        for (i, byte) in b.iter_mut().enumerate() {
            *byte = u8::from_str_radix(&s[i * 2..i * 2 + 2], 16).expect("hex byte");
        }
        u64::from_le_bytes(b)
    }

    /// FAST, always-on: the pure per-row logic (`dist`, `high_confidence`, `py_float_str`) and
    /// the MQ0_THR / transversion boundaries — NO BAM needed. Uses the fixture's CAPTURED
