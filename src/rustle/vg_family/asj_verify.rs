// ===========================================================================
// py_float_str  — reproduce CPython str(float)
// ===========================================================================

/// Reproduce CPython's `str(float)` (shortest round-trip repr) for the frac_mq0 range.
///
/// Rust's `f64: Display` already emits the shortest round-trip decimal, identical to CPython
/// digit-for-digit; the only divergences are (1) Python appends `.0` to an integer-valued
/// float and (2) Python switches to exponential notation for `|x| < 1e-4` (or very large).
/// Fraction values are in `[0, 1)` with the smallest nonzero `~8e-3`, so (2) never fires; this
/// function only needs to restore the `.0` (and use CPython's `nan`/`inf` spellings). The
/// byte-parity test independently asserts the f64 bits, so correctness never rests on this
/// string alone.
pub fn py_float_str(x: f64) -> String {
    if x.is_nan() {
        return "nan".to_string();
    }
    if x.is_infinite() {
        return if x < 0.0 { "-inf".to_string() } else { "inf".to_string() };
    }
    let s = format!("{x}");
    // Rust prints integer-valued floats without a fractional part ("0"); Python writes "0.0".
    if s.contains('.') || s.contains('e') || s.contains('E') {
        s
    } else {
        format!("{s}.0")
    }
}

// ===========================================================================
// dist / high_confidence  — pure per-row logic (bench/asj_verify.py:60,65)
