/// Anchor→junction distance `min(|anchor - donor|, |anchor - acceptor|)`.
/// Python `bench/asj_verify.py:60  r["dist"] = min(abs(anc - d), abs(anc - a))`.
pub fn dist_of(anchor: i64, donor: i64, acceptor: i64) -> i64 {
    (anchor - donor).abs().min((anchor - acceptor).abs())
}

/// `high_confidence = (anchor_type == "transversion") AND (frac_mq0 < MQ0_THR)`.
/// Python `bench/asj_verify.py:95  h = int(r["anchor_type"] == "transversion" and r["frac_mq0"] < MQ0_THR)`.
pub fn is_high_confidence(anchor_type: &str, frac_mq0: f64) -> bool {
    anchor_type == "transversion" && frac_mq0 < MQ0_THR
}

