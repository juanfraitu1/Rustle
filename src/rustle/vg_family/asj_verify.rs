/// One parsed ASJ-call row: every column echoed to the verified TSV (as its RAW string, since
/// Python writes `str(r[c])` over dict-of-strings) plus the parsed integer anchor/donor/acceptor
/// the `dist`/`frac_mq0` computation needs.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct CallRow {
    /// `gene` column (echoed verbatim).
    pub gene: String,
    /// `chrom` column (echoed; also the fetch contig).
    pub chrom: String,
    /// `anchor` column, RAW string (echoed verbatim).
    pub anchor: String,
    /// `alleleX` column (echoed verbatim).
    pub allele_x: String,
    /// `alleleY` column (echoed verbatim).
    pub allele_y: String,
    /// `donor` column, RAW string (echoed verbatim).
    pub donor: String,
    /// `acceptor` column, RAW string (echoed verbatim).
    pub acceptor: String,
    /// `psiX` column (echoed verbatim).
    pub psi_x: String,
    /// `psiY` column (echoed verbatim).
    pub psi_y: String,
    /// `dPSI` column (echoed verbatim).
    pub d_psi: String,
    /// `q` column (echoed verbatim — the input `pval` column is NOT emitted).
    pub q: String,
    /// `anchor_type` column ("transversion" / "transition"); drives `high_confidence`.
    pub anchor_type: String,
    /// `int(anchor)` — the fetch position AND the `dist` anchor point.
    pub anchor_i: i64,
    /// `int(donor)`.
    pub donor_i: i64,
    /// `int(acceptor)`.
    pub acceptor_i: i64,
}

/// Parse the ASJ-calls TSV text into [`CallRow`]s, faithful to `bench/asj_verify.py:45-48`
/// (`hdr = split header; rows = dict(zip(hdr, split))` per line). Columns are located BY NAME
/// (robust to reordering); `anchor`/`donor`/`acceptor` are parsed to `i64`. Python does not
/// skip blank lines here, and the shipped file has none; a genuinely empty line would fail to
/// parse (mirroring Python's `KeyError`), which cannot occur on the real input.
pub fn parse_calls(text: &str) -> Result<Vec<CallRow>> {
    let mut lines = text.lines();
    let hdr_line = lines.next().context("empty ASJ-calls TSV (no header)")?;
    let hdr: Vec<&str> = hdr_line.split('\t').collect();
    let col = |name: &str| -> Result<usize> {
        hdr.iter()
            .position(|&c| c == name)
            .with_context(|| format!("ASJ-calls header missing column {name:?}"))
    };
    let (ci_gene, ci_chrom, ci_anchor, ci_ax, ci_ay, ci_donor, ci_acceptor, ci_psix, ci_psiy, ci_dpsi, ci_q, ci_at) = (
        col("gene")?,
        col("chrom")?,
        col("anchor")?,
        col("alleleX")?,
        col("alleleY")?,
        col("donor")?,
        col("acceptor")?,
        col("psiX")?,
        col("psiY")?,
        col("dPSI")?,
        col("q")?,
        col("anchor_type")?,
    );

    let mut out = Vec::new();
    for line in lines {
        let f: Vec<&str> = line.split('\t').collect();
        let get = |i: usize| -> &str { f.get(i).copied().unwrap_or("") };
        let anchor = get(ci_anchor);
        let donor = get(ci_donor);
        let acceptor = get(ci_acceptor);
        out.push(CallRow {
            gene: get(ci_gene).to_string(),
            chrom: get(ci_chrom).to_string(),
            anchor: anchor.to_string(),
            allele_x: get(ci_ax).to_string(),
            allele_y: get(ci_ay).to_string(),
            donor: donor.to_string(),
            acceptor: acceptor.to_string(),
            psi_x: get(ci_psix).to_string(),
            psi_y: get(ci_psiy).to_string(),
            d_psi: get(ci_dpsi).to_string(),
            q: get(ci_q).to_string(),
            anchor_type: get(ci_at).to_string(),
            anchor_i: anchor.parse().with_context(|| format!("anchor int in {line:?}"))?,
            donor_i: donor.parse().with_context(|| format!("donor int in {line:?}"))?,
            acceptor_i: acceptor.parse().with_context(|| format!("acceptor int in {line:?}"))?,
        });
    }
    Ok(out)
}

