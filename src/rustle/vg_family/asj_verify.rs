/// The confound-control result for one call: the two appended metrics, the `high_confidence`
/// flag, and the EXACT verified-TSV line (data columns + `\t{high_confidence}`).
#[derive(Clone, Debug, PartialEq)]
pub struct VerifiedRow {
    /// `min(|anchor-donor|, |anchor-acceptor|)`.
    pub dist: i64,
    /// The anchor's MAPQ-0 fraction (shared across all calls with the same `(chrom, anchor)`).
    pub frac_mq0: f64,
    /// `anchor_type == "transversion" && frac_mq0 < MQ0_THR`.
    pub high_confidence: bool,
    /// The exact tab-joined verified-TSV line for this call (no trailing newline).
    pub line: String,
}

/// A reusable ASJ-verify engine: parses the `.bai` index + header ONCE (like
/// [`super::asj_strand_bias::StrandBiasEngine`] / [`super::denovo_assemble::BamIndexCache`]),
/// then answers `frac_mq0_at` per unique anchor with the cached index.
pub struct AsjVerifyEngine {
    bam_path: String,
    header: noodles_sam::Header,
    index: noodles_bam::bai::Index,
}

impl AsjVerifyEngine {
    /// Open `{bam_path}` and parse its header + `{bam_path}.bai`. Errors (so the caller/test
    /// can skip) when the index is missing.
    pub fn open(bam_path: &str) -> Result<Self> {
        let bai_path = format!("{bam_path}.bai");
        anyhow::ensure!(
            Path::new(&bai_path).exists(),
            "AsjVerifyEngine needs a .bai index next to {bam_path} (expected {bai_path})"
        );
        let mut reader = noodles_bam::io::reader::Builder::default().build_from_path(bam_path)?;
        let header = reader.read_header()?;
        let index = noodles_bam::bai::read(&bai_path)?;
        Ok(Self { bam_path: bam_path.to_string(), header, index })
    }

    /// MAPQ-0 fraction over the primary reads covering the single base `pos` (0-based).
    /// Faithful port of `bench/asj_verify.py::frac_mq0_at`.
    ///
    /// pysam `fetch(chrom, pos, pos+1)` (0-based half-open) == the 1-based inclusive region
    /// `{chrom}:{pos+1}-{pos+1}`; both return the reads overlapping that base in coordinate
    /// (BAM file) order. Per read: skip `is_unmapped`/`is_secondary`/`is_supplementary`;
    /// else `n += 1` and `z += 1` when `mapping_quality == 0`; **break once `n >= CAP`** so
    /// only the first 600 primary reads count (identical prefix under identical order ⇒
    /// identical `z`/`n`). Returns `z/n` (exact small-int f64 division) or `0.0` if `n == 0`.
    ///
    /// MAPQ-255 (SAM "missing", noodles `mapping_quality() == None`) is treated as NON-zero,
    /// matching pysam's `mapping_quality == 255 != 0` (minimap2 never emits 255, so this
    /// cannot affect parity on `GGO.bam`; the choice keeps the port correct in general).
    pub fn frac_mq0_at(&self, chrom: &str, pos: i64) -> Result<f64> {
        let mut reader = noodles_bam::io::reader::Builder::default().build_from_path(&self.bam_path)?;
        let region: noodles_core::Region = format!("{chrom}:{}-{}", pos + 1, pos + 1).parse()?;
        let query = reader.query(&self.header, &self.index, &region)?;
        let (mut n, mut z) = (0i64, 0i64);
        for result in query {
            let record = result?;
            let rb = RecordBuf::try_from_alignment_record(&self.header, &record)?;
            let flags = rb.flags();
            if flags.is_unmapped() || flags.is_secondary() || flags.is_supplementary() {
                continue;
            }
            n += 1;
            // mapping_quality == 0 (Some(0)); None == MAPQ-255 "missing" ⇒ NOT zero.
            if rb.mapping_quality().map(|q| q.get() == 0).unwrap_or(false) {
                z += 1;
            }
            if n >= CAP {
                break;
            }
        }
        Ok(if n > 0 { z as f64 / n as f64 } else { 0.0 })
    }

    /// Run the confound control over every parsed call, replicating `main`:
    ///  1. dedup unique `(chrom, anchor)` anchors in first-occurrence order, computing
    ///     `frac_mq0_at` ONCE each;
    ///  2. per row: `dist`, the anchor's `frac_mq0`, `high_confidence`, and the exact
    ///     verified-TSV line.
    pub fn run(&self, calls: &[CallRow]) -> Result<Vec<VerifiedRow>> {
        // (1) unique-anchor frac_mq0 map (first-occurrence order, one fetch per anchor).
        let mut mq0: std::collections::HashMap<(String, i64), f64> = std::collections::HashMap::new();
        for c in calls {
            let key = (c.chrom.clone(), c.anchor_i);
            if !mq0.contains_key(&key) {
                let f = self.frac_mq0_at(&c.chrom, c.anchor_i)?;
                mq0.insert(key, f);
            }
        }
        // (2) per-row output.
        let mut out = Vec::with_capacity(calls.len());
        for c in calls {
            let frac = mq0[&(c.chrom.clone(), c.anchor_i)];
            let dist = dist_of(c.anchor_i, c.donor_i, c.acceptor_i);
            let hc = is_high_confidence(&c.anchor_type, frac);
            out.push(VerifiedRow { dist, frac_mq0: frac, high_confidence: hc, line: c.verified_line(dist, frac, hc) });
        }
        Ok(out)
    }
}

impl CallRow {
    /// Build the exact verified-TSV line: the 12 echoed columns (RAW strings, in output order)
    /// then computed `dist` and `frac_mq0` (`str(float)`), then `\t{high_confidence as int}`.
    /// `bench/asj_verify.py:91-96`.
    pub fn verified_line(&self, dist: i64, frac_mq0: f64, high_confidence: bool) -> String {
        format!(
            "{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}",
            self.gene,
            self.chrom,
            self.anchor,
            self.allele_x,
            self.allele_y,
            self.donor,
            self.acceptor,
            self.psi_x,
            self.psi_y,
            self.d_psi,
            self.q,
            self.anchor_type,
            dist,
            py_float_str(frac_mq0),
            high_confidence as u8,
        )
    }
}

