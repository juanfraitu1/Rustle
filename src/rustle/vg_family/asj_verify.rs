//! O3 ASJ VERIFY layer: the deterministic CONFOUND CONTROL over the ASJ calls.
//!
//! Faithful Rust port of `bench/asj_verify.py`. The O3 ASJ *core* (calling the
//! allele-specific junctions themselves) lives in [`super::allele_specific_junctions`], and
//! the strand-bias filter is [`super::asj_strand_bias`]; this module ports the SECOND
//! analysis layer that runs ON TOP of the shipped `asj_calls.tsv`. It attaches to every call
//! two confound-control columns the raw FDR cannot see:
//!  * `frac_mq0` — the MAPQ-0 fraction at the anchor SNP. A HIGH fraction flags a
//!    COLLAPSED-PARALOG MASQUERADE (the two "alleles" are really paralog copies, so the
//!    "allele-specific" junctions are copy-specific isoforms); a LOW fraction (uniquely
//!    mapped) means genuine within-gene heterozygosity.
//!  * `dist` — the anchor→junction distance (a mechanism-plausibility proxy; PROXIMITY only,
//!    NOT "on the canonical dinucleotide" — see `bench/asj_motif_check.py`).
//! and marks the confound-controlled `high_confidence` set (transversion anchor AND uniquely
//! mapped). It writes `bench/asj_calls_verified.tsv` (the print()/summary block in the Python
//! is analysis-only — this port reproduces the WRITTEN TSV, not the stdout).
//!
//! ## What is ported (Python = ground truth)
//!  * [`AsjVerifyEngine::frac_mq0_at`] (`bench/asj_verify.py:30`): `fetch(chrom, pos, pos+1)`,
//!    skip `is_unmapped`(0x4)/`is_secondary`(0x100)/`is_supplementary`(0x800), `n += 1`,
//!    `z += 1` when `mapping_quality == 0`, and **BREAK when `n >= 600`** — an
//!    order-dependent cap over pysam's coordinate-order fetch (reproduced below).
//!    Returns `z/n` (an exactly-representable small-int f64 division) or `0.0` when `n == 0`.
//!  * [`parse_calls`] + [`AsjVerifyEngine::run`] (`main`, `:43`): read the calls TSV, DEDUP
//!    unique `(chrom, int(anchor))` anchors (compute `frac_mq0_at` ONCE per anchor,
//!    first-occurrence order), then per row `dist = min(|anchor-donor|, |anchor-acceptor|)`,
//!    `frac_mq0 = the anchor's value`, and
//!    `high_confidence = int(anchor_type == "transversion" && frac_mq0 < MQ0_THR)`, emitting
//!    the verified row with columns `[gene, chrom, anchor, alleleX, alleleY, donor, acceptor,
//!    psiX, psiY, dPSI, q, anchor_type, dist, frac_mq0] + high_confidence` (the input `pval`
//!    column is dropped; `q` is kept).
//!
//! ## The 600-cap and coordinate order (parity vs pysam)
//! `pysam.fetch` yields the reads that overlap `[pos, pos+1)` in coordinate (BAM file) order;
//! noodles' indexed `query` yields the same records in the same file order. Because the cap
//! keeps the FIRST 600 primary (non-unmapped/secondary/supplementary) reads, both implementations
//! process the identical prefix, so `z`/`n` — hence `frac_mq0` — are bit-identical even when an
//! anchor exceeds 600 reads. (On `GGO.bam` the fixture records whether any anchor hits the cap.)
//!
//! ## The frac_mq0 float→string reproduction
//! The TSV writes `str(r["frac_mq0"])` — CPython's shortest round-trip `float→str`. Rust's
//! `f64: Display` also emits the shortest round-trip decimal, digit-for-digit identical to
//! CPython for every value here; the ONLY difference is that Python appends `.0` to an
//! integer-valued float (`0.0`) while Rust prints `0`. [`py_float_str`] restores that `.0`
//! (and CPython's `nan`/`inf` spellings), reproducing `str(float)` EXACTLY for the frac_mq0
//! range `[0, 1)` (all values `>= ~8e-3`, so neither implementation switches to exponential
//! notation, which is Python's only other divergence — disclosed here). The byte-parity test
//! ALSO asserts the raw f64 bits independently, so parity never relies on the string alone.
//!
//! Byte-parity is enforced against `testdata/asj_verify_fixture.json` (generated by
//! `bench/gen_asj_verify_fixture.py`, PYTHONHASHSEED=0, over the real `GGO.bam`): the live
//! `#[test]` re-fetches the BAM and recomputes every anchor's `frac_mq0` (bits + string) and
//! every call's `dist`/`high_confidence`/written line, asserting `== Python`. A FAST,
//! always-on test pins the pure `dist`/`high_confidence`/`py_float_str` logic without the BAM.

