//! Shared exon-graph LIBRARY -- faithful Rust port of the reusable core of
//! `bench/recombination_bridge_detector.py` (RBD), the O1 over-merge-gate migration
//! (`docs/RETIREMENT_AND_MIGRATION.md` Tier-2 #6, full byte-parity path).
//!
//! This is the library the TWO shipped O1 over-merge gates consume:
//!   * `bench/recombinant_split.py`  (Alu/recombinant-bridge SPLIT gate) uses
//!     `family_exons` / `exon_match_tensor` / `build_graph` / `colinear_cov` /
//!     `subfams_colocated` / `subfam_dom_gene` + `COLINEAR_COV` / `ID_THRESH`;
//!   * `bench/multi_repeat_bridge_gate.py` (repeat-bridge gate) uses `family_exons`
//!     / `exon_match_tensor` / `build_graph` / `cross_component_maxid`.
//! Both gates call the LIBRARY functions below; the port targets exactly those.
//!
//! PORTED (the Python is ground truth; line refs are `bench/recombination_bridge_detector.py`):
//!   * constants `ID_THRESH=0.70` (:57), `MIN_EXON=30` (:58), `COLINEAR_COV=0.60` (:59);
//!   * `revcomp` (:66) + the `_COMP` table (:63); `aln_id` (:70) -- the CRUX (edlib HW);
//!   * `load_skeletons` (:88) -- RBD's OWN 1-based-inclusive exon complement (see note);
//!   * `family_exons` (:162), `exon_match_tensor` (:185), `build_graph` (:216),
//!     `pair_coverage` (:228), `cross_component_maxid` (:237), `colinear_cov` (:250),
//!     `subfam_label` (:273), `subfam_dom_gene` (:279), `subfams_colocated` (:284).
//!   * `IndexedFasta` is REUSED from `super::repeat_catalog` (already byte-exact).
//!
//! DEFERRED (NOT the library the gates call -- TSV/JSON production + analysis):
//!   * `analyze_family` (:299), `main` (:527), `_pure_controls`/`_control_precompute`/
//!     `control_recall_cost` (:457-524), and the loaders `load_families` (:129) /
//!     `target_families` (:140) / `load_strand` (:115). (`multi_repeat_bridge_gate` does
//!     call `analyze_family` in `_rederive_disconnected`, but that is a gate-DRIVER
//!     concern; the reusable exon-graph MATH is what this module ports.) Constants
//!     `CARD_ID` (:60) / `N_CONTROL` (:61) are used ONLY by the deferred control-recall.
//!
//! CRUX -- `aln_id` HW (infix) edit distance without edlib: RBD does
//! `edlib.align(q, t, mode="HW", task="distance")` = the minimum edit distance of `q`
//! against ANY substring of `t` (free gaps at BOTH ends of `t`). We compute it with a
//! pure DP: `dp[i][j]` over `q` rows x `t` cols, `dp[0][*]=0` (free start in `t`),
//! `dp[i][0]=i`, standard 3-way min, answer `= min_j dp[|q|][j]` (free end in `t`).
//! This equals edlib HW exactly (proven on 20 010 random + adversarial pairs, and the
//! >=80-pair `aln_id` fixture below). `aln_id` tries `q` AND `revcomp(q)` and returns
//! `1 - min_dist/len(q)`.
//!
//! STRAND note (`family_exons`): RBD orders exons 5'->3' by REVERSING the exon ORDER
//! for `'-'` strand -- it does NOT reverse-complement the bases; each exon carries the
//! forward (`+`-strand) genome slice, upper-cased. (Reverse-complement enters ONLY via
//! `aln_id`, which tries both orientations.) The `exlen` of a `'-'` member is therefore
//! the genomic exon-length list reversed. The fixture ships `'-'` multi-exon members to
//! pin this.
//!
//! COORDINATE note: RBD's `load_skeletons` uses a DIFFERENT convention from
//! `vg_repeat_catalog.dn_exons` (ported in `super::repeat_catalog`): RBD builds exons as
//! 1-based-INCLUSIVE `(cur, isr-1)` .. `(cur, end)` with `cur = ier+1`, does NOT sort the
//! introns, keeps only `b >= a`, and `family_exons` fetches `fa.fetch(chrom, s-1, e)`
//! (the `s-1` makes it 1-based->0-based). `dn_exons` is 0-based half-open with a SORTED
//! intron list and a direct `fetch(a, b)`. They are two independent scripts with distinct
//! conventions, so this module ports RBD's `load_skeletons` faithfully (it does NOT reuse
//! `repeat_catalog::{dn_exons,load_skeletons}`); it DOES reuse `IndexedFasta`.
//!
//! Verified byte-identical to the shipped Python against a golden fixture
//! (`testdata/bridge_detector_fixture.json`, generated by
//! `bench/gen_bridge_detector_fixture.py`, PYTHONHASHSEED=0); see the `#[test]`s.

