/// `best[(mi, ei, nj)] = (id, exon_index_in_nj)` -- the best HW match of exon `ei` of
/// member `mi` against member `nj`. Stores entries in Python `dict` INSERTION order
/// (a outer, b middle, i inner) for exact iteration parity, plus a lookup map with the
/// `(0.0, -1)` default of the Python `best.get(...)`.
#[derive(Debug, Default)]
pub struct Tensor {
    /// `(a, i, b, id, j)` in insertion order (mirrors `best.items()`).
    pub entries: Vec<(usize, usize, usize, f64, i64)>,
    map: HashMap<(usize, usize, usize), (f64, i64)>,
}

impl Tensor {
    /// `best.get((a, i, b), (0.0, -1))`.
    pub fn get(&self, a: usize, i: usize, b: usize) -> (f64, i64) {
        self.map.get(&(a, i, b)).copied().unwrap_or((0.0, -1))
    }
}

/// Pairwise exon-match tensor via `aln_id` + length prefilter.
///
/// Faithful port of `exon_match_tensor` (:185): for every ordered pair `a != b`, for
/// every exon `i` of `a` with `len >= MIN_EXON`, scan every exon `j` of `b` with
/// `len >= MIN_EXON`; skip if `min(len)/max(len) < 0.5`; align the SHORTER as the query
/// (`aln_id(qa, tb)` if `len(qa) <= len(tb)` else `aln_id(tb, qa)`); keep the strict-max
/// `(id, j)` (init `(0.0, -1)`); store `best[(a, i, b)]`.
pub fn exon_match_tensor(recs: &[Rec]) -> Tensor {
    let n = recs.len();
    let mut t = Tensor::default();
    for a in 0..n {
        for b in 0..n {
            if a == b {
                continue;
            }
            let ea = &recs[a].exons;
            let eb = &recs[b].exons;
            for (i, qa) in ea.iter().enumerate() {
                if qa.len() < MIN_EXON {
                    continue;
                }
                let mut bid = 0.0f64;
                let mut bj: i64 = -1;
                for (j, tb) in eb.iter().enumerate() {
                    if tb.len() < MIN_EXON {
                        continue;
                    }
                    let (lo, hi) = if qa.len() <= tb.len() {
                        (qa.len(), tb.len())
                    } else {
                        (tb.len(), qa.len())
                    };
                    // Python: if lo / hi < 0.5: continue   (float division)
                    if (lo as f64) / (hi as f64) < 0.5 {
                        continue;
                    }
                    let idv = if qa.len() <= tb.len() {
                        aln_id(qa, tb)
                    } else {
                        aln_id(tb, qa)
                    };
                    if idv > bid {
                        bid = idv;
                        bj = j as i64;
                    }
                }
                t.entries.push((a, i, b, bid, bj));
                t.map.insert((a, i, b), (bid, bj));
            }
        }
    }
    t
}

