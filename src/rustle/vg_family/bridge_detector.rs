/// One member locus fed to `family_exons` (`{dn, gene, chrom, start, end}`; the dict
/// `_members` builds in the gates). `gene` is used by the subfam helpers.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Member {
    pub dn: String,
    pub gene: String,
    pub chrom: String,
    pub start: i64,
    pub end: i64,
}

/// Parse the denovo-skeletons TSV text into RBD's `{(chrom,start,end) -> exon list}`,
/// where each exon is a 1-based-INCLUSIVE `(a, b)` interval.
///
/// Faithful port of `load_skeletons` (:88): skip the header, split on `\t`, pad short
/// rows to 6 fields (`(t + [""]*6)[:6]`), read `chrom,start,end,introns = f0,f1,f2,f5`,
/// parse `introns = "a-b;c-d;..."` into `iv` WITHOUT sorting, then walk the complement
/// `cur=start`: for each `(isr, ier)` push exon `(cur, isr-1)` and set `cur = ier+1`;
/// finally push `(cur, end)`; keep only exons with `b >= a`.
pub fn parse_skeletons(text: &str) -> HashMap<(String, i64, i64), Vec<(i64, i64)>> {
    let mut skel = HashMap::new();
    let mut lines = text.lines();
    lines.next(); // header
    for ln in lines {
        // Python: t = line.rstrip("\n").split("\t"); if len<6: t=(t+[""]*6)[:6]
        let mut f: Vec<&str> = ln.split('\t').collect();
        if f.len() < 6 {
            while f.len() < 6 {
                f.push("");
            }
        }
        let (chrom, start, end, introns) = (f[0], f[1], f[2], f[5]);
        let start: i64 = match start.parse() {
            Ok(v) => v,
            Err(_) => continue,
        };
        let end: i64 = match end.parse() {
            Ok(v) => v,
            Err(_) => continue,
        };
        // iv = [(a,b) for seg in introns.split(";")] IF introns else []   (NO sort)
        let mut iv: Vec<(i64, i64)> = Vec::new();
        if !introns.is_empty() {
            for seg in introns.split(';') {
                let mut it = seg.split('-');
                let a: i64 = it
                    .next()
                    .expect("intron token left field")
                    .parse()
                    .expect("intron start parses");
                let b: i64 = it
                    .next()
                    .expect("intron token right field")
                    .parse()
                    .expect("intron end parses");
                iv.push((a, b));
            }
        }
        let mut exons: Vec<(i64, i64)> = Vec::new();
        let mut cur = start;
        for (isr, ier) in iv {
            exons.push((cur, isr - 1));
            cur = ier + 1;
        }
        exons.push((cur, end));
        exons.retain(|&(a, b)| b >= a);
        skel.insert((chrom.to_string(), start, end), exons);
    }
    skel
}

/// Read + parse the denovo-skeletons TSV file (see `parse_skeletons`).
pub fn load_skeletons(path: &str) -> std::io::Result<HashMap<(String, i64, i64), Vec<(i64, i64)>>> {
    Ok(parse_skeletons(&std::fs::read_to_string(path)?))
}

