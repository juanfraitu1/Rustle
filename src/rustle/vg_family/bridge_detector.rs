/// A per-member exon record (transcript 5'->3' order). Faithful to the Python dict
/// (`dn, gene, chrom, start, end, strand, exons, exlen`).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct Rec {
    pub dn: String,
    pub gene: String,
    pub chrom: String,
    pub start: i64,
    pub end: i64,
    pub strand: String,
    /// exon sequences (upper-cased, forward-strand bases), in transcript 5'->3' order
    pub exons: Vec<Vec<u8>>,
    /// `[len(x) for x in exons]`
    pub exlen: Vec<usize>,
}

/// Genome-slice fetcher matching `pysam.FastaFile.fetch(chrom, start, end)` on 0-based
/// half-open coordinates (returns bytes verbatim, case-carrying). `IndexedFasta`
/// implements it; tests supply a mock backed by the fixture's captured slices.
pub trait ExonFetcher {
    fn fetch(&self, chrom: &str, start: i64, end: i64) -> Option<Vec<u8>>;
}

impl ExonFetcher for IndexedFasta {
    fn fetch(&self, chrom: &str, start: i64, end: i64) -> Option<Vec<u8>> {
        IndexedFasta::fetch(self, chrom, start, end)
    }
}

/// Build a family's per-member exon records (transcript order). Drops members whose
/// `(chrom,start,end)` skeleton is absent (Python `if exons is None: continue`).
///
/// Faithful port of `family_exons` (:162): `st = strand.get(dn, "+")`; transcript order
/// = exon indices, REVERSED iff `st == "-"`; each exon's sequence is
/// `fa.fetch(chrom, s-1, e).upper()` (forward-strand bases, upper-cased -- NOT
/// reverse-complemented). `exlen = [len(x) for x in seqs]`.
pub fn family_exons<F: ExonFetcher>(
    members: &[Member],
    skel: &HashMap<(String, i64, i64), Vec<(i64, i64)>>,
    strand: &HashMap<String, String>,
    fa: &F,
) -> Vec<Rec> {
    let mut recs = Vec::new();
    for m in members {
        let key = (m.chrom.clone(), m.start, m.end);
        let exons = match skel.get(&key) {
            None => continue,
            Some(e) => e,
        };
        let st = strand.get(&m.dn).map(|s| s.as_str()).unwrap_or("+");
        // transcript 5'->3' order (reverse the exon ORDER for '-')
        let mut order: Vec<usize> = (0..exons.len()).collect();
        if st == "-" {
            order.reverse();
        }
        let mut seqs: Vec<Vec<u8>> = Vec::with_capacity(order.len());
        for gi in order {
            let (s, e) = exons[gi];
            let raw = fa.fetch(&m.chrom, s - 1, e).unwrap_or_default();
            let up: Vec<u8> = raw.iter().map(|b| b.to_ascii_uppercase()).collect();
            seqs.push(up);
        }
        let exlen = seqs.iter().map(|x| x.len()).collect();
        recs.push(Rec {
            dn: m.dn.clone(),
            gene: m.gene.clone(),
            chrom: m.chrom.clone(),
            start: m.start,
            end: m.end,
            strand: st.to_string(),
            exons: seqs,
            exlen,
        });
    }
    recs
}

