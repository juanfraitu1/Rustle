/// The intra-family LOCUS graph: nodes `0..n`, an undirected edge `(a,b)` iff some exon
/// match hits `id >= ID_THRESH`, plus `edge_exons[(a,b)] = [exon i of a that hit b]` in
/// tensor-insertion order.
#[derive(Debug)]
pub struct LocusGraph {
    pub n: usize,
    /// adjacency (undirected), deterministic ordered sets
    pub adj: Vec<BTreeSet<usize>>,
    /// directed `(a,b) -> [i,...]` in insertion order (the Python `edge_exons`)
    pub edge_exons: Vec<((usize, usize), Vec<usize>)>,
}

impl LocusGraph {
    pub fn num_edges(&self) -> usize {
        self.adj.iter().enumerate().map(|(u, s)| s.iter().filter(|&&v| v > u).count()).sum()
    }

    pub fn neighbors(&self, u: usize) -> &BTreeSet<usize> {
        &self.adj[u]
    }

    /// Sorted, deduplicated undirected edge list `(u<v)` -- matches Python
    /// `sorted({tuple(sorted((u,v))) for u,v in G.edges()})`.
    pub fn edges(&self) -> Vec<(usize, usize)> {
        let mut out = Vec::new();
        for u in 0..self.n {
            for &v in &self.adj[u] {
                if v > u {
                    out.push((u, v));
                }
            }
        }
        out.sort_unstable();
        out
    }

    /// Connected components as sorted lists, sorted by first element -- matches the
    /// gates' `sorted((sorted(c) for c in nx.connected_components(G)), key=lambda c:c[0])`.
    /// Deterministic BFS in ascending node order.
    pub fn connected_components(&self) -> Vec<Vec<usize>> {
        let mut seen = vec![false; self.n];
        let mut comps: Vec<Vec<usize>> = Vec::new();
        for s in 0..self.n {
            if seen[s] {
                continue;
            }
            let mut stack = vec![s];
            seen[s] = true;
            let mut comp = Vec::new();
            while let Some(u) = stack.pop() {
                comp.push(u);
                for &v in &self.adj[u] {
                    if !seen[v] {
                        seen[v] = true;
                        stack.push(v);
                    }
                }
            }
            comp.sort_unstable();
            comps.push(comp);
        }
        comps.sort_by(|a, b| a[0].cmp(&b[0]));
        comps
    }
}

/// Build the locus graph from the tensor (`build_graph`, :216). Iterates the tensor in
/// insertion order so `edge_exons` list order matches Python `best.items()`.
pub fn build_graph(recs: &[Rec], t: &Tensor) -> LocusGraph {
    let n = recs.len();
    let mut adj: Vec<BTreeSet<usize>> = vec![BTreeSet::new(); n];
    let mut ee_index: HashMap<(usize, usize), usize> = HashMap::new();
    let mut edge_exons: Vec<((usize, usize), Vec<usize>)> = Vec::new();
    for &(a, i, b, idv, _j) in &t.entries {
        if idv >= ID_THRESH {
            adj[a].insert(b);
            adj[b].insert(a);
            // edge_exons[(a,b)].append(i)  (directed key, insertion order)
            match ee_index.get(&(a, b)) {
                Some(&k) => edge_exons[k].1.push(i),
                None => {
                    ee_index.insert((a, b), edge_exons.len());
                    edge_exons.push(((a, b), vec![i]));
                }
            }
        }
    }
    LocusGraph { n, adj, edge_exons }
}

