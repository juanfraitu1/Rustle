/// Fraction of `a`'s exons (`>= MIN_EXON`) with an `id >= ID_THRESH` match to some exon
/// of `b` (`pair_coverage`, :228).
pub fn pair_coverage(recs: &[Rec], t: &Tensor, a: usize, b: usize) -> f64 {
    let ne: Vec<usize> = recs[a]
        .exons
        .iter()
        .enumerate()
        .filter(|(_, s)| s.len() >= MIN_EXON)
        .map(|(i, _)| i)
        .collect();
    if ne.is_empty() {
        return 0.0;
    }
    let hit = ne.iter().filter(|&&i| t.get(a, i, b).0 >= ID_THRESH).count();
    hit as f64 / ne.len() as f64
}

/// `round(x, 3)` matching CPython's `float.__round__` (correctly-rounded decimal, ties
/// to even). Verified to equal Rust `format!("{:.3}", x)` + parse (see unit test).
fn round3(x: f64) -> f64 {
    if !x.is_finite() {
        return x;
    }
    format!("{:.3}", x).parse::<f64>().expect("3-decimal format parses")
}

/// Max best-exon identity BETWEEN distinct components, `round`ed to 3 dp
/// (`cross_component_maxid`, :237). `comps` are node-index groups; each is sorted
/// internally (Python `comps = [sorted(c) for c in comps]`).
pub fn cross_component_maxid(recs: &[Rec], t: &Tensor, comps: &[Vec<usize>]) -> f64 {
    let sorted_comps: Vec<Vec<usize>> = comps
        .iter()
        .map(|c| {
            let mut c = c.clone();
            c.sort_unstable();
            c
        })
        .collect();
    let mut mx = 0.0f64;
    for ci in 0..sorted_comps.len() {
        for cj in (ci + 1)..sorted_comps.len() {
            for &a in &sorted_comps[ci] {
                for &b in &sorted_comps[cj] {
                    for i in 0..recs[a].exons.len() {
                        let v = t.get(a, i, b).0;
                        if v > mx {
                            mx = v;
                        }
                    }
                }
            }
        }
    }
    round3(mx)
}

/// Longest order-preserving matched-exon chain of bridge `b` covered by neighbour `nn`,
/// divided by `n_exons(b)` (`colinear_cov`, :250). LIS is NON-decreasing (Python
/// `bisect_right`), over `j` in increasing-`i` order.
pub fn colinear_cov(recs: &[Rec], t: &Tensor, b: usize, nn: usize) -> f64 {
    let k = recs[b].exons.len();
    // pairs (i, j) for i with an id>=ID_THRESH, j>=0 match; sorted by (i,j) == by i.
    let mut pairs: Vec<(usize, i64)> = Vec::new();
    for i in 0..k {
        let (idv, j) = t.get(b, i, nn);
        if idv >= ID_THRESH && j >= 0 {
            pairs.push((i, j));
        }
    }
    if pairs.is_empty() {
        return 0.0;
    }
    pairs.sort_unstable(); // by (i, j); i is unique so effectively by i
    // patience sorting -> longest NON-decreasing subsequence of the j sequence.
    let mut tails: Vec<i64> = Vec::new();
    for (_, x) in pairs {
        // bisect_right: first index with tails[idx] > x
        let p = tails.partition_point(|&v| v <= x);
        if p == tails.len() {
            tails.push(x);
        } else {
            tails[p] = x;
        }
    }
    if k == 0 {
        0.0
    } else {
        tails.len() as f64 / k as f64
    }
}

