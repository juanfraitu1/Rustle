/// Dominant gene of a component (`collections.Counter(...).most_common(1)[0][0]`):
/// highest count, ties broken by FIRST-SEEN in `comp` order (CPython `most_common`
/// selects the first-inserted among equal counts). `comp` must be non-empty.
pub fn subfam_dom_gene(recs: &[Rec], comp: &[usize]) -> String {
    let mut order: Vec<String> = Vec::new();
    let mut counts: HashMap<String, usize> = HashMap::new();
    for &i in comp {
        let g = &recs[i].gene;
        if !counts.contains_key(g) {
            order.push(g.clone());
        }
        *counts.entry(g.clone()).or_insert(0) += 1;
    }
    let mut best = &order[0];
    for g in &order {
        // strict '>' keeps the first-seen on a count tie
        if counts[g] > counts[best] {
            best = g;
        }
    }
    best.clone()
}

/// `f"{dom}({len(comp)})"` (`subfam_label`, :273).
pub fn subfam_label(recs: &[Rec], comp: &[usize]) -> String {
    format!("{}({})", subfam_dom_gene(recs, comp), comp.len())
}

/// True iff two DISTINCT parts of `bridged` occupy genomically OVERLAPPING loci (same
/// chrom, closed-interval overlap `a.start <= b.end && b.start <= a.end`)
/// (`subfams_colocated`, :284).
pub fn subfams_colocated(recs: &[Rec], bridged: &[Vec<usize>]) -> bool {
    for ci in 0..bridged.len() {
        for cj in (ci + 1)..bridged.len() {
            for &a in &bridged[ci] {
                for &b in &bridged[cj] {
                    let (ra, rb) = (&recs[a], &recs[b]);
                    if ra.chrom == rb.chrom && ra.start <= rb.end && rb.start <= ra.end {
                        return true;
                    }
                }
            }
        }
    }
    false
}

