/// Render the full `asj_genetic_core.tsv` bytes: [`CORE_HEADER`] then every row's [`line`], each
/// terminated by `\r\n` (INCLUDING a trailing `\r\n` after the last row, matching
/// `csv.DictWriter`). Byte-identical to the shipped file.
///
/// [`line`]: GeneticCoreRow::line
pub fn render_tsv(core: &GeneticCore) -> String {
    let mut out = String::with_capacity((core.rows.len() + 1) * 64);
    out.push_str(CORE_HEADER);
    out.push_str(LINE_TERMINATOR);
    for r in &core.rows {
        out.push_str(&r.line());
        out.push_str(LINE_TERMINATOR);
    }
    out
}

/// Build the funnel from the two input TSV files (`ver_path` / `sb_path`). Files default to
/// `{bench}/asj_calls_verified.tsv` and `{bench}/asj_calls_strandbias.tsv` when the caller
/// passes those basenames under a bench directory.
pub fn run_from_paths(ver_path: &Path, sb_path: &Path) -> Result<GeneticCore> {
    let ver_text = std::fs::read_to_string(ver_path)
        .with_context(|| format!("read verified TSV {}", ver_path.display()))?;
    let sb_text = std::fs::read_to_string(sb_path)
        .with_context(|| format!("read strand-bias TSV {}", sb_path.display()))?;
    let ver = parse_verified(&ver_text)?;
    let sb = parse_strandbias(&sb_text)?;
    GeneticCore::build(&ver, &sb)
}

/// Build the funnel from a bench directory (joins the two default input basenames) and write
/// `asj_genetic_core.tsv` into it, byte-identical to the Python output. Returns the funnel so the
/// caller can print the summary. `bench/asj_genetic_core.py::main`.
pub fn run_and_write(bench_dir: &Path) -> Result<GeneticCore> {
    let ver_path = bench_dir.join(IN_VERIFIED_BASENAME);
    let sb_path = bench_dir.join(IN_STRANDBIAS_BASENAME);
    let core = run_from_paths(&ver_path, &sb_path)?;
    let out_path = bench_dir.join(OUT_TSV_BASENAME);
    std::fs::write(&out_path, render_tsv(&core))
        .with_context(|| format!("write {}", out_path.display()))?;
    Ok(core)
}

