/// Parse `asj_calls_verified.tsv` text (columns located BY NAME, like `csv.DictReader`).
/// The first line is the header; every subsequent line is a data row (no blank-line skip,
/// matching `csv.DictReader` over the shipped input, which has none).
pub fn parse_verified(text: &str) -> Result<Vec<VerifiedRow>> {
    let mut lines = text.lines();
    let header_line = lines.next().context("empty asj_calls_verified.tsv (no header)")?;
    let header: Vec<&str> = header_line.split('\t').collect();
    let (ci_gene, ci_chrom, ci_anchor, ci_ax, ci_ay, ci_donor, ci_acceptor, ci_dpsi, ci_q, ci_hc) = (
        col_index(&header, "gene")?,
        col_index(&header, "chrom")?,
        col_index(&header, "anchor")?,
        col_index(&header, "alleleX")?,
        col_index(&header, "alleleY")?,
        col_index(&header, "donor")?,
        col_index(&header, "acceptor")?,
        col_index(&header, "dPSI")?,
        col_index(&header, "q")?,
        col_index(&header, "high_confidence")?,
    );
    let mut out = Vec::new();
    for line in lines {
        let f: Vec<&str> = line.split('\t').collect();
        let get = |i: usize| -> String { f.get(i).copied().unwrap_or("").to_string() };
        out.push(VerifiedRow {
            gene: get(ci_gene),
            chrom: get(ci_chrom),
            anchor: get(ci_anchor),
            allele_x: get(ci_ax),
            allele_y: get(ci_ay),
            donor: get(ci_donor),
            acceptor: get(ci_acceptor),
            d_psi: get(ci_dpsi),
            q: get(ci_q),
            high_confidence: get(ci_hc),
        });
    }
    Ok(out)
}

