/// Resolve a header column to its index, erroring (like `csv.DictReader`'s later `KeyError`)
/// when the column is absent.
fn col_index(header: &[&str], name: &str) -> Result<usize> {
    header
        .iter()
        .position(|&c| c == name)
        .with_context(|| format!("TSV header missing required column {name:?}"))
}

