/// The complete funnel result: every joined row plus the four funnel tallies and the sorted
/// core-gene list. `bench/asj_genetic_core.py:48-52`.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct GeneticCore {
    /// Every joined output row (all 475), in input order.
    pub rows: Vec<GeneticCoreRow>,
    /// `n_all` — total candidate ASJ calls.
    pub n_all: usize,
    /// `n_transversion` — rows with `high_confidence == "1"`.
    pub n_transversion: usize,
    /// `n_nonloc` — rows with `high_confidence == "1"` AND non-LOC.
    pub n_nonloc: usize,
    /// `n_core` — rows in the genetic core (all three filters pass).
    pub n_core: usize,
    /// The sorted, unique set of genes among the core rows.
    pub core_genes: Vec<String>,
}

impl GeneticCore {
    /// Build the funnel by row-aligned join of the verified + strand-bias tables.
    ///
    /// Reproduces `main`'s two asserts as errors: the tables must be the SAME length and
    /// row-aligned by the 7-tuple key (`bench/asj_genetic_core.py:34,37`). A de-aligned input
    /// therefore STOPS (does not silently mis-join).
    pub fn build(ver: &[VerifiedRow], sb: &[StrandBiasRow]) -> Result<Self> {
        ensure!(
            ver.len() == sb.len(),
            "call tables differ in length (verified={}, strandbias={})",
            ver.len(),
            sb.len()
        );
        let mut rows = Vec::with_capacity(ver.len());
        for (i, (v, s)) in ver.iter().zip(sb.iter()).enumerate() {
            if v.key() != s.key() {
                bail!(
                    "call tables are not row-aligned at row {i}: verified key {:?} != strandbias key {:?}",
                    v.key(),
                    s.key()
                );
            }
            let transversion = v.high_confidence == "1";
            let non_loc = !v.gene.starts_with("LOC");
            let sor_pass = s.sor_pass == "1";
            let in_core = transversion && non_loc && sor_pass;
            rows.push(GeneticCoreRow {
                gene: v.gene.clone(),
                chrom: v.chrom.clone(),
                anchor: v.anchor.clone(),
                allele_x: v.allele_x.clone(),
                allele_y: v.allele_y.clone(),
                donor: v.donor.clone(),
                acceptor: v.acceptor.clone(),
                d_psi: v.d_psi.clone(),
                q: v.q.clone(),
                high_confidence: v.high_confidence.clone(),
                non_loc_copy_confound_clean: non_loc as u8,
                sor: s.sor.clone(),
                sor_pass: sor_pass as u8,
                in_genetic_core: in_core as u8,
            });
        }

        let n_all = rows.len();
        // n_transversion: high_confidence == "1".
        let n_transversion = rows.iter().filter(|r| r.high_confidence == "1").count();
        // n_nonloc: high_confidence == "1" AND non_loc (Python's `and r["non_loc_..."]` truthy).
        let n_nonloc = rows
            .iter()
            .filter(|r| r.high_confidence == "1" && r.non_loc_copy_confound_clean == 1)
            .count();
        // core rows + sorted unique gene set (Python `sorted({r["gene"] for r in core})`).
        let mut core_gene_set: std::collections::BTreeSet<String> = std::collections::BTreeSet::new();
        let mut n_core = 0usize;
        for r in &rows {
            if r.in_genetic_core == 1 {
                n_core += 1;
                core_gene_set.insert(r.gene.clone());
            }
        }
        let core_genes: Vec<String> = core_gene_set.into_iter().collect();

        Ok(Self { rows, n_all, n_transversion, n_nonloc, n_core, core_genes })
    }

    /// The genetic-core rows only (`in_genetic_core == 1`) — the 54-call deliverable.
    pub fn core_rows(&self) -> impl Iterator<Item = &GeneticCoreRow> {
        self.rows.iter().filter(|r| r.in_genetic_core == 1)
    }
}

