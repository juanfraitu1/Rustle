    #[test]
    fn optout_is_a_noop() {
        let _guard = ENV_LOCK.lock().unwrap();
        // enabled/disabled recognition
        std::env::remove_var(OPTOUT_ENV);
        assert!(abstain_enabled(), "unset env -> enabled");
        for v in ["1", "true", "True", "TRUE"] {
            std::env::set_var(OPTOUT_ENV, v);
            assert!(!abstain_enabled(), "env={v} -> disabled");
        }
        for v in ["0", "no", "2", ""] {
            std::env::set_var(OPTOUT_ENV, v);
            assert!(abstain_enabled(), "env={v:?} -> enabled");
        }

        // pick a VG that flips reads when enabled; disabled -> [] and VG unchanged.
        let fx = load_fixture();
        let flipper = fx["vgs"]
            .as_array()
            .unwrap()
            .iter()
            .find(|v| !v["expect_flipped"].as_array().unwrap().is_empty())
            .expect("a flipping VG in the fixture");
        let before = parse_vg(flipper);

        std::env::set_var(OPTOUT_ENV, "1");
        let mut vg = parse_vg(flipper);
        let flipped = apply_abstain_to_vg(&mut vg);
        assert!(flipped.is_empty(), "disabled leg must return []");
        // bit-for-bit unchanged: statuses, best_copy, counters
        for (r, b) in vg.reads.iter().zip(&before.reads) {
            assert_eq!(r.status, b.status);
            assert_eq!(r.best_copy, b.best_copy);
            assert!(r.gate_status_pre_abstain.is_none() && r.recombinant_kind.is_none());
        }
        assert_eq!(vg.assignment, before.assignment);
        assert_eq!(vg.per_copy, before.per_copy);

        std::env::remove_var(OPTOUT_ENV); // restore default-ON for other tests
        eprintln!("opt-out no-op verified: RUSTLE_NO_RECOMBINANT_ABSTAIN=1 -> [] and byte-identical VG");
    }
