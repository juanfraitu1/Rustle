//! O2 recombinant-read ABSTAIN gate -- faithful Rust port of
//! `bench/recombinant_abstain.py` (the recombinant-read abstain leg of the O2
//! copy-assignment gate). Continues the family-def migration: the O1 pipeline is
//! already fully ported to `super::*`; this is the O2 leg.
//!
//! WHY (`bench/VG_READ_PATH_RECOMBINATION.md`, commit 7e3be89): the per-read
//! significance gate (`super::copy_assign`) FORCE-ASSIGNS recombinant reads to a
//! single copy. A recombinant read carries copy A's private SUN in one
//! bubble-bounded arm and copy B's in another arm; it satisfies TWO
//! Strong-Separation witnesses at once, so it belongs to NO single copy = a
//! read-level K-frontier (THEORY.md K>=3 recombination obstruction). Such a read
//! must ABSTAIN rather than be force-assigned to whichever copy has more SUNs.
//!
//! WHAT THIS MODULE IS. The SINGLE SOURCE of the recombinant-detection logic. It
//! hosts (verbatim) the bubble-bounded copy-switch test
//! [`detect_read_recombination`] + [`full_pattern_switches`] + their thresholds,
//! plus [`build_supported`] (read-supported-allele pileup), [`is_recombinant`]
//! (the reusable predicate) and [`apply_abstain_to_vg`] (the DEFAULT-ON gate leg
//! over a materialized family VG, `bench/o2_vg_visualization.py`).
//!
//! DETERMINISTIC + PURE: no BAM/genome/pysam/RNG. Iteration is over `BTreeMap`
//! keys / `names` slice order, mirroring Python's `sorted(obs)` and
//! `itertools.combinations(names, 2)` (which preserves list order). The
//! pair-selection tie-break key `(switches, -len(seq), imp, A, B)` (with the copy
//! NAME strings as the final tie-break, byte-compared like Python str) and the
//! crossover-vs-conversion boundary arithmetic + `clean_full` are reproduced
//! EXACTLY.
//!
//! OPT-OUT: DEFAULT-ON. Disable with env `RUSTLE_NO_RECOMBINANT_ABSTAIN=1`
//! (accepted truthy values `1`/`true`/`True`/`TRUE`); [`apply_abstain_to_vg`] is
//! then a no-op returning `[]` and the assignment output is byte-identical to the
//! prior gate.
//!
//! Verified byte-identical to the shipped Python against a golden fixture
//! (`testdata/recombinant_abstain_fixture.json`, generated by
//! `bench/gen_recombinant_abstain_fixture.py`, PYTHONHASHSEED=0); see the
//! `#[test]`s (detection parity, `build_supported` parity, apply-abstain flip-list
//! + counters parity, and the opt-out no-op check).

use std::collections::{BTreeMap, BTreeSet};

// ---------------------------------------------------------------------------
// detection thresholds (documented; conservative for a HiFi ERR~0.003 single
// molecule). MOVED verbatim from `bench/recombinant_abstain.py:57-70`.
// ---------------------------------------------------------------------------

/// Read must span >= this many pair-discriminating bubbles matched to A or B.
/// `bench/recombinant_abstain.py:57  MIN_INFO = 4`.
pub const MIN_INFO: usize = 4;
/// Crossover: each side of the switch >= this many discriminating bubbles.
/// `bench/recombinant_abstain.py:58  MIN_ARM = 2`.
pub const MIN_ARM: usize = 2;
/// Conversion: each flank (the outer A blocks) >= this many bubbles.
/// `bench/recombinant_abstain.py:59  MIN_FLANK = 2`.
pub const MIN_FLANK: usize = 2;
/// Conversion: tract (inner B block) >= this many bubbles (a 1-bubble "tract" is a
/// point event, not a recombination tract). `bench/recombinant_abstain.py:60  MIN_TRACT = 2`.
pub const MIN_TRACT: usize = 2;
/// NO single copy may explain the read within `(MIN_SINGLE_MM - 1)` mismatches.
/// `bench/recombinant_abstain.py:63  MIN_SINGLE_MM = 2`.
pub const MIN_SINGLE_MM: usize = 2;
/// Allow <= this many read bases matching NEITHER paired allele (dropped from split).
/// `bench/recombinant_abstain.py:64  IMPURITY_MAX = 1`.
pub const IMPURITY_MAX: usize = 1;
/// Supported(base) = read-count >= max(ALLELE_SUPPORT_ABS, ALLELE_SUPPORT_FRAC*cov).
/// `bench/recombinant_abstain.py:69  ALLELE_SUPPORT_ABS = 3`.
pub const ALLELE_SUPPORT_ABS: u32 = 3;
/// `bench/recombinant_abstain.py:70  ALLELE_SUPPORT_FRAC = 0.02`.
pub const ALLELE_SUPPORT_FRAC: f64 = 0.02;

/// Opt-out env (default-ON). `bench/recombinant_abstain.py:73`.
pub const OPTOUT_ENV: &str = "RUSTLE_NO_RECOMBINANT_ABSTAIN";
/// The abstain label (distinct from assigned/ambiguous/tied/no_cover).
/// `bench/recombinant_abstain.py:218  ABSTAIN_STATUS = "recombinant"`.
pub const ABSTAIN_STATUS: &str = "recombinant";

/// The recombinant-abstain leg is DEFAULT-ON; `RUSTLE_NO_RECOMBINANT_ABSTAIN=1`
/// disables it. Mirrors `bench/recombinant_abstain.py:76 abstain_enabled`:
/// `os.environ.get(OPTOUT_ENV, "0") not in ("1", "true", "True", "TRUE")`.
pub fn abstain_enabled() -> bool {
    match std::env::var(OPTOUT_ENV) {
        Ok(v) => !matches!(v.as_str(), "1" | "true" | "True" | "TRUE"),
        Err(_) => true, // unset -> "0" -> enabled
    }
}

// ---------------------------------------------------------------------------
// data representation of the materialized family VG the gate operates on
// (a subset of `bench/o2_vg_visualization.materialize_family`'s dict -- only the
// fields the abstain leg reads/writes).
// ---------------------------------------------------------------------------

/// A copy allele vector in COLUMN space: `col -> that copy's allele` (or `None`
/// when the copy has no allele at that bubble, mirroring `dict.get`). Built by
/// `copy_vecs[nm] = {j: bubbles[j]["hap"].get(nm) for j in range(len(bubbles))}`.
pub type CopyVec = BTreeMap<usize, Option<char>>;

/// Read-supported alleles per bubble: `col -> set(supported bases)`.
pub type Supported = BTreeMap<usize, BTreeSet<char>>;

/// Recombination kind (the copy-switch pattern class).
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum RecombKind {
    /// A single ordered switch `A..A|B..B` (1 switch).
    Crossover,
    /// A bounded reverting tract `A..A|B..B|A..A` (2 switches, `syms[0]==syms[-1]`).
    Conversion,
}

impl RecombKind {
    /// The Python `cand["type"]` string.
    pub fn as_str(&self) -> &'static str {
        match self {
            RecombKind::Crossover => "crossover",
            RecombKind::Conversion => "conversion",
        }
    }
}

/// The best recombinant split for one read (`detect_read_recombination`'s `cand`).
#[derive(Clone, Debug)]
pub struct Recombination {
    pub kind: RecombKind,
    pub a: String,
    pub b: String,
    /// `[(col, 'A'|'B')]` over bubbles where A,B differ and the read matches one.
    pub seq: Vec<(usize, char)>,
    pub imp: usize,
    pub switches: usize,
    pub bnd_idx: Vec<usize>,
    /// `[i1, i2-1]` for a conversion, `None` for a crossover.
    pub tract_idx: Option<(usize, usize)>,
    pub full_switches: usize,
    pub n_full_ab: usize,
    /// `int(full_switches == switches)` -- 1 iff no extra switch is hidden by
    /// dropping the copy-unsupported columns.
    pub clean_full: u8,
}

/// One copy node of the VG (only the name is needed by the abstain leg).
#[derive(Clone, Debug)]
pub struct VgCopy {
    pub name: String,
}

/// One PSV bubble (only the `hap` map `copy -> allele` is needed).
#[derive(Clone, Debug)]
pub struct VgBubble {
    pub hap: BTreeMap<String, char>,
}

/// One threaded read. `obs` is the RAW observed alleles `col -> base` (the ACGT
/// filter of `apply_abstain_to_vg` is applied by the leg, not stored here).
#[derive(Clone, Debug)]
pub struct VgRead {
    pub name: String,
    pub obs: BTreeMap<usize, char>,
    pub status: String,
    pub best_copy: Option<String>,
    /// Set to the pre-abstain status ONLY on a flipped read (else `None`).
    pub gate_status_pre_abstain: Option<String>,
    /// Set to the switch kind ONLY on a flipped read (else `None`).
    pub recombinant_kind: Option<String>,
}

/// The materialized family VG (subset the abstain leg reads/writes).
#[derive(Clone, Debug)]
pub struct FamilyVg {
    pub family: i64,
    pub copies: Vec<VgCopy>,
    pub bubbles: Vec<VgBubble>,
    pub reads: Vec<VgRead>,
    pub assignment: BTreeMap<String, i64>,
    pub per_copy: BTreeMap<String, i64>,
}

/// One flipped-read report record (an element of `apply_abstain_to_vg`'s return).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct FlipRecord {
    pub family: i64,
    pub read: String,
    pub kind: String,
    pub copy_a: String,
    pub copy_b: String,
    pub switches: usize,
    pub clean_full: u8,
    pub prev_best: Option<String>,
}

