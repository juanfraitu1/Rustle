/// DEFAULT-ON recombinant-abstain leg over a materialized family VG.
///
/// For every read the significance gate currently ASSIGNS (`status == "assigned"`)
/// that [`is_recombinant`], relabel `status -> "recombinant"` (abstain), record the
/// pre-abstain gate call in `gate_status_pre_abstain` and the switch kind in
/// `recombinant_kind`, and drop `best_copy`. A PURE MONOTONE ADDITION OF
/// ABSTENTIONS: non-recombinant reads and already-abstaining reads are left
/// bit-for-bit unchanged; only force-assigned recombinant reads change. The
/// `assignment` and `per_copy` summary counters are kept consistent (each flipped
/// read is moved out of `assigned` and out of its copy's quant into `recombinant`).
///
/// Returns one [`FlipRecord`] per flipped read (empty when disabled or no leaks).
/// No-op (returns `[]`) when `RUSTLE_NO_RECOMBINANT_ABSTAIN=1`, or when the VG has
/// `< 2` copies or `< 2` bubbles.
/// Port of `bench/recombinant_abstain.py:221 apply_abstain_to_vg`.
pub fn apply_abstain_to_vg(vg: &mut FamilyVg) -> Vec<FlipRecord> {
    if !abstain_enabled() {
        return Vec::new();
    }
    let names: Vec<String> = vg.copies.iter().map(|c| c.name.clone()).collect();
    let n_bubbles = vg.bubbles.len();
    if names.len() < 2 || n_bubbles < 2 {
        return Vec::new();
    }

    // copy_vecs[nm] = {j: bubbles[j]["hap"].get(nm) for j in range(len(bubbles))}
    let mut copy_vecs: BTreeMap<String, CopyVec> = BTreeMap::new();
    for nm in &names {
        let mut cv: CopyVec = BTreeMap::new();
        for j in 0..n_bubbles {
            cv.insert(j, vg.bubbles[j].hap.get(nm).copied());
        }
        copy_vecs.insert(nm.clone(), cv);
    }
    let supported = build_supported(&vg.reads, n_bubbles);

    // Split the borrow of the distinct VG fields so the read loop can mutate the
    // reads AND the summary counters simultaneously.
    let family = vg.family;
    let reads = &mut vg.reads;
    let assignment = &mut vg.assignment;
    let per_copy = &mut vg.per_copy;

    let mut flipped: Vec<FlipRecord> = Vec::new();
    for r in reads.iter_mut() {
        if r.status != "assigned" {
            continue; // only ADD abstentions on force-assigned reads
        }
        // obs = {int(k): v for k, v in r["obs"].items() if v in "ACGT"}
        let mut obs: BTreeMap<usize, char> = BTreeMap::new();
        for (&k, &v) in &r.obs {
            if matches!(v, 'A' | 'C' | 'G' | 'T') {
                obs.insert(k, v);
            }
        }
        if obs.len() < MIN_INFO {
            continue;
        }
        let cand = match is_recombinant(&obs, &supported, &copy_vecs, &names) {
            Some(c) => c,
            None => continue,
        };
        let prev_best = r.best_copy.clone();
        flipped.push(FlipRecord {
            family,
            read: r.name.clone(),
            kind: cand.kind.as_str().to_string(),
            copy_a: cand.a.clone(),
            copy_b: cand.b.clone(),
            switches: cand.switches,
            clean_full: cand.clean_full,
            prev_best: prev_best.clone(),
        });
        r.gate_status_pre_abstain = Some(r.status.clone());
        r.recombinant_kind = Some(cand.kind.as_str().to_string());
        r.status = ABSTAIN_STATUS.to_string();
        r.best_copy = None;
        // keep the summary counters consistent (get-with-default 0, like Python).
        *assignment.entry("assigned".to_string()).or_insert(0) -= 1;
        *assignment.entry(ABSTAIN_STATUS.to_string()).or_insert(0) += 1;
        if let Some(pb) = &prev_best {
            if let Some(v) = per_copy.get_mut(pb) {
                *v -= 1;
            }
        }
    }
    flipped
}

