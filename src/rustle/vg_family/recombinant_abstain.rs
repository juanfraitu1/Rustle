    /// `detect_read_recombination` == Python EXACTLY on every detection case
    /// (type/A/B/switches/clean_full/full_switches/n_full_ab/imp/seq). Reports the
    /// first mismatch. Covers crossover, conversion, clean_full 0/1, the non-recombinant
    /// branches, and the >=2-pair tie-break.
    #[test]
    fn detect_read_recombination_parity() {
        let fx = load_fixture();
        let cases = fx["detection_cases"].as_array().expect("detection_cases");
        assert!(cases.len() >= 200, "want >= 200 detection cases, got {}", cases.len());
        let (mut n_cross, mut n_conv, mut n_none, mut n_c0, mut n_c1, mut n_syn) = (0, 0, 0, 0, 0, 0);
        for case in cases {
            let label = case["label"].as_str().unwrap();
            let names = parse_names(&case["names"]);
            let obs = parse_obs(&case["obs"]);
            let supported = parse_supported(&case["supported"]);
            let copy_vecs = parse_copy_vecs(&case["copy_vecs"]);
            let got = detect_read_recombination(&obs, &supported, &copy_vecs, &names);
            if let Err(why) = check_detect(&got, &case["expect"]) {
                panic!("detect mismatch on case '{label}': {why}");
            }
            // is_recombinant is the same predicate -> must agree case-by-case
            let ir = is_recombinant(&obs, &supported, &copy_vecs, &names);
            assert_eq!(ir.is_some(), got.is_some(), "is_recombinant disagrees on '{label}'");
            if case["expect"].is_null() {
                n_none += 1;
            } else {
                match case["expect"]["type"].as_str().unwrap() {
                    "crossover" => n_cross += 1,
                    "conversion" => n_conv += 1,
                    _ => {}
                }
                match case["expect"]["clean_full"].as_u64().unwrap() {
                    0 => n_c0 += 1,
                    _ => n_c1 += 1,
                }
            }
            if label.starts_with("syn_") {
                n_syn += 1;
            }
        }
        assert!(n_cross >= 5, "want crossover cases, got {n_cross}");
        assert!(n_conv >= 5, "want conversion cases, got {n_conv}");
        assert!(n_none >= 10, "want None cases, got {n_none}");
        assert!(n_c0 >= 5 && n_c1 >= 5, "want clean_full 0 and 1 cases, got {n_c0}/{n_c1}");
        assert!(n_syn >= 10, "want synthetic boundary cases, got {n_syn}");
        eprintln!(
            "detect parity: {} cases identical (crossover={n_cross} conversion={n_conv} none={n_none} clean_full0={n_c0} clean_full1={n_c1} synthetic={n_syn})",
            cases.len()
        );
    }

