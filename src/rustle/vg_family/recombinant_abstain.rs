    #[test]
    fn build_supported_parity() {
        let fx = load_fixture();
        // (a) dedicated synthetic cases (frac-vs-abs threshold boundary)
        let cases = fx["build_supported_cases"].as_array().expect("build_supported_cases");
        assert!(!cases.is_empty());
        for case in cases {
            let label = case["label"].as_str().unwrap();
            let n_bubbles = case["n_bubbles"].as_u64().unwrap() as usize;
            let reads: Vec<VgRead> = case["reads"]
                .as_array()
                .unwrap()
                .iter()
                .map(|r| VgRead {
                    name: String::new(),
                    obs: parse_obs(&r["obs"]),
                    status: String::new(),
                    best_copy: None,
                    gate_status_pre_abstain: None,
                    recombinant_kind: None,
                })
                .collect();
            let got = build_supported(&reads, n_bubbles);
            let want = parse_supported(&case["expected"]);
            assert_eq!(got, want, "build_supported mismatch on synthetic case '{label}'");
        }
        // (b) the whole-VG read piles: build_supported(vg.reads) == the stored supported
        let mut n_real = 0;
        for vgv in fx["vgs"].as_array().unwrap() {
            let vg = parse_vg(vgv);
            if vg.bubbles.len() < 2 {
                continue;
            }
            let got = build_supported(&vg.reads, vg.bubbles.len());
            let want = parse_supported(&vgv["expect_supported"]);
            assert_eq!(got, want, "build_supported mismatch on VG fam {}", vg.family);
            n_real += 1;
        }
        eprintln!("build_supported parity: {} synthetic + {} real family piles identical", cases.len(), n_real);
    }

