    /// `apply_abstain_to_vg` == Python on every whole VG: the flipped list (order +
    /// every field), the post-abstain per-read status/best_copy/gate_status_pre_abstain/
    /// recombinant_kind, and the post assignment/per_copy counters. Also asserts the
    /// MONOTONE property: only 'assigned'->'recombinant' reads change; everything else
    /// is bit-for-bit unchanged. Reports the first mismatch.
    #[test]
    fn apply_abstain_parity() {
        let _guard = ENV_LOCK.lock().unwrap();
        std::env::remove_var(OPTOUT_ENV); // DEFAULT-ON
        assert!(abstain_enabled());

        let fx = load_fixture();
        let vgs = fx["vgs"].as_array().expect("vgs");
        let (mut n_flip_vgs, mut n_noflip_vgs, mut total_flips) = (0usize, 0usize, 0usize);
        for vgv in vgs {
            let mut vg = parse_vg(vgv);
            let pre = vg.clone(); // to verify the MONOTONE property
            let flipped = apply_abstain_to_vg(&mut vg);

            // (1) flipped list == expect_flipped (order + fields)
            let want_flipped = vgv["expect_flipped"].as_array().unwrap();
            assert_eq!(
                flipped.len(),
                want_flipped.len(),
                "fam {}: flip count {} != {}",
                vg.family,
                flipped.len(),
                want_flipped.len()
            );
            for (i, (g, w)) in flipped.iter().zip(want_flipped).enumerate() {
                assert_eq!(g.family, w["family"].as_i64().unwrap(), "fam {} flip[{i}] family", vg.family);
                assert_eq!(g.read, w["read"].as_str().unwrap(), "fam {} flip[{i}] read", vg.family);
                assert_eq!(g.kind, w["kind"].as_str().unwrap(), "fam {} flip[{i}] kind ({})", vg.family, g.read);
                assert_eq!(g.copy_a, w["copyA"].as_str().unwrap(), "fam {} flip[{i}] copyA ({})", vg.family, g.read);
                assert_eq!(g.copy_b, w["copyB"].as_str().unwrap(), "fam {} flip[{i}] copyB ({})", vg.family, g.read);
                assert_eq!(g.switches as u64, w["switches"].as_u64().unwrap(), "fam {} flip[{i}] switches ({})", vg.family, g.read);
                assert_eq!(g.clean_full as u64, w["clean_full"].as_u64().unwrap(), "fam {} flip[{i}] clean_full ({})", vg.family, g.read);
                assert_eq!(g.prev_best.as_deref(), w["prev_best"].as_str(), "fam {} flip[{i}] prev_best ({})", vg.family, g.read);
            }

            // (2) post-abstain per-read fields == expect_reads
            let want_reads = vgv["expect_reads"].as_array().unwrap();
            assert_eq!(vg.reads.len(), want_reads.len(), "fam {}: read count", vg.family);
            let mut changed = 0;
            for (i, (r, w)) in vg.reads.iter().zip(want_reads).enumerate() {
                assert_eq!(r.name, w["name"].as_str().unwrap(), "fam {} read[{i}] name", vg.family);
                assert_eq!(r.status, w["status"].as_str().unwrap(), "fam {} read[{i}] status ({})", vg.family, r.name);
                assert_eq!(r.best_copy.as_deref(), w["best_copy"].as_str(), "fam {} read[{i}] best_copy ({})", vg.family, r.name);
                assert_eq!(
                    r.gate_status_pre_abstain.as_deref(),
                    w["gate_status_pre_abstain"].as_str(),
                    "fam {} read[{i}] gate_status_pre_abstain ({})",
                    vg.family,
                    r.name
                );
                assert_eq!(
                    r.recombinant_kind.as_deref(),
                    w["recombinant_kind"].as_str(),
                    "fam {} read[{i}] recombinant_kind ({})",
                    vg.family,
                    r.name
                );
                // MONOTONE: a read changed status iff it was flipped assigned->recombinant.
                let pr = &pre.reads[i];
                if r.status != pr.status {
                    assert_eq!(pr.status, "assigned", "fam {}: only assigned reads may flip ({})", vg.family, r.name);
                    assert_eq!(r.status, ABSTAIN_STATUS, "fam {}: flipped read must be recombinant ({})", vg.family, r.name);
                    changed += 1;
                } else {
                    // unchanged status => the read is bit-for-bit unchanged
                    assert_eq!(r.best_copy, pr.best_copy, "fam {}: non-flipped best_copy changed ({})", vg.family, r.name);
                    assert!(r.gate_status_pre_abstain.is_none() && r.recombinant_kind.is_none(),
                        "fam {}: non-flipped read got abstain fields ({})", vg.family, r.name);
                }
            }
            assert_eq!(changed, flipped.len(), "fam {}: #status-changed != #flipped", vg.family);

            // (3) post assignment / per_copy counters
            assert_eq!(vg.assignment, parse_counter(&vgv["expect_assignment"]), "fam {}: assignment", vg.family);
            assert_eq!(vg.per_copy, parse_counter(&vgv["expect_per_copy"]), "fam {}: per_copy", vg.family);

            total_flips += flipped.len();
            if flipped.is_empty() {
                n_noflip_vgs += 1;
            } else {
                n_flip_vgs += 1;
            }
        }
        assert!(n_flip_vgs >= 3, "want >= 3 flipping VGs, got {n_flip_vgs}");
        assert!(n_noflip_vgs >= 2, "want >= 2 non-flipping VGs, got {n_noflip_vgs}");
        eprintln!(
            "apply_abstain parity: {} VGs identical ({n_flip_vgs} flip, {n_noflip_vgs} no-flip; {total_flips} total reads abstained)",
            vgs.len()
        );
    }

