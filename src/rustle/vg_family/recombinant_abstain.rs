/// HONESTY LEG: switch count over ALL read-supported discriminating columns for
/// the chosen pair -- NOT just the both-copy-read-supported subset the split is
/// fit on. `spanned` is already restricted to columns where the READ base is
/// read-supported. Keeps every column where the two copies differ (`cvA != cvB`)
/// regardless of whether the copy allele is itself read-supported, classifies the
/// read A/B/neither, and counts switches on the A/B subsequence. Returns
/// `(full_switch_count, n_full_AB_cols)`.
/// Port of `bench/recombinant_abstain.py:82 full_pattern_switches`.
pub fn full_pattern_switches(
    spanned: &[usize],
    obs: &BTreeMap<usize, char>,
    cva: &CopyVec,
    cvb: &CopyVec,
) -> (usize, usize) {
    let mut syms: Vec<char> = Vec::new();
    for &c in spanned {
        let a = cva.get(&c).copied().flatten();
        let b = cvb.get(&c).copied().flatten();
        match (a, b) {
            (Some(a), Some(b)) if a != b => {
                let r = obs[&c];
                if r == a && r != b {
                    syms.push('A');
                } else if r == b && r != a {
                    syms.push('B');
                }
                // matches neither paired allele -> skip
            }
            _ => {}
        }
    }
    let sw = (1..syms.len()).filter(|&i| syms[i] != syms[i - 1]).count();
    (sw, syms.len())
}

/// The best recombinant split for one read, or `None`.
///
/// `obs[col] -> read base`; `supported[col] -> set of READ-supported alleles at
/// that bubble`; `copy_vecs[copy][col] -> that copy's allele`. Only bubbles whose
/// read base is a supported allele are used (`spanned`); a pair (A,B) may only
/// switch at cols where BOTH copies' alleles are read-supported. A recombinant =
/// NO single copy explains it (min single-copy mismatch >= `MIN_SINGLE_MM`) AND
/// some pair admits a PURE ordered A|B (or A|B|A) split with 1 or 2 switches.
///
/// Port of `bench/recombinant_abstain.py:106 detect_read_recombination`.
pub fn detect_read_recombination(
    obs: &BTreeMap<usize, char>,
    supported: &Supported,
    copy_vecs: &BTreeMap<String, CopyVec>,
    names: &[String],
) -> Option<Recombination> {
    let empty: BTreeSet<char> = BTreeSet::new();
    let sup_at = |c: usize| supported.get(&c).unwrap_or(&empty);

    // spanned = [c for c in sorted(obs) if obs[c] in supported.get(c, ())]
    // (obs is a BTreeMap -> iterated in sorted-key order == Python `sorted(obs)`).
    let spanned: Vec<usize> = obs
        .iter()
        .filter(|(c, b)| sup_at(**c).contains(*b))
        .map(|(c, _)| *c)
        .collect();
    if spanned.len() < MIN_INFO {
        return None;
    }

    // single-copy mismatch, counted only where the copy's own allele is
    // read-supported (fair comparison). If any single copy explains the read
    // within (MIN_SINGLE_MM - 1) mismatches -> not recombinant.
    let mut min_mm: usize = usize::MAX;
    for nm in names {
        let cv = &copy_vecs[nm];
        let mut mm = 0usize;
        for &c in &spanned {
            if let Some(base) = cv.get(&c).copied().flatten() {
                if sup_at(c).contains(&base) && obs[&c] != base {
                    mm += 1;
                }
            }
        }
        if mm < min_mm {
            min_mm = mm;
        }
    }
    if min_mm < MIN_SINGLE_MM {
        return None;
    }

    let mut best: Option<Recombination> = None;
    let mut best_key: Option<(usize, isize, usize, String, String)> = None;

    // itertools.combinations(names, 2) preserves list order: (i, j) with i < j.
    for i in 0..names.len() {
        for j in (i + 1)..names.len() {
            let a_name = &names[i];
            let b_name = &names[j];
            let cva = &copy_vecs[a_name];
            let cvb = &copy_vecs[b_name];

            let mut seq: Vec<(usize, char)> = Vec::new();
            let mut imp = 0usize;
            for &c in &spanned {
                let a = cva.get(&c).copied().flatten();
                let b = cvb.get(&c).copied().flatten();
                let sup = sup_at(c);
                match (a, b) {
                    (Some(a), Some(b)) if a != b && sup.contains(&a) && sup.contains(&b) => {
                        let r = obs[&c];
                        if r == a && r != b {
                            seq.push((c, 'A'));
                        } else if r == b && r != a {
                            seq.push((c, 'B'));
                        } else {
                            imp += 1; // matches neither paired allele
                        }
                    }
                    _ => {} // not a discriminating, read-supported bubble
                }
            }
            if imp > IMPURITY_MAX || seq.len() < MIN_INFO {
                continue;
            }
            let syms: Vec<char> = seq.iter().map(|&(_, s)| s).collect();
            let sw: Vec<usize> = (1..syms.len())
                .filter(|&k| syms[k] != syms[k - 1])
                .collect();

            let cand: Recombination = if sw.len() == 1 {
                let ii = sw[0];
                if ii.min(syms.len() - ii) < MIN_ARM {
                    continue;
                }
                Recombination {
                    kind: RecombKind::Crossover,
                    a: a_name.clone(),
                    b: b_name.clone(),
                    seq: seq.clone(),
                    imp,
                    switches: 1,
                    bnd_idx: vec![ii],
                    tract_idx: None,
                    full_switches: 0,
                    n_full_ab: 0,
                    clean_full: 0,
                }
            } else if sw.len() == 2 {
                let (i1, i2) = (sw[0], sw[1]);
                if syms[0] != syms[syms.len() - 1] {
                    continue; // must revert (X Y X)
                }
                let flank1 = i1;
                let tract = i2 - i1;
                let flank2 = syms.len() - i2;
                if flank1 < MIN_FLANK || flank2 < MIN_FLANK || tract < MIN_TRACT {
                    continue;
                }
                Recombination {
                    kind: RecombKind::Conversion,
                    a: a_name.clone(),
                    b: b_name.clone(),
                    seq: seq.clone(),
                    imp,
                    switches: 2,
                    bnd_idx: vec![i1, i2],
                    tract_idx: Some((i1, i2 - 1)),
                    full_switches: 0,
                    n_full_ab: 0,
                    clean_full: 0,
                }
            } else {
                continue;
            };

            // prefer fewer switches, then more informative bubbles, then less
            // impurity, then copy order (A, B copy-name strings byte-compared).
            let key = (cand.switches, -(seq.len() as isize), imp, a_name.clone(), b_name.clone());
            if best_key.as_ref().map_or(true, |bk| key.lt(bk)) {
                best = Some(cand);
                best_key = Some(key);
            }
        }
    }

    if let Some(mut b) = best {
        let cva = &copy_vecs[&b.a];
        let cvb = &copy_vecs[&b.b];
        let (full_sw, n_full) = full_pattern_switches(&spanned, obs, cva, cvb);
        b.full_switches = full_sw;
        b.n_full_ab = n_full;
        b.clean_full = u8::from(full_sw == b.switches);
        Some(b)
    } else {
        None
    }
}

// ===========================================================================
// reusable predicate
// ===========================================================================

/// Read-supported alleles per bubble (factored verbatim from `process_family`).
/// A base is supported iff its read-count >=
/// `max(ALLELE_SUPPORT_ABS, ALLELE_SUPPORT_FRAC * coverage)`. Drops asm20
/// copy-vector miscalls (a copy allele with ~0 read support) + singleton errors.
/// Port of `bench/recombinant_abstain.py:183 build_supported`.
pub fn build_supported(reads: &[VgRead], n_bubbles: usize) -> Supported {
    // pile[col][base] += 1 over ACGT read bases.
    let mut pile: BTreeMap<usize, BTreeMap<char, u64>> = BTreeMap::new();
    for r in reads {
        for (&k, &v) in &r.obs {
            if matches!(v, 'A' | 'C' | 'G' | 'T') {
                *pile.entry(k).or_default().entry(v).or_insert(0) += 1;
            }
        }
    }
    let mut supported: Supported = BTreeMap::new();
    for j in 0..n_bubbles {
        let counts = pile.get(&j);
        let cov: u64 = counts.map(|m| m.values().sum()).unwrap_or(0);
        // thr = max(3, 0.02 * cov). Comparing an integer count `n` to this f64 is
        // exact for `n < 2^53`, so `n as f64 >= thr` matches Python's `n >= thr`
        // whether `thr` is the int 3 or the float 0.02*cov.
        let thr = (ALLELE_SUPPORT_FRAC * cov as f64).max(ALLELE_SUPPORT_ABS as f64);
        let mut s: BTreeSet<char> = BTreeSet::new();
        if let Some(m) = counts {
            for (&b, &n) in m {
                if n as f64 >= thr {
                    s.insert(b);
                }
            }
        }
        supported.insert(j, s);
    }
    supported
}

/// The reusable recombinant predicate. `None` == Python `(False, None, None)`;
/// `Some(rec)` == `(True, rec.kind, arms)` where `arms` = the copy pair + the
/// colinear arms (`a`, `b`, `switches`, `clean_full`, `seq`). A thin wrapper over
/// [`detect_read_recombination`] -- the SAME test the diagnostic detector uses.
/// Port of `bench/recombinant_abstain.py:201 is_recombinant`.
pub fn is_recombinant(
    obs: &BTreeMap<usize, char>,
    supported: &Supported,
    copy_vecs: &BTreeMap<String, CopyVec>,
    names: &[String],
) -> Option<Recombination> {
    detect_read_recombination(obs, supported, copy_vecs, names)
}

