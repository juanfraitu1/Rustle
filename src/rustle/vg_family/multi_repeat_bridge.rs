/// A cached loader bundle for the gate (`_stage_loaders`, :605) -- the RNA
/// exon-structure + genome + VG-multiplicity inputs `characterize` needs. `fa_up` /
/// `fa_mask` are separate handles in Python; here a single `ExonFetcher` backs both.
pub struct StageLoaders<'a, F: ExonFetcher> {
    pub r_skel: &'a HashMap<(String, i64, i64), Vec<(i64, i64)>>,
    pub strand: &'a HashMap<String, String>,
    pub vskel: &'a HashMap<(String, i64, i64), String>,
    pub meta: &'a HashMap<String, (String, i64, i64)>,
    pub fa: &'a F,
    pub mult: &'a HashMap<u64, usize>,
    pub cyclic: &'a HashMap<u64, usize>,
}

/// Return a PARTITION of `block` (list of sorted DN-lists) plus the plan. Faithful port
/// of `split_family_repeat_bridge` (:638): build members; if `< 2`, no split; else
/// `characterize`; if the plan is skipped or `gate_cut` does not fire, no split; else
/// replace the block by its full-exon components (`comps_dn`) plus leftover
/// no-skeleton singletons (`sorted(set(block) - covered)`), then sort the parts by first
/// element. Returns `(parts, Some(plan))` on a cut, `([sorted(block)], plan_or_none)`
/// otherwise (the plan is returned only when the gate FIRES, else `None`, matching
/// Python which returns `pl` only on the cut path).
pub fn split_family_repeat_bridge<F: ExonFetcher>(
    block: &[String],
    genes: &HashMap<String, GeneMeta>,
    gene_of_dn: &HashMap<String, String>,
    t: usize,
    several: usize,
    res: &StageLoaders<F>,
) -> (Vec<Vec<String>>, Option<Plan>) {
    let members = block_members(block, genes, gene_of_dn);
    if members.len() < 2 {
        return (vec![sorted_block(block)], None);
    }
    let pl = characterize(
        &members, res.r_skel, res.strand, res.fa, res.meta, res.vskel, res.fa, res.mult, res.cyclic,
    );
    let plan = match pl {
        None => return (vec![sorted_block(block)], None),
        Some(p) => p,
    };
    if plan.skipped || !gate_cut(&plan, t, several) {
        return (vec![sorted_block(block)], None);
    }
    let mut covered: BTreeSet<String> = BTreeSet::new();
    let mut parts: Vec<Vec<String>> = Vec::new();
    for comp in &plan.comps_dn {
        let mut p = comp.clone();
        p.sort(); // sorted(comp) (already sorted, but faithful)
        for dn in &p {
            covered.insert(dn.clone());
        }
        parts.push(p);
    }
    // leftover no-skeleton members -> singletons: sorted(set(block) - covered)
    let bset: BTreeSet<String> = block.iter().cloned().collect();
    for dn in bset.difference(&covered) {
        parts.push(vec![dn.clone()]);
    }
    // sorted((p for p in parts if p), key=lambda c: c[0])
    let mut result: Vec<Vec<String>> = parts.into_iter().filter(|p| !p.is_empty()).collect();
    result.sort_by(|a, b| a[0].cmp(&b[0]));
    (result, Some(plan))
}

/// `sorted(block)` (lexicographic on the ASCII DN ids).
fn sorted_block(block: &[String]) -> Vec<String> {
    let mut b: Vec<String> = block.to_vec();
    b.sort();
    b
}

