/// The global per-node `(multiplicity, cyclic)` maps, parsed from the "# SECTION
/// nodes (mult>=2)" block of the shipped `bench/vg_repeat_catalog.tsv`.
///
/// Faithful port of `load_node_mult` (:86): drop the first two lines (the section
/// banner + the column header), then for each subsequent line STOP at the
/// "# SECTION edges" banner, split on `\t`, and record `mult[f0] = int(f1)` and
/// `cyclic[f0] = int(f3)`. Nodes ABSENT from this section default to `mult 1` /
/// `cyclic 0` at every lookup (they are the unique/low-mult minimizers not written
/// to the table). Returns `(mult, cyclic)`.
pub fn parse_node_mult(text: &str) -> (HashMap<u64, usize>, HashMap<u64, usize>) {
    let mut mult = HashMap::new();
    let mut cyclic = HashMap::new();
    let mut lines = text.lines();
    lines.next(); // "# SECTION nodes (mult>=2)"
    lines.next(); // header
    for ln in lines {
        if ln.starts_with("# SECTION edges") {
            break;
        }
        let f: Vec<&str> = ln.split('\t').collect();
        // Python: code = int(f[0]); mult[code]=int(f[1]); cyclic[code]=int(f[3])
        let code: u64 = match f[0].parse() {
            Ok(v) => v,
            Err(_) => continue,
        };
        mult.insert(code, f[1].parse().expect("node multiplicity parses"));
        cyclic.insert(code, f[3].parse().expect("node cyclic flag parses"));
    }
    (mult, cyclic)
}

/// Read + parse the `vg_repeat_catalog.tsv` node section (see `parse_node_mult`).
pub fn load_node_mult(path: &str) -> std::io::Result<(HashMap<u64, usize>, HashMap<u64, usize>)> {
    Ok(parse_node_mult(&std::fs::read_to_string(path)?))
}

