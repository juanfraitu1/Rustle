/// The CONJUNCTION gate decision. Faithful port of `gate_cut` (:229): CUT iff
/// (NOT skipped) AND (`no_full_shared_exon`) AND (`rep_bridges[t] >= several`) AND
/// (`guard_ok`). A `t` outside MULT_GRID reads `rep_bridges.get(t) -> 0` (Python
/// `.get(t, 0)`), so the gate does not fire for it.
pub fn gate_cut(plan: &Plan, t: usize, several: usize) -> bool {
    if plan.skipped {
        return false;
    }
    if !plan.no_full_shared_exon {
        return false;
    }
    if plan.rep_bridges.get(&t).copied().unwrap_or(0) < several {
        return false;
    }
    if !plan.guard_ok {
        return false;
    }
    true
}

