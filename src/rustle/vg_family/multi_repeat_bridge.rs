//! O1 multi-repeat-bridge gate -- faithful Rust port of the WIRED path of
//! `bench/multi_repeat_bridge_gate.py` (MRB) (the O1 over-merge-gate migration,
//! `docs/RETIREMENT_AND_MIGRATION.md` Tier-2 #7, full byte-parity path).
//!
//! WHAT THIS GATE DOES.  It removes the DISCONNECTED repeat-bridge RNA-level over-merge
//! class: families whose pairwise `E_r` oracle glued loci that share NO FULL EXON at
//! `id >= 0.70` (a sub-exonic Alu/repeat bridge, not real transcript homology) yet
//! survive the single-extreme-edge repeat-hub gate.  The recall-safe distinguisher is
//! the CONJUNCTION: (>=2 full-exon components AND cross-component best-exon-id < 0.70 =
//! NO full shared exon) AND (>= `several` DISTINCT cross-component shared VG minimizer
//! nodes each with global multiplicity >= `t`) AND the same-gene guard (never separate
//! same-gene loci).  GSTM2 (domain-share) + MAGE (cardinality) share a full exon => the
//! family is a SINGLE full-exon component => the gate STRUCTURALLY cannot fire (spared
//! at every threshold), which is the load-bearing "no-full-shared-exon" conjunct.
//!
//! WIRED PATH ONLY.  The DRIVER (`family_rna_refine.build_catalog`) calls exactly
//! `MRB.split_families_repeat_bridge(refined, genes, gene_of_dn, t=8, several=2)`; its
//! reachable code is `split_families_repeat_bridge` [:664] -> `split_family_repeat_bridge`
//! [:638] -> `characterize` [:122] + `gate_cut` [:229] (+ `_block_members` [:624],
//! `locus_node_set` [:103], `load_node_mult` [:86], `_stage_loaders` [:605]).  Ported here.
//!
//! DEFERRED (NOT wired-runtime -- analysis / gate-stage / sweeps; see the report):
//!   * `main` [:258], `gate_stage` [:773], `_rederive_disconnected` [:242],
//!     `analyze_family` (in RBD), `apply_gate`/`run_scope`, the MULT_GRID/SEVERAL_GRID
//!     sweeps, `_verdict`/`_gate_verdict`/`_metrics`/`_oracle_recall`/
//!     `real_loss_provenance`/`_cut_truth_classes`.
//!
//! REUSES the already-ported libraries -- nothing re-derived:
//!   * `super::bridge_detector`: `family_exons` / `exon_match_tensor` / `build_graph` /
//!     `connected_components` / `cross_component_maxid` + `ID_THRESH` (RBD exon graph),
//!     and `load_strand` (RBD's `_stage_loaders` strand map);
//!   * `super::repeat_catalog::dn_exons` (`vg_repeat_catalog.dn_exons`, introns-string
//!     convention) + `super::minimizers::{minimizers, MINIMIZER_K, MINIMIZER_W}` for the
//!     canonical-minimizer `locus_node_set`;
//!   * `super::family_loaders::GeneMeta` for the `genes` dict shape.
//!
//! fa_up vs fa_mask.  MRB opens TWO handles: `fa_up = FastaFile(R.GENOME)` and
//! `fa_mask = FastaFile(V.GENOME)`.  In the shipped build R.GENOME == V.GENOME ==
//! `GGO.fasta` (the SAME soft-masked file); `family_exons` reads via `fa_up` and
//! `.upper()`s every exon (exon IDENTITY is case-insensitive), while `locus_node_set`
//! reads via `fa_mask` and feeds the case-carrying bytes to `minimizers`.  BUT
//! `locus_node_set` returns `set(val for val, _ in minimizers(s))` -- it DISCARDS the
//! per-minimizer `masked` bool, and the canonical 2-bit `val` is itself case-insensitive
//! (`base_code` maps A/a,C/c,... identically).  So the node VALUES are independent of the
//! genome's soft-mask; `fa_up` and `fa_mask` are the same bytes here and the port takes a
//! single `ExonFetcher` for both.  (`family_exons` still upper-cases; `minimizers` still
//! reads the raw bytes -- both are honoured exactly.)
//!
//! Verified byte-identical to the shipped Python build against a golden fixture
//! (`testdata/multi_repeat_bridge_fixture.json`, generated by
//! `bench/gen_multi_repeat_bridge_fixture.py`, PYTHONHASHSEED=0); see the `#[test]`s.
//!
