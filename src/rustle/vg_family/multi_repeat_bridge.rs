/// The canonical-minimizer NODE SET of a locus = EXACTLY `vg_repeat_catalog`'s
/// construction: the spliced exonic sequence (`dn_exons` complement of the introns +
/// per-exon genome fetch, case-carrying) run through `minimizers`, keeping the
/// canonical VALUES (the per-minimizer `masked` bool is DISCARDED).
///
/// Faithful port of `locus_node_set` (:103):
///   * `meta.get(dn)` miss  -> `None` (Python returns `None`; `characterize` maps it to
///     an empty set);
///   * `V.dn_exons(dn, meta, vskel)` -> `(chrom, exons)` (never `None` here since meta
///     hit); an empty exon list => empty spliced sequence;
///   * the fetch join is wrapped in `try/except` -> any failed fetch yields the empty
///     set (here: a `None` from `fa.fetch` on any exon -> `Some(empty)`);
///   * `if len(s) < K: return set()`;
///   * else `set(val for val, _ in minimizers(s))`.
pub fn locus_node_set<F: ExonFetcher>(
    dn: &str,
    meta: &HashMap<String, (String, i64, i64)>,
    vskel: &HashMap<(String, i64, i64), String>,
    fa: &F,
) -> Option<HashSet<u64>> {
    // mm = meta.get(dn); if mm is None: return None
    meta.get(dn)?;
    // chrom, exons = V.dn_exons(dn, meta, vskel)   (Some, since meta hit)
    let (chrom, exons) = match dn_exons(dn, meta, vskel) {
        Some(x) => x,
        None => return Some(HashSet::new()), // defensive; unreachable on a meta hit
    };
    // s = "".join(fa.fetch(chrom, a, b) for a, b in exons)   (try/except -> empty set)
    let mut s: Vec<u8> = Vec::new();
    for (a, b) in exons {
        match fa.fetch(&chrom, a, b) {
            Some(part) => s.extend_from_slice(&part),
            None => return Some(HashSet::new()), // Python `except -> set()`
        }
    }
    if s.len() < MINIMIZER_K {
        return Some(HashSet::new());
    }
    Some(
        minimizers(&s, MINIMIZER_K, MINIMIZER_W)
            .into_iter()
            .map(|(val, _)| val)
            .collect(),
    )
}

