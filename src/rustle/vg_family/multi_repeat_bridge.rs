/// Member dicts `(dn, gene, chrom, start, end)` for a block of DN loci. Faithful port
/// of `_block_members` (:624): iterate `sorted(block)`, drop any `dn` absent from
/// `genes`, else build a member with `gene = gene_of_dn.get(dn, "NA")` and
/// `chrom/start/end` from `genes[dn]`.
pub fn block_members(
    block: &[String],
    genes: &HashMap<String, GeneMeta>,
    gene_of_dn: &HashMap<String, String>,
) -> Vec<Member> {
    let mut sb: Vec<String> = block.to_vec();
    sb.sort();
    let mut ms = Vec::new();
    for dn in &sb {
        let g = match genes.get(dn) {
            None => continue,
            Some(g) => g,
        };
        ms.push(Member {
            dn: dn.clone(),
            gene: gene_of_dn.get(dn).cloned().unwrap_or_else(|| "NA".to_string()),
            chrom: g.chrom.clone(),
            start: g.start,
            end: g.end,
        });
    }
    ms
}

