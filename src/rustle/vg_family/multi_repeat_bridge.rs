/// One entry of the split bookkeeping (Python `split_info` dict).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct SplitInfo {
    pub dominant: String,
    pub genes: Vec<String>,
    pub name: String,
    pub n_loci: usize,
    pub n_parts: usize,
    pub subfam_genes: Vec<String>,
}

/// Apply the gate to a list of refined blocks. Faithful port of
/// `split_families_repeat_bridge` (:664): for each block, `split_family_repeat_bridge`;
/// if it produced `> 1` parts, record a `SplitInfo` (pre-split gene set + dominant +
/// per-part dominants); extend `new_refined` by the parts. Returns
/// `(new_refined, split_info)`.
///
/// ORDER CONTRACT: `dominant` is `Counter(gene_of_dn[dn] for dn in b ...).most_common(1)`,
/// whose tie-break is the FIRST gene seen while iterating `b`; so the port iterates each
/// block in the EXACT element order given (the driver feeds sorted DN lists). `genes`
/// (`pre_genes`) is a sorted set and `subfam_genes` iterate sorted parts, so those are
/// order-independent.
pub fn split_families_repeat_bridge<F: ExonFetcher>(
    refined: &[Vec<String>],
    genes: &HashMap<String, GeneMeta>,
    gene_of_dn: &HashMap<String, String>,
    t: usize,
    several: usize,
    res: &StageLoaders<F>,
) -> (Vec<Vec<String>>, Vec<SplitInfo>) {
    let mut new_refined: Vec<Vec<String>> = Vec::new();
    let mut split_info: Vec<SplitInfo> = Vec::new();
    for b in refined {
        let (parts, _) = split_family_repeat_bridge(b, genes, gene_of_dn, t, several, res);
        if parts.len() > 1 {
            // pre_genes = sorted({gene_of_dn[dn] for dn in b if not None/NA})
            let mut pre_set: BTreeSet<String> = BTreeSet::new();
            for dn in b {
                if let Some(g) = gene_of_dn.get(dn) {
                    if g != "NA" {
                        pre_set.insert(g.clone());
                    }
                }
            }
            let pre_genes: Vec<String> = pre_set.into_iter().collect();
            // dom = Counter(gene_of_dn[dn] for dn in b if not None/NA).most_common(1)
            let dom_seq: Vec<String> = b
                .iter()
                .filter_map(|dn| gene_of_dn.get(dn))
                .filter(|g| g.as_str() != "NA")
                .cloned()
                .collect();
            let dominant = most_common_gene(&dom_seq).unwrap_or_else(|| "NA".to_string());
            // per-part dominants
            let mut subfam_genes: Vec<String> = Vec::new();
            for p in &parts {
                let gs: Vec<String> = p
                    .iter()
                    .filter_map(|dn| gene_of_dn.get(dn))
                    .filter(|g| g.as_str() != "NA")
                    .cloned()
                    .collect();
                subfam_genes.push(most_common_gene(&gs).unwrap_or_else(|| "NA".to_string()));
            }
            let name = if pre_genes.is_empty() {
                "NA".to_string()
            } else {
                pre_genes.join("+")
            };
            split_info.push(SplitInfo {
                dominant,
                genes: pre_genes,
                name,
                n_loci: parts.iter().map(|p| p.len()).sum(),
                n_parts: parts.len(),
                subfam_genes,
            });
        }
        new_refined.extend(parts);
    }
    (new_refined, split_info)
}

/// `collections.Counter(seq).most_common(1)[0][0]` -- the highest-count element, ties
/// broken by FIRST-SEEN in iteration order (CPython `most_common` is stable on equal
/// counts). `None` iff `seq` is empty.
fn most_common_gene(seq: &[String]) -> Option<String> {
    let mut order: Vec<&String> = Vec::new();
    let mut counts: HashMap<&String, usize> = HashMap::new();
    for g in seq {
        if !counts.contains_key(g) {
            order.push(g);
        }
        *counts.entry(g).or_insert(0) += 1;
    }
    let mut best: Option<&String> = None;
    for g in order {
        match best {
            None => best = Some(g),
            Some(b) => {
                if counts[g] > counts[b] {
                    best = Some(g);
                }
            }
        }
    }
    best.cloned()
}

