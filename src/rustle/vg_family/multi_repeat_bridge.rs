/// The per-family CHARACTERIZE "plan": the full-exon component split + the fields the
/// gate reads. Mirrors the Python `dict` returned by `characterize`.
///
/// `characterize` returns `None` (Python) iff `n < 2` (fewer than 2 skeleton'd recs);
/// otherwise a `Plan` with `skipped == true` iff `n > MAX_MEMBERS` (in which case only
/// `n_members` / `n_distinct_genes` / `same_gene_family` are meaningful and `comps_dn`
/// / `all_dn` are empty, mirroring the Python `comps_dn=None, all_dn=None`).
#[derive(Clone, Debug, Default, PartialEq)]
pub struct Plan {
    pub n_members: usize,
    pub n_distinct_genes: usize,
    pub same_gene_family: bool,
    pub skipped: bool,
    // -- below only meaningful when `!skipped` --
    pub n_comp: usize,
    pub connected: bool,
    pub shares_full_exon: bool,
    /// `None` iff `n_comp <= 1` (Python `xcomp_id = ... if n_comp > 1 else None`).
    pub xcomp_best_exon_id: Option<f64>,
    pub no_full_shared_exon: bool,
    pub n_cross_pairs: usize,
    pub n_cross_pairs_with_node: usize,
    pub n_cross_shared_nodes: usize,
    pub max_cross_mult: usize,
    pub med_cross_mult: usize,
    pub n_cross_cyclic: usize,
    /// `t -> #distinct cross-component shared nodes with multiplicity >= t`, over MULT_GRID.
    pub rep_bridges: BTreeMap<usize, usize>,
    pub n_internal_shared_nodes: usize,
    pub max_internal_mult: usize,
    pub n_internal_repeat_m8: usize,
    pub min_comp_size: usize,
    pub separates_same_gene: bool,
    pub guard_ok: bool,
    /// full-exon components as sorted DN lists (Python `comps_dn`, frozensets -> sorted).
    pub comps_dn: Vec<Vec<String>>,
    /// every DN kept by `family_exons`, in rec order (Python `all_dn`).
    pub all_dn: Vec<String>,
}

/// `_distinct_genes(members)` (:254): sorted set of member genes excluding `"NA"`/`""`.
fn distinct_genes(members: &[Member]) -> Vec<String> {
    let mut s: BTreeSet<String> = BTreeSet::new();
    for m in members {
        if m.gene != "NA" && !m.gene.is_empty() {
            s.insert(m.gene.clone());
        }
    }
    s.into_iter().collect()
}

/// Build the CHARACTERIZE plan for a family. Faithful port of `characterize` (:122);
/// see the field-by-field comments. Returns `None` iff `n < 2`.
///
/// `fa_up` feeds `family_exons` (`.upper()`ed exon identity); `fa_mask` feeds
/// `locus_node_set` (case-carrying minimizers). In the shipped build these are the SAME
/// genome; the two parameters are kept distinct to mirror `characterize`'s signature.
#[allow(clippy::too_many_arguments)]
pub fn characterize<F: ExonFetcher, G: ExonFetcher>(
    members: &[Member],
    r_skel: &HashMap<(String, i64, i64), Vec<(i64, i64)>>,
    strand: &HashMap<String, String>,
    fa_up: &F,
    meta: &HashMap<String, (String, i64, i64)>,
    vskel: &HashMap<(String, i64, i64), String>,
    fa_mask: &G,
    mult: &HashMap<u64, usize>,
    cyclic: &HashMap<u64, usize>,
) -> Option<Plan> {
    let recs = family_exons(members, r_skel, strand, fa_up);
    let n = recs.len();
    if n < 2 {
        return None;
    }
    let dg = distinct_genes(members);
    let n_distinct_genes = dg.len();
    let same_gene_family = n_distinct_genes <= 1;

    if n > MAX_MEMBERS {
        // skip dict: only n_members / n_distinct_genes / same_gene_family meaningful.
        return Some(Plan {
            n_members: n,
            n_distinct_genes,
            same_gene_family,
            skipped: true,
            ..Default::default()
        });
    }

    // ---- full-exon locus graph (REUSE the recombination detector) ----
    let best = exon_match_tensor(&recs);
    let graph = build_graph(&recs, &best);
    let comps = graph.connected_components(); // sorted comps, sorted by first element
    let n_comp = comps.len();
    let comps_dn: Vec<Vec<String>> = comps
        .iter()
        .map(|comp| {
            // frozenset(recs[i]["dn"] for i in comp) -> sorted DN list
            let mut s: BTreeSet<String> = BTreeSet::new();
            for &i in comp {
                s.insert(recs[i].dn.clone());
            }
            s.into_iter().collect()
        })
        .collect();
    let all_dn: Vec<String> = recs.iter().map(|r| r.dn.clone()).collect();
    let connected = n_comp == 1;
    let shares_full_exon = connected;
    let xcomp_id = if n_comp > 1 {
        Some(cross_component_maxid(&recs, &best, &comps))
    } else {
        None
    };
    let no_full_shared_exon = n_comp >= 2 && xcomp_id.map(|x| x < ID_THRESH).unwrap_or(false);

    // comp_of[i]
    let mut comp_of: Vec<usize> = vec![0; n];
    for (ci, comp) in comps.iter().enumerate() {
        for &m in comp {
            comp_of[m] = ci;
        }
    }

    // ---- per-locus node sets ----
    let nodesets: Vec<HashSet<u64>> = recs
        .iter()
        .map(|r| locus_node_set(&r.dn, meta, vskel, fa_mask).unwrap_or_default())
        .collect();

    // ---- cross-component (bridge) shared nodes vs all-pairs internal shared nodes ----
    let mut cross_shared: HashMap<u64, usize> = HashMap::new();
    let mut cross_codes: Vec<u64> = Vec::new(); // distinct keys (order irrelevant to outputs)
    let mut internal_shared: HashSet<u64> = HashSet::new();
    let mut n_cross_pairs = 0usize;
    let mut n_cross_pairs_with_node = 0usize;
    for a in 0..n {
        for b in (a + 1)..n {
            let sh: Vec<u64> = nodesets[a].intersection(&nodesets[b]).copied().collect();
            for &c in &sh {
                internal_shared.insert(c);
            }
            if comp_of[a] != comp_of[b] {
                n_cross_pairs += 1;
                if !sh.is_empty() {
                    n_cross_pairs_with_node += 1;
                }
                for &c in &sh {
                    let e = cross_shared.entry(c).or_insert(0);
                    if *e == 0 {
                        cross_codes.push(c);
                    }
                    *e += 1;
                }
            }
        }
    }

    let mut cross_mults: Vec<usize> = cross_codes.iter().map(|&c| mult_of(mult, c)).collect();
    cross_mults.sort_unstable();
    let mut rep_bridges: BTreeMap<usize, usize> = BTreeMap::new();
    for &t in MULT_GRID.iter() {
        let nb = cross_codes.iter().filter(|&&c| mult_of(mult, c) >= t).count();
        rep_bridges.insert(t, nb);
    }
    let n_cross_cyclic = cross_codes
        .iter()
        .filter(|&&c| cyclic.get(&c).copied().unwrap_or(0) != 0)
        .count();
    let max_cross_mult = cross_mults.last().copied().unwrap_or(0);
    let med_cross_mult = if cross_mults.is_empty() {
        0
    } else {
        cross_mults[cross_mults.len() / 2]
    };

    let internal_mults: Vec<usize> = internal_shared.iter().map(|&c| mult_of(mult, c)).collect();
    let max_internal_mult = internal_mults.iter().copied().max().unwrap_or(0);
    let n_internal_repeat_m8 = internal_mults.iter().filter(|&&v| v >= 8).count();

    // ---- recall-safety guard (never separate same-gene loci) ----
    let min_comp_size = comps.iter().map(|c| c.len()).min().unwrap_or(n);
    let mut gene_comps: HashMap<String, BTreeSet<usize>> = HashMap::new();
    for (i, r) in recs.iter().enumerate() {
        if r.gene != "NA" && !r.gene.is_empty() {
            gene_comps.entry(r.gene.clone()).or_default().insert(comp_of[i]);
        }
    }
    let separates_same_gene = gene_comps.values().any(|cs| cs.len() >= 2);
    let guard_ok = n_comp >= 2 && !separates_same_gene;

    Some(Plan {
        n_members: n,
        n_distinct_genes,
        same_gene_family,
        skipped: false,
        n_comp,
        connected,
        shares_full_exon,
        xcomp_best_exon_id: xcomp_id,
        no_full_shared_exon,
        n_cross_pairs,
        n_cross_pairs_with_node,
        n_cross_shared_nodes: cross_codes.len(),
        max_cross_mult,
        med_cross_mult,
        n_cross_cyclic,
        rep_bridges,
        n_internal_shared_nodes: internal_shared.len(),
        max_internal_mult,
        n_internal_repeat_m8,
        min_comp_size,
        separates_same_gene,
        guard_ok,
        comps_dn,
        all_dn,
    })
}

/// `mult.get(c, 1)` -- absent nodes default to multiplicity 1 (Python).
#[inline]
fn mult_of(mult: &HashMap<u64, usize>, c: u64) -> usize {
    mult.get(&c).copied().unwrap_or(1)
}

