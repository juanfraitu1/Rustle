//! O1 family-definition LOADERS (Rust port of the Python reference).
//!
//! Faithful Rust port of the input loaders + DN-locus->gene projection that feed
//! the already-ported `distinct_loci` / `refine_families` operators in
//! `family_definition.rs`. This is the next increment of the Python->Rust
//! family-definition migration (`docs/RETIREMENT_AND_MIGRATION.md` Tier-1 #2).
//!
//! Ported functions (Python source is the SPEC; line refs are the shipped file):
//!   * `components_from_edges` (bench/graph_def_refine_sweep.py:180)  -- partition
//!     nodes into connected components using ONLY the kept edges;
