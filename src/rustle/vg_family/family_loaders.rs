/// One annotation interval `(start, end, biotype, gene)` on a contig.
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct AnnotInterval {
    pub start: i64,
    pub end: i64,
    pub biotype: String,
    pub gene: String,
}

/// Per-contig annotation index: intervals sorted by the FULL tuple
/// `(start, end, biotype, gene)` (matching Python's `ivals.sort()`), the parallel
/// `starts` vector for binary search, and the max interval length on the contig.
#[derive(Clone, Debug)]
pub struct ContigAnnot {
    pub starts: Vec<i64>,
    pub ivals: Vec<AnnotInterval>,
    pub maxlen: i64,
}

/// The whole annotation: `contig -> ContigAnnot`. Faithful port of `load_annot`.
#[derive(Clone, Debug, Default)]
pub struct Annot {
    pub by_contig: HashMap<String, ContigAnnot>,
}

impl Annot {
    /// Build from `contig -> unsorted intervals` (the `by_c` dict in `load_annot`).
    /// Sorts each contig's intervals by `(start, end, biotype, gene)` and records
    /// `starts` + `maxlen` exactly as the Python does.
    pub fn build(by_contig: HashMap<String, Vec<AnnotInterval>>) -> Annot {
        let mut out: HashMap<String, ContigAnnot> = HashMap::new();
        for (c, mut ivals) in by_contig {
            // Python `ivals.sort()` on (int,int,str,str) tuples -> lexicographic.
            ivals.sort_by(|a, b| {
                (a.start, a.end, &a.biotype, &a.gene).cmp(&(b.start, b.end, &b.biotype, &b.gene))
            });
            let starts: Vec<i64> = ivals.iter().map(|iv| iv.start).collect();
            // Python: maxlen = max(e - s for ...). Non-empty by construction.
            let maxlen = ivals.iter().map(|iv| iv.end - iv.start).max().unwrap_or(0);
            out.insert(c, ContigAnnot { starts, ivals, maxlen });
        }
        Annot { by_contig: out }
    }

    /// Parse the ANNOT TSV text into an `Annot` (see `load_annot`). Columns:
    /// `f[0]=contig f[1]=start f[2]=end f[3]=biotype f[4]=gene`; skips the header.
    pub fn from_str(text: &str) -> Annot {
        let mut by_c: HashMap<String, Vec<AnnotInterval>> = HashMap::new();
        for line in text.lines().skip(1) {
            let f: Vec<&str> = line.split('\t').collect();
            by_c.entry(f[0].to_string()).or_default().push(AnnotInterval {
                start: f[1].parse().expect("annot start int"),
                end: f[2].parse().expect("annot end int"),
                biotype: f[3].to_string(),
                gene: f[4].to_string(),
            });
        }
        Annot::build(by_c)
    }

    /// Max-overlap annotation interval for a DN locus `[qs, qe)`, plus the overlap
    /// fraction `ovf = max(overlap/DN_span, overlap/gene_span)`. Returns
    /// `(gene, biotype, ovf)`, or `(None, None, 0.0)` when the locus overlaps no
    /// interval. FAITHFUL port of the Python `gene_of` -- the load-bearing details:
    ///
    ///   * scan intervals with `start <= qe` DOWNWARD from `bisect_right`;
    ///   * BREAK when `start < qs - maxlen` (a valid prune: any real overlapper has
    ///     span `<= maxlen`, so its start `> qs - maxlen`);
    ///   * count overlap `ov = min(e,qe) - max(s,qs)` only when `e > qs`;
    ///   * keep the STRICTLY-greatest `ov` (`if ov > best_ov`) -- ties keep the
    ///     FIRST-scanned interval = the highest `start` (with the `(start,end,bt,
    ///     gene)` tuple order as the sub-tie-break). This scan order + strict `>`
    ///     are preserved EXACTLY.
    pub fn gene_of(&self, chrom: &str, qs: i64, qe: i64) -> (Option<String>, Option<String>, f64) {
        let rec = match self.by_contig.get(chrom) {
            Some(r) => r,
            None => return (None, None, 0.0),
        };
        // hi = bisect_right(starts, qe) == number of starts <= qe.
        let hi = rec.starts.partition_point(|&s| s <= qe);
        let mut best_ov: i64 = 0;
        let mut best_gene: Option<&str> = None;
        let mut best_bt: Option<&str> = None;
        let mut best_span: i64 = 0;
        let lo_bound = qs - rec.maxlen;
        let mut i = hi as isize - 1;
        while i >= 0 {
            let iv = &rec.ivals[i as usize];
            if iv.start < lo_bound {
                break;
            }
            if iv.end > qs {
                let ov = iv.end.min(qe) - iv.start.max(qs);
                if ov > best_ov {
                    best_ov = ov;
                    best_gene = Some(&iv.gene);
                    best_bt = Some(&iv.biotype);
                    best_span = iv.end - iv.start;
                }
            }
            i -= 1;
        }
        match best_gene {
            None => (None, None, 0.0),
            Some(g) => {
                let dn_span = qe - qs;
                let frac_dn = if dn_span > 0 {
                    best_ov as f64 / dn_span as f64
                } else {
                    0.0
                };
                let frac_gene = if best_span > 0 {
                    best_ov as f64 / best_span as f64
                } else {
                    0.0
                };
                (
                    Some(g.to_string()),
                    best_bt.map(|s| s.to_string()),
                    frac_dn.max(frac_gene),
                )
            }
        }
    }
}

/// Read the ANNOT TSV file and parse it (see `Annot::from_str`).
pub fn load_annot(path: &str) -> std::io::Result<Annot> {
    Ok(Annot::from_str(&std::fs::read_to_string(path)?))
}

