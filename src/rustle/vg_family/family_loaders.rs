/// DENOVO_FAMS TSV -> list of families, each a `Vec<DN id>` (the `f[2]` comma
/// list). Skips the header. Faithful port of `load_raw_families`.
pub fn load_raw_families_str(text: &str) -> Vec<Vec<String>> {
    let mut fams = Vec::new();
    for line in text.lines().skip(1) {
        let f: Vec<&str> = line.split('\t').collect();
        fams.push(f[2].split(',').map(|s| s.to_string()).collect());
    }
    fams
}

/// Read the DENOVO_FAMS TSV file and parse it (see `load_raw_families_str`).
pub fn load_raw_families(path: &str) -> std::io::Result<Vec<Vec<String>>> {
    Ok(load_raw_families_str(&std::fs::read_to_string(path)?))
}

/// DENOVO_EDGES TSV -> list of `(a, b)` pairs (`f[0]`, `f[1]`). Skips the header.
/// Faithful port of `load_edges` (no dedup; order preserved).
pub fn load_edges_str(text: &str) -> Vec<(String, String)> {
    let mut edges = Vec::new();
    for line in text.lines().skip(1) {
        let f: Vec<&str> = line.split('\t').collect();
        edges.push((f[0].to_string(), f[1].to_string()));
    }
    edges
}

/// Read the DENOVO_EDGES TSV file and parse it (see `load_edges_str`).
pub fn load_edges(path: &str) -> std::io::Result<Vec<(String, String)>> {
    Ok(load_edges_str(&std::fs::read_to_string(path)?))
}

