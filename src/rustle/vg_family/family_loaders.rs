/// Per-DN gene metadata (one entry of the Python `genes` dict): the DN locus
/// coords plus the floored gene projection. `biotype`/`name` default to `"NA"` /
/// the DN id when the projection is dropped by `OV_FLOOR`; `ov` is the UNFLOORED
/// overlap fraction (kept for the sensitivity report).
#[derive(Clone, Debug, PartialEq)]
pub struct GeneMeta {
    pub chrom: String,
    pub start: i64,
    pub end: i64,
    pub biotype: String,
    pub name: String,
    pub ov: f64,
}

impl GeneMeta {
    /// Project to the `Gene` shape consumed by `refine_families` / `distinct_loci`
    /// (drops the `ov` field). Lets the ported loaders feed the ported refiner.
    pub fn to_gene(&self) -> Gene {
        Gene {
            chrom: self.chrom.clone(),
            start: self.start,
            end: self.end,
            name: self.name.clone(),
            biotype: self.biotype.clone(),
        }
    }
}

/// Overlap-fraction contamination counts (the Python `ovstats` dict).
#[derive(Clone, Debug, PartialEq, Eq)]
pub struct OvStats {
    pub mapped_raw: usize,
    pub mapped_floored: usize,
    pub dropped_by_floor: usize,
    pub lt20_overlap: usize,
    pub lt50_overlap: usize,
}

/// Result of `build_genes_dict`: the `genes` metadata map plus the floored /
/// unfloored gene projections and the diagnostic counters.
#[derive(Clone, Debug)]
pub struct BuildGenes {
    /// DN id -> gene metadata (the Python `genes` dict).
    pub genes: HashMap<String, GeneMeta>,
    /// DN id -> gene, FLOORED (`ovf >= OV_FLOOR`) -- the headline projection.
    pub gene_of_dn: HashMap<String, String>,
    /// DN id -> gene, UNFLOORED max-overlap map (any truthy gene).
    pub gene_of_dn_raw: HashMap<String, String>,
    /// Count of DN ids absent from `meta` (resolved by the fallback id parse).
    pub miss_meta: usize,
    pub ovstats: OvStats,
}

/// Assemble the per-DN `genes` metadata for every member of every raw family.
///
/// Faithful port of `build_genes_dict`. For each DN member (FIRST occurrence
/// wins across the flattened `raw_fams`):
///   1. look up `meta`; if missing, count it and parse `DN_<contig>_<start>_<nreads>`
///      -> `chrom = "_".join(parts[1:-2])`, `start = int(parts[-2])`, `end = start`
///      (the contig may itself contain underscores);
///   2. project to a gene via `annot.gene_of` -> `(g, bt, ovf)`;
///   3. `keep = g.is_some() && ovf >= OV_FLOOR`;
///   4. `genes[dn] = {chrom,start,end, biotype: keep?bt:"NA", name: keep?g:dn, ov: ovf}`;
///   5. `gene_of_dn[dn] = g` iff `keep`; `gene_of_dn_raw[dn] = g` iff `g` is truthy.
///
/// All of the fallback parse, the floor, the `"NA"`/self-name defaults, and the
/// `ovstats` counters are preserved exactly.
pub fn build_genes_dict(
    raw_fams: &[Vec<String>],
    meta: &HashMap<String, (String, i64, i64)>,
    annot: &Annot,
) -> BuildGenes {
    let mut genes: HashMap<String, GeneMeta> = HashMap::new();
    let mut gene_of_dn: HashMap<String, String> = HashMap::new();
    let mut gene_of_dn_raw: HashMap<String, String> = HashMap::new();
    let mut seen: HashSet<String> = HashSet::new();
    let mut miss_meta = 0usize;
    let mut lt20 = 0usize;
    let mut lt50 = 0usize;
    let mut mapped_raw = 0usize;

    for fam in raw_fams {
        for dn in fam {
            // Python: `if dn in genes: continue` -- first occurrence wins.
            if !seen.insert(dn.clone()) {
                continue;
            }
            let (chrom, start, end) = match meta.get(dn) {
                Some((c, s, e)) => (c.clone(), *s, *e),
                None => {
                    miss_meta += 1;
                    // DN_<contig...>_<start>_<nreads>; contig may contain underscores.
                    let parts: Vec<&str> = dn.split('_').collect();
                    let n = parts.len();
                    let start: i64 = parts[n - 2].parse().expect("fallback start int");
                    let chrom = parts[1..n - 2].join("_");
                    (chrom, start, start)
                }
            };
            let (g, bt, ovf) = annot.gene_of(&chrom, start, end);
            let keep = g.is_some() && ovf >= OV_FLOOR;
            genes.insert(
                dn.clone(),
                GeneMeta {
                    chrom,
                    start,
                    end,
                    biotype: if keep {
                        bt.clone().unwrap()
                    } else {
                        "NA".to_string()
                    },
                    name: if keep {
                        g.clone().unwrap()
                    } else {
                        dn.clone()
                    },
                    ov: ovf,
                },
            );
            if let Some(gname) = &g {
                gene_of_dn_raw.insert(dn.clone(), gname.clone());
                mapped_raw += 1;
                if ovf < 0.20 {
                    lt20 += 1;
                }
                if ovf < 0.50 {
                    lt50 += 1;
                }
            }
            if keep {
                gene_of_dn.insert(dn.clone(), g.unwrap());
            }
        }
    }

    let ovstats = OvStats {
        mapped_raw,
        mapped_floored: gene_of_dn.len(),
        dropped_by_floor: mapped_raw - gene_of_dn.len(),
        lt20_overlap: lt20,
        lt50_overlap: lt50,
    };
    BuildGenes {
        genes,
        gene_of_dn,
        gene_of_dn_raw,
        miss_meta,
        ovstats,
    }
}

