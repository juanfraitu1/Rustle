    fn gene_of_tie_break_keeps_first_scanned_highest_start() {
        // Two intervals give the SAME overlap (500) to query [1000,2000):
        //   LOW : [500,1500)  ov = 500, span 1000
        //   HIGH: [1500,3000) ov = 500, span 1500
        // Descending scan hits HIGH first; strict `>` keeps it (LOW does not replace).
        let mut by = HashMap::new();
        by.insert(
            "c".to_string(),
            vec![iv(500, 1500, "bt_low", "GENE_LOW"), iv(1500, 3000, "bt_high", "GENE_HIGH")],
        );
        let annot = Annot::build(by);
        let (g, bt, ovf) = annot.gene_of("c", 1000, 2000);
        assert_eq!(g.as_deref(), Some("GENE_HIGH"));
        assert_eq!(bt.as_deref(), Some("bt_high"));
        assert!((ovf - 0.5).abs() < 1e-12, "ovf = {ovf}"); // max(500/1000, 500/1500)
    }

