/// DN id -> `(chrom, start, end)`, skipping the header line. Faithful port of
/// `load_meta` operating on the raw TSV text (`load_meta` reads the file and
/// delegates here). Columns: `f[0]=id  f[1]=chrom  f[2]=start  f[3]=end`.
pub fn load_meta_str(text: &str) -> HashMap<String, (String, i64, i64)> {
    let mut m = HashMap::new();
    for line in text.lines().skip(1) {
        // Python: f = ln.rstrip("\n").split("\t")
        let f: Vec<&str> = line.split('\t').collect();
        let start: i64 = f[2].parse().expect("meta start int");
        let end: i64 = f[3].parse().expect("meta end int");
        m.insert(f[0].to_string(), (f[1].to_string(), start, end));
    }
    m
}

/// Read the META TSV file and parse it (see `load_meta_str`).
pub fn load_meta(path: &str) -> std::io::Result<HashMap<String, (String, i64, i64)>> {
    Ok(load_meta_str(&std::fs::read_to_string(path)?))
}

