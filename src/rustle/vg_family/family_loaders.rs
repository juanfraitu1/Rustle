use std::collections::{BTreeSet, HashMap, HashSet};

use super::family_definition::Gene;

/// Minimum overlap fraction for the DN-locus -> gene projection to be KEPT.
///
/// A projection is kept iff its overlap covers `>= OV_FLOOR` of the DN span OR
/// `>= OV_FLOOR` of the gene span. Below the floor the locus name/biotype default
/// to the DN id / `"NA"` (a spurious `<20%` clip must not seed a block name or
/// inflate the over-merge count). Hard-coded from the Python constant
/// `bench/family_er_pr.py:69  OV_FLOOR = 0.20`.
pub const OV_FLOOR: f64 = 0.20;

