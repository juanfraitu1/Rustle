/// Partition `all_nodes` into connected components using ONLY `kept_edges`.
///
/// Faithful port of the Python `components_from_edges`: it builds a graph over
/// `all_nodes` PLUS every endpoint appearing in `kept_edges` (networkx
/// `add_edge` implicitly adds unseen endpoints), then returns the connected
/// components. Each `kept_edges` entry is an unordered pair `(u, v)` (the Python
/// `frozenset` pair). The component ORDER is irrelevant to the caller (the
/// Python result is a `[set(...)]`); the returned `Vec<BTreeSet>` is nonetheless
/// deterministic (union-find over the sorted node universe).
pub fn components_from_edges(
    all_nodes: &[String],
    kept_edges: &[(String, String)],
) -> Vec<BTreeSet<String>> {
    // Node universe = all_nodes UNION every edge endpoint (networkx semantics).
    let mut universe: BTreeSet<&str> = BTreeSet::new();
    for n in all_nodes {
        universe.insert(n.as_str());
    }
    for (u, v) in kept_edges {
        universe.insert(u.as_str());
        universe.insert(v.as_str());
    }
    // Stable index assignment in sorted node order -> deterministic output.
    let verts: Vec<&str> = universe.iter().copied().collect();
    let idx: HashMap<&str, usize> = verts.iter().enumerate().map(|(i, &v)| (v, i)).collect();

    let mut parent: Vec<usize> = (0..verts.len()).collect();
    fn find(parent: &mut [usize], x: usize) -> usize {
        let mut root = x;
        while parent[root] != root {
            root = parent[root];
        }
        let mut cur = x;
        while parent[cur] != root {
            let next = parent[cur];
            parent[cur] = root;
            cur = next;
        }
        root
    }
    for (u, v) in kept_edges {
        let (ru, rv) = (find(&mut parent, idx[u.as_str()]), find(&mut parent, idx[v.as_str()]));
        if ru != rv {
            parent[ru] = rv;
        }
    }

    // Group nodes by root; each group is one connected component.
    let mut groups: HashMap<usize, BTreeSet<String>> = HashMap::new();
    for (i, &v) in verts.iter().enumerate() {
        let r = find(&mut parent, i);
        groups.entry(r).or_default().insert(v.to_string());
    }
    let mut comps: Vec<BTreeSet<String>> = groups.into_values().collect();
    // Deterministic order (by smallest member) -- cosmetic; callers compare as a set.
    comps.sort_by(|a, b| a.iter().next().cmp(&b.iter().next()));
    comps
}

