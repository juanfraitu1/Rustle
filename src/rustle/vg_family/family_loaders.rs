//!     intervals + maxlen;
//!   * `gene_of`     (bench/family_er_pr.py:111)  -- max-overlap annotation interval
//!     for a DN locus (the SUBTLE one: strict `>` tie-break + descending-scan order
//!     are load-bearing; see `Annot::gene_of`);
//!   * `load_raw_families` (bench/family_er_pr.py:148) -- DENOVO_FAMS TSV -> families;
//!   * `load_edges`  (bench/family_er_pr.py:158)  -- DENOVO_EDGES TSV -> (a,b) pairs;
//!   * `build_genes_dict` (bench/family_er_pr.py:284) -- assemble the per-DN gene
