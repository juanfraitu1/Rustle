/// 2x2 strand-by-junction-usage counts over reads spanning `(donor, acceptor)`.
/// Returns `(r_fwd, r_rev, a_fwd, a_rev) = (used+, used-, notused+, notused-)` RAW (no
/// pseudocount). Faithful port of `bench/asj_strand_bias.py::strand_table`.
///
/// `donor`/`acceptor` must already be NORMALISED (`donor <= acceptor`; the caller swaps).
/// The read set is the indexed query over `[donor, acceptor+1)` — pysam
/// `fetch(chrom, donor, acceptor + 1)` (0-based half-open) == the 1-based inclusive region
/// `{chrom}:{donor+1}-{acceptor+1}`. Both return exactly the reads whose alignment overlaps
/// that interval, so re-applying the identical Python post-filter yields identical counts.
///
/// Per read (Python lines 79-94):
///  1. skip `is_unmapped` (0x4) / `is_secondary` (0x100) / `is_supplementary` (0x800) /
///     no-CIGAR (`cigartuples is None`);
///  2. require SPAN: `reference_start <= donor && reference_end >= acceptor`, where
///     `reference_end = reference_start + cigar reference-span` (sum of `M/D/N/=/X`),
///     exactly pysam's `reference_end`;
///  3. `used = (donor, acceptor) in introns(read)`; `rev = is_reverse` (flag 0x10 =
///     noodles `is_reverse_complemented`);
///  4. tally into `(used, rev)` -> one of `r_fwd/r_rev/a_fwd/a_rev`.
///
/// Opens a fresh reader per call (cheap) and uses the caller-cached `header`/`index`
/// (parsing the multi-MB `.bai` once), matching [`super::denovo_assemble::BamIndexCache`].
pub fn strand_table(
    bam_path: &str,
    header: &noodles_sam::Header,
    index: &noodles_bam::bai::Index,
    chrom: &str,
    donor: i64,
    acceptor: i64,
) -> Result<(i64, i64, i64, i64)> {
    let mut reader = noodles_bam::io::reader::Builder::default().build_from_path(bam_path)?;
    // pysam fetch(chrom, donor, acceptor+1) 0-based half-open == 1-based inclusive [donor+1, acceptor+1].
    let region: noodles_core::Region =
        format!("{chrom}:{}-{}", donor + 1, acceptor + 1).parse()?;
    let query = reader.query(header, index, &region)?;

    let (mut r_fwd, mut r_rev, mut a_fwd, mut a_rev) = (0i64, 0i64, 0i64, 0i64);
    for result in query {
        let record = result?;
        let rb = RecordBuf::try_from_alignment_record(header, &record)?;

        let flags = rb.flags();
        if flags.is_unmapped() || flags.is_secondary() || flags.is_supplementary() {
            continue;
        }
        // cigartuples is None -> skip (an empty CIGAR record).
        let cigar = rb.cigar();
        if cigar.as_ref().is_empty() {
            continue;
        }
        let Some(start) = rb.alignment_start() else {
            continue;
        };
        let ref_start = start.get() as i64 - 1;
        let span = cigar.alignment_span() as i64;
        if span == 0 {
            // pysam reference_end is None here; such a read is never returned by fetch
            // (it has no reference overlap) -> skip defensively (cannot affect parity).
            continue;
        }
        let ref_end = ref_start + span;
        // SPAN the junction: reference_start <= donor AND reference_end >= acceptor.
        if ref_start > donor || ref_end < acceptor {
            continue;
        }
        let used = introns(&rb).iter().any(|&(s, e)| s == donor && e == acceptor);
        let rev = flags.is_reverse_complemented(); // flag 0x10 == pysam is_reverse
        match (used, rev) {
            (true, false) => r_fwd += 1,
            (true, true) => r_rev += 1,
            (false, false) => a_fwd += 1,
            (false, true) => a_rev += 1,
        }
    }
    Ok((r_fwd, r_rev, a_fwd, a_rev))
}

