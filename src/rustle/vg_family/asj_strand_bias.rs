// fisher_strand_p  (bench/asj_strand_bias.py:111) — NON-gate cross-check
// ===========================================================================

/// Fisher-exact strand-bias p over the raw 2x2 `[[r_fwd, r_rev], [a_fwd, a_rev]]` — a
/// cross-check column, NOT the gate. Port of `bench/asj_strand_bias.py::fisher_strand_p`.
///
/// REUSES [`super::allele_specific_junctions::fisher_exact_2x2`], which implements scipy's
/// two-sided convention (sum the hypergeometric probabilities of all same-margin tables no
/// more likely than observed). It matches `scipy.stats.fisher_exact` to ~4e-13 across the
/// real calls (measured; see the fixture's `max_fisher_div_vs_rust_replica`), NOT
/// bit-for-bit — it uses a Lanczos `ln Γ` rather than libm. scipy never raises for these
/// non-negative tables (degenerate/all-zero margins -> `1.0`), so this never returns `NaN`;
/// the only `NaN` fisher arises in the chrom-not-in-refs branch handled by the driver.
pub fn fisher_strand_p(r_fwd: i64, r_rev: i64, a_fwd: i64, a_rev: i64) -> f64 {
    super::allele_specific_junctions::fisher_exact_2x2(
        r_fwd as u32,
        r_rev as u32,
        a_fwd as u32,
        a_rev as u32,
    )
}

