//! O3 ASJ ANALYSIS layer: the StrandOddsRatio (SOR) strand-bias filter.
//!
//! Faithful Rust port of `bench/asj_strand_bias.py`. The O3 ASJ *core* (calling the
//! allele-specific junctions themselves) already lives in
//! [`super::allele_specific_junctions`]; this module ports the analysis layer that runs
//! ON TOP of the shipped `asj_calls.tsv`: for every ASJ call it re-fetches the reads that
//! SPAN the junction, splits them by (junction-usage x strand) into a 2x2 table, and
//! computes the GATK StrandOddsRatio. A junction "used" only by reads from one strand is a
//! hallmark of an alignment artifact rather than a true splice choice (longcallR, Nat
//! Methods 2026, rejects allele-specific junctions with `SOR >= 2`).
//!
//! ## What is ported (Python = ground truth)
//!  * [`introns`] (`bench/asj_strand_bias.py:58`): CIGAR-derived intron chain — one
//!    `(rpos, rpos+len)` per `N` op, with `M/D/=/X` consuming reference and `I/S/H/P` not.
//!  * [`strand_table`] (`:70`): fetch every read spanning `(donor, acceptor)`, skip
//!    unmapped/secondary/supplementary/no-CIGAR, require SPAN
//!    (`reference_start <= donor && reference_end >= acceptor`), and tally
//!    `(r_fwd, r_rev, a_fwd, a_rev) = (used+, used-, notused+, notused-)` RAW.
//!  * [`sor`] (`:98`): GATK SOR with a `+1` pseudocount — a PURE float function, ported
//!    bit-for-bit (`f64::ln == math.log` on Linux libm, verified in prior ports).
//!  * [`fisher_strand_p`] (`:111`): the Fisher-exact strand-bias p (a NON-gate cross-check
//!    column), computed by REUSING [`super::allele_specific_junctions::fisher_exact_2x2`]
//!    (scipy two-sided convention; matches scipy to ~4e-13 — see the byte-parity test).
//!  * [`StrandBiasEngine::run`] / [`compute_row`](StrandBiasEngine::compute_row)
//!    (`main`, `:120`): per-row donor/acceptor normalisation (swap if `donor > acceptor`),
//!    the chrom-not-in-refs -> `NaN` branch, and `sor_pass = !sor.is_nan() && sor < SOR_KEEP`.
//!
//! ## The gate is exact; fisher is a tolerance-matched cross-check
//! `sor` / `sor_pass` are the ACTUAL gate and are asserted BIT-EXACT against the shipped
//! Python build. `fisher_strand_p` is an advisory cross-check only; the reused
//! `fisher_exact_2x2` uses a Lanczos `ln Γ` approximation (not libm), so it agrees with
//! scipy to ~1e-12 rather than bit-for-bit. This is disclosed and the parity test asserts
//! the tolerance relationship (never the raw bits) for fisher.
//!
//! Byte-parity is enforced against `testdata/asj_strand_bias_fixture.json` (generated by
//! `bench/gen_asj_strand_bias_fixture.py`, PYTHONHASHSEED=0, over the real `GGO_mm.bam`)
//! by the `#[test]` below, which re-fetches the live BAM and recomputes every column.

