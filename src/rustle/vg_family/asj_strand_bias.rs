/// CIGAR-derived intron chain (0-based reference coords of each `N` block) for an aligned
/// read. Faithful port of `bench/asj_strand_bias.py::introns`.
///
/// `rpos` starts at `reference_start` (0-based = `alignment_start - 1`). For each op:
/// `N`(Skip) appends `(rpos, rpos+len)` then advances `rpos`; `M/D/=/X`
/// (Match/Deletion/SequenceMatch/SequenceMismatch) advance `rpos`; `I/S/H/P`
/// (Insertion/SoftClip/HardClip/Pad) do NOT consume reference. A record with no
/// alignment start yields an empty chain (never reached for the mapped reads this scans).
pub fn introns(rb: &RecordBuf) -> Vec<(i64, i64)> {
    let ref_start = match rb.alignment_start() {
        Some(s) => s.get() as i64 - 1,
        None => return Vec::new(),
    };
    let mut out: Vec<(i64, i64)> = Vec::new();
    let mut rpos = ref_start;
    for op in rb.cigar().as_ref().iter() {
        let len = op.len() as i64;
        match op.kind() {
            Kind::Skip => {
                out.push((rpos, rpos + len)); // N: intron
                rpos += len;
            }
            Kind::Match | Kind::Deletion | Kind::SequenceMatch | Kind::SequenceMismatch => {
                rpos += len; // M/D/=/X consume reference
            }
            // I(Insertion) / S(SoftClip) / H(HardClip) / P(Pad): no reference consumed.
            Kind::Insertion | Kind::SoftClip | Kind::HardClip | Kind::Pad => {}
        }
    }
    out
}

