// sor  (bench/asj_strand_bias.py:98) — PURE float, bit-exact
// ===========================================================================

/// GATK StrandOddsRatio with a `+1` pseudocount on every cell. Faithful, bit-exact port of
/// `bench/asj_strand_bias.py::sor`:
/// ```text
/// rp,rm,ap,am = r_fwd+1, r_rev+1, a_fwd+1, a_rev+1
/// ratio     = (rp*am) / (ap*rm)
/// sym       = ratio + 1/ratio
/// ref_ratio = min(rp,rm) / max(rp,rm)
/// alt_ratio = min(ap,am) / max(ap,am)
/// SOR       = ln(sym) + ln(ref_ratio) - ln(alt_ratio)
/// ```
/// Every operation (`+`, `*`, `/`, `min`, `max`, `ln`) is a bit-exact IEEE-754 f64 op with
/// identical evaluation order to CPython, so the returned `f64` matches `math.log`-based
/// Python bit-for-bit (the gate depends on this).
pub fn sor(r_fwd: i64, r_rev: i64, a_fwd: i64, a_rev: i64) -> f64 {
    let rp = r_fwd as f64 + 1.0;
    let rm = r_rev as f64 + 1.0;
    let ap = a_fwd as f64 + 1.0;
    let am = a_rev as f64 + 1.0;
    let ratio = (rp * am) / (ap * rm);
    let sym = ratio + 1.0 / ratio;
    let ref_ratio = rp.min(rm) / rp.max(rm);
    let alt_ratio = ap.min(am) / ap.max(am);
    sym.ln() + ref_ratio.ln() - alt_ratio.ln()
}

