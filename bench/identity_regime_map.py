# ----------------------------------------------------------------------------- SEDEF segdup index (DN start +/- window)
def parse_dn(name):
    # DN_NC_073236.2_25270756_7 -> ("NC_073236.2", 25270756)
    body = name[3:] if name.startswith("DN_") else name
    chrom, start, _nex = body.rsplit("_", 2)
    return chrom, int(start)

sed_by_chr = defaultdict(list)   # chrom -> list of (start, end, pchrom, pstart, pend)
n_sed = 0
try:
    with open(SEDEF) as f:
        for line in f:
            if line.startswith("#"): continue
            p = line.rstrip("\n").split("\t")
            if len(p) < 22: continue
            try:
                ident = float(p[20])
            except ValueError:
                continue
            if ident < SEDEF_MIN_ID: continue
            c1, s1, e1 = p[0], int(p[1]), int(p[2])
            c2, s2, e2 = p[3], int(p[4]), int(p[5])
            sed_by_chr[c1].append((s1, e1, c2, s2, e2))
            sed_by_chr[c2].append((s2, e2, c1, s1, e1))
            n_sed += 1
except FileNotFoundError:
    pass
# sort each chrom list by interval start for pruning
for c in sed_by_chr:
    sed_by_chr[c].sort()
sed_starts = {c: [rec[0] for rec in lst] for c, lst in sed_by_chr.items()}

def sedef_link(dn_a, dn_b):
    """True iff a SEDEF segdup connects the two DN loci (both ends within WIN)."""
    try:
        ca, sa = parse_dn(dn_a); cb, sb = parse_dn(dn_b)
    except Exception:
        return False
    lst = sed_by_chr.get(ca)
    if not lst: return False
    lo_a, hi_a = sa - SEDEF_WIN, sa + SEDEF_WIN
    lo_b, hi_b = sb - SEDEF_WIN, sb + SEDEF_WIN
    starts = sed_starts[ca]
    # candidate records whose start < hi_a; prune by bisect, then test overlap on A and partner on B
    j = bisect.bisect_right(starts, hi_a)
    for k in range(j):
        s1, e1, pc, ps, pe = lst[k]
        if e1 < lo_a: continue            # A-end no overlap
        if pc != cb: continue
        if pe >= lo_b and ps <= hi_b:     # partner overlaps B window
            return True
    return False

# ----------------------------------------------------------------------------- classify one genuine-FP edge
def classify_genuine(r):
    """-> bucket in {cardinality, ep_oversplit, genuine_overmerge}, plus sedef bool."""
    col70 = int(r["colinear"])
    col60 = int(r.get("colinear_60") or 0)
    is_card = (r.get("gstm2") == "1" or r.get("mage") == "1"
               or r["gene_a"] in CARD_GENES or r["gene_b"] in CARD_GENES)
    sed = sedef_link(r["dn_a"], r["dn_b"])
    if is_card:
        return "cardinality", sed
    # structurally a real duplication: >=2 colinear high-id exons
    if col70 >= 2:
        return "ep_oversplit", sed
    # residual single-exon domain share
    return "genuine_overmerge", sed

