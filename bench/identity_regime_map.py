"""identity_regime_map.py  —  CHARACTERIZE stage (no wiring).

Two-regime hypothesis test.  Bins the catalog's cross-gene family EDGES (the
5571 multi-exon core-present direct E_r edges = the shipped oracle learn
population, `bench/colinear_multiexon_gate.tsv`) and the shipped E_p residual-FP
roster (`bench/family_level_pr_current.json :: residual_fp_roster`) by COPY
IDENTITY, on TWO axes:

  * core_recip     = whole-transcript reciprocal identity  (the FLOOR / O1 axis)
  * mean_matched_id= matched-exon (shared-SEGMENT) identity (the confusability
                     / O2 axis; read_confusability_boundary.json boundary ~0.99)

Per bin it reports (1) EDGE precision  real=(TP+truthbar) vs genuine-FP, and
(2) the FP COMPOSITION of the genuine-FP edges, into three buckets:

  CARDINALITY          near-identical over-counted copies (GSTM2/MAGE hub flags
                       + diploid-CN oracle expanded arrays)
  EP-OVERSPLIT-OF-DUP  >=2 colinear high-id exons  (structurally a real
                       duplication the PROTEIN truth E_p over-splits; SEDEF
                       segdup support reported as independent DNA corroboration)
  GENUINE-OVER-MERGE   colinear<=1 single-exon domain-share, not cardinality
                       (the true residual over-merge)

`precision_corrected` credits CARDINALITY + EP-OVERSPLIT as truth-artifacts
(real, mis-labelled FP by E_p) and leaves only GENUINE-OVER-MERGE as FP.

Deterministic: PYTHONHASHSEED=0, set/sorted only, no RNG.  RNA + genome-base +
E_p/DNA/SEDEF as validation only.  Writes bench/identity_regime_map.tsv.
"""
