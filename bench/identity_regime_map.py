def frac_overmerge_crossover(rows, thr=0.5):
    """Continuous identity where genuine-over-merge fraction of FP mass crosses thr (descending)."""
    xs = [(r["mid"], r["frac_overmerge"]) for r in sorted(rows, key=lambda r: r["mid"])
          if r["n_genuine"] > 0]
    for i in range(1, len(xs)):
        (x0, y0), (x1, y1) = xs[i - 1], xs[i]
        if (y0 - thr) * (y1 - thr) <= 0 and y0 != y1:
            return round(x0 + (y0 - thr) / (y0 - y1) * (x1 - x0), 4)
    return None

def handoff_saturation(rows, pmin=0.90, ommax=0.5, ngmin=5):
    """First core_recip bin (ascending) with corrected precision saturated >=pmin AND
    genuine-over-merge no longer dominating the FP mass (frac<ommax)."""
    for r in sorted(rows, key=lambda r: r["bin_lo"]):
        if r["n_genuine"] >= ngmin and r["precision_corrected"] >= pmin and r["frac_overmerge"] < ommax:
            return r
    return None

