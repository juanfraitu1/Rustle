def regime_ov_sedef(cr_lo, cr_hi):
    """DNA-backing transparency: of the ep_oversplit genuine-FP edges in a core_recip
    window, how many carry an independent SEDEF (WGAC>=0.90) segdup.  ep_oversplit is
    assigned on the STRUCTURAL colinear>=2 signal WITHOUT requiring a segdup, so the
    corrected-precision credit is DNA-VALIDATED only for the SEDEF-backed subset; the
    remainder is structural inference (SEDEF's 0.90 threshold cannot capture ancient/
    divergent dups, so this is a floor on real duplications, not proof of over-merge)."""
    ov = [r for r in EDGES if r["cls"] == "genuine" and r["_bucket"] == "ep_oversplit"
          and cr_lo <= r["_cr"] < cr_hi]
    sed = sum(1 for r in ov if r["_sed"])
    return len(ov), sed

def regime_fp(rows_lo, rows_hi_open):
    sub = [r for r in core_plot if rows_lo <= r["bin_lo"] < rows_hi_open]
    gen = sum(r["n_genuine"] for r in sub)
    om  = sum(r["g_overmerge"] for r in sub)
    ov  = sum(r["g_ep_oversplit"] for r in sub)
    cd  = sum(r["g_cardinality"] for r in sub)
    real = sum(r["n_real"] for r in sub); tot = real + gen
    n_ov, n_ov_sed = regime_ov_sedef(rows_lo, rows_hi_open)
    return dict(n_edges=tot, n_real=real, n_genuine_fp=gen,
                genuine_overmerge=om, ep_oversplit=ov, cardinality=cd,
                # genuine single-domain over-merge as a fraction of the FP MASS and of ALL edges
                frac_overmerge=round(om / gen, 4) if gen else 0.0,
                overmerge_frac_of_all_edges=round(om / tot, 4) if tot else 0.0,
                # DNA-backing split of the ep_oversplit credit (see regime_ov_sedef)
                ep_oversplit_dna_confirmed=n_ov_sed,
                ep_oversplit_structural_only=n_ov - n_ov_sed,
                ep_oversplit_sedef_frac=round(n_ov_sed / n_ov, 4) if n_ov else 0.0,
                precision_raw=round(real / tot, 4) if tot else 0.0,
                precision_corrected=round((real + cd + ov) / tot, 4) if tot else 0.0)
