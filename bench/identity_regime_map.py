def classify_block(entry):
    genes = entry["genes"]
    pf = entry.get("protein_families", {})
    gene2pf = {}
    for fam, gs in pf.items():
        for g in gs: gene2pf[g] = fam
    # cross-protein-family edges present in the gate substrate
    cross = []
    for i in range(len(genes)):
        for j in range(i+1, len(genes)):
            a, b = genes[i], genes[j]
            if gene2pf.get(a) == gene2pf.get(b): continue
            r = gate_pair.get(frozenset((a, b)))
            if r is not None: cross.append(r)
    max_col = max((int(r["colinear"]) for r in cross), default=-1)
    best_mm = max((fnum(r["mean_matched_id"]) for r in cross), default=0.0)
    best_cr = max((fnum(r["core_recip"]) for r in cross), default=0.0)
    # cardinality: explicit near-identical hub flag / diploid-CN expanded array, OR a
    # large block of near-identical copies (>=4 loci AND best matched-exon id >=0.95)
    card = any(r.get("gstm2")=="1" or r.get("mage")=="1"
               or r["gene_a"] in CARD_GENES or r["gene_b"] in CARD_GENES for r in cross) \
           or any(g in CARD_GENES for g in genes) \
           or (entry["distinct_loci"] >= 4 and best_mm >= 0.95)
    sed = any(r["_sed"] for r in cross)
    if card:
        verdict = "cardinality"
    elif max_col >= 2:
        verdict = "ep_oversplit"
    elif max_col <= 1 and max_col >= 0:
        verdict = "genuine_overmerge"
    else:
        verdict = "no_multiexon_edge"   # merged only via single-exon aln_frac, no direct multi-exon E_r edge
    return dict(block=entry["block_index"], genes=";".join(genes),
                n_loci=entry["distinct_loci"], n_prot=entry["n_protein_families"],
                n_cross_edges=len(cross), max_colinear=max_col,
                best_mean_matched_id=round(best_mm,4), best_core_recip=round(best_cr,4),
                sedef=int(sed), verdict=verdict)

ROSTER = sorted((classify_block(e) for e in roster), key=lambda d: d["block"])

