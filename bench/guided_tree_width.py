# ---------------- newick ----------------
def parse_newick(s):
    """Return (children, parent, length, label) dicts over integer node ids; leaves carry their name as label."""
    s = s.strip().rstrip(";")
    children, parent, length, label = {}, {}, {}, {}
    stack, cur, nid, i = [], None, 0, 0

    def new(p):
        nonlocal nid
        n = nid
        nid += 1
        children[n] = []
        parent[n] = p
        length[n] = 0.0
        label[n] = ""
        if p is not None:
            children[p].append(n)
        return n
    root = new(None)
    cur = root
    while i < len(s):
        c = s[i]
        if c == "(":
            child = new(cur)
            stack.append(cur)
            cur = child
            i += 1
        elif c == ",":
            p = stack[-1]
            cur = new(p)
            i += 1
        elif c == ")":
            cur = stack.pop()
            i += 1
        elif c == ":":
            j = i + 1
            while j < len(s) and s[j] not in ",()":
                j += 1
            length[cur] = float(s[i + 1:j])
            i = j
        else:
            j = i
            while j < len(s) and s[j] not in ",():":
                j += 1
            label[cur] = s[i:j]
            i = j
    return root, children, parent, length, label


def leaves_under(n, children, label, memo):
    if n in memo:
        return memo[n]
    out = {label[n]} if not children[n] else set().union(*(leaves_under(c, children, label, memo) for c in children[n]))
    memo[n] = out
    return out


def splits(tree):
    root, children, parent, length, label = tree
    memo = {}
    allleaves = leaves_under(root, children, label, memo)
    out = []
    for n in children:
        if not children[n] or parent[n] is None:
            continue
        sup = label[n].split("/")
        sh = float(sup[0]) if sup and sup[0] not in ("",) else float("nan")
        ufb = float(sup[1]) if len(sup) > 1 else float("nan")
        side = leaves_under(n, children, label, memo)
        if 1 < len(side) < len(allleaves) - 1:
            out.append((frozenset(side), sh, ufb))
    return out, allleaves


def midpoint_partition(tree):
    root, children, parent, length, label = tree
    adj = collections.defaultdict(list)
    for n, p in parent.items():
        if p is not None:
            adj[n].append((p, length[n]))
            adj[p].append((n, length[n]))
    leaves = [n for n in children if not children[n]]

    def farthest(src):
        dist, prev, stack = {src: 0.0}, {src: None}, [src]
        while stack:
            u = stack.pop()
            for v, w in adj[u]:
                if v not in dist:
                    dist[v], prev[v] = dist[u] + w, u
                    stack.append(v)
        far = max(leaves, key=lambda x: dist[x])
        return far, dist, prev
    a, _, _ = farthest(leaves[0])
    b, dist, prev = farthest(a)
    half = dist[b] / 2
    node = b
    while prev[node] is not None and dist[prev[node]] >= half:
        node = prev[node]
    u, v = node, prev[node]  # midpoint lies on edge (u, v) with dist[u] >= half > dist[v]
    # side containing u when edge (u, v) is cut
    seen, stack = {u}, [u]
    while stack:
        x = stack.pop()
        for y, _ in adj[x]:
            if y not in seen and not (x == u and y == v):
                seen.add(y)
                stack.append(y)
    side = {label[n] for n in seen if not children[n]}
    allleaves = {label[n] for n in leaves}
    return side, allleaves - side


def build_tree(tag, fasta):
    aln, trim = f"{TD}/{tag}.aln.fa", f"{TD}/{tag}.trim.fa"
    with open(aln, "w") as fh:
        subprocess.run(["mafft", "--retree", "2", "--thread", "4", fasta], stdout=fh, stderr=subprocess.DEVNULL, check=True)
    names, seqs, cur = [], [], None
    for line in open(aln):
        if line.startswith(">"):
            names.append(line[1:].strip())
            seqs.append([])
        else:
            seqs[-1].append(line.strip())
    seqs = ["".join(s).upper() for s in seqs]
    L = len(seqs[0])
    keep = [j for j in range(L) if sum(1 for s in seqs if s[j] == "-") <= 0.5 * len(seqs)]
    with open(trim, "w") as fh:
        for n, s in zip(names, seqs):
            fh.write(f">{n}\n{''.join(s[j] for j in keep)}\n")
    t0 = time.time()
    subprocess.run([IQTREE, "-s", trim, *MODEL, "-B", "1000", "-alrt", "1000", "-T", "4", "--seed", "1", "--prefix",
                    f"{TD}/{tag}", "-redo", "-quiet"], check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL,
                   timeout=600)
    model = next((l.split(":", 1)[1].strip() for l in open(f"{TD}/{tag}.iqtree") if l.startswith("Best-fit model")),
                 MODEL[-1])
    return parse_newick(open(f"{TD}/{tag}.treefile").read()), L, len(keep), time.time() - t0, model


def tree_scores(tree, fam, label_of):
    sp, allleaves = splits(tree)
    truth_leaves = {m for m in allleaves if label_of.get(m)}
    res = {}
    for gname, G in GROUPS[fam].items():
        present = {label_of[m] for m in truth_leaves} & G
        if len(present) < 2:
            res[gname] = ("absent", None, None)
            continue
        best = None
        for side, sh, ufb in sp:
            ts = {label_of[m] for m in side if m in truth_leaves}
            tc = {label_of[m] for m in (allleaves - side) if m in truth_leaves}
            if ts == present or tc == present:
                best = (sh, ufb)
        if best is None:
            res[gname] = ("no split", None, None)
        else:
            res[gname] = ("RECOVERED" if best[0] > 75 else "unsupported", best[0], best[1])
    positional = None
    if fam in POSITIONAL:
        P = POSITIONAL[fam]
        positional = False
        for side, sh, ufb in sp:
            ts = {label_of[m] for m in side if m in truth_leaves}
            tc = {label_of[m] for m in (allleaves - side) if m in truth_leaves}
            present = {label_of[m] for m in truth_leaves}
            if sh > 75 and ((ts == P & present) or (tc == P & present)) and ts and tc:
                positional = True
    a, b = midpoint_partition(tree)
    lab = {m: 0 for m in a} | {m: 1 for m in b}
    items = [(m, label_of[m]) for m in allleaves if label_of.get(m)]
    pred = [lab[m] for m, _ in items]
    true = [rec[r]["level1"] for _, r in items]
    ps, pp = pairwise(pred, true)
    br, bp, ex, nt = bipartite(pred, true)
    mid = ([sorted(label_of.get(m, m) for m in a), sorted(label_of.get(m, m) for m in b)])
    return res, positional, (ps, pp, br, bp, ex, nt), mid


